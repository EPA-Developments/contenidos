<h4>Frecuencia Monitoreo HbA1c</h4>
<ul>
<li><strong>Control estable, alcanzando metas:</strong> Cada 6 meses (2×/año mínimo)</li>
<li><strong>Terapia cambiada o NO alcanzando metas:</strong> Cada 3 meses (trimestral)</li>
<li><strong>Diabetes gestacional, tipo 1 lábil:</strong> Más frecuente según caso</li>
</ul>

<h4>Automonitoreo Glucosa Capilar (SMBG)</h4>

<p><strong>Indicaciones:</strong></p>
<ul>
<li><strong>Insulina (múltiples dosis o bomba):</strong> 6-10 pruebas/día (preprandial, 2h postprandial, bedtime, ocasional 3am)</li>
<li><strong>Insulina basal sola:</strong> 1-2 pruebas/día (ayunas, rotando otros momentos)</li>
<li><strong>Sin insulina, control estable:</strong> Menos frecuente (puede ser innecesario rutinario si HbA1c meta)</li>
<li><strong>Sin insulina, NO controlado:</strong> Episódico para identificar patrones (paired testing: pre/post comidas)</li>
<li><strong>Durante enfermedad:</strong> Más frecuente (riesgo hiperglucemia severa)</li>
</ul>

<p><strong>Limitaciones SMBG:</strong></p>
<ul>
<li>Instantánea puntual (no captura variabilidad)</li>
<li>Requiere adherencia paciente (doloroso, inconveniente)</li>
<li>Costo tiras reactivas</li>
</ul>

<h4>Monitoreo Continuo Glucosa (CGM) - Tecnología Transformadora</h4>

<p><strong>Tipos:</strong></p>
<ul>
<li><strong>CGM Tiempo Real (rtCGM):</strong> Dexcom G6/G7, Freestyle Libre 2/3 - alertas hipo/hiperglucemia tiempo real</li>
<li><strong>CGM Intermitente (iCGM/"Flash"):</strong> Freestyle Libre 1 - escaneo intermitente, sin alertas</li>
</ul>

<p><strong>Métricas CGM:</strong></p>
<ul>
<li><strong>Tiempo en Rango (TIR):</strong> % tiempo 70-180 mg/dL - meta >70%</li>
<li><strong>Tiempo por debajo rango (TBR):</strong> <70 mg/dL (<4%), <54 mg/dL (<1%)</li>
<li><strong>Tiempo sobre rango (TAR):</strong> >180 mg/dL (<25%), >250 mg/dL (<5%)</li>
<li><strong>Variabilidad glucémica:</strong> Coeficiente variación (CV) <36%</li>
<li><strong>Glucosa media estimada (GMI):</strong> Correlaciona HbA1c</li>
</ul>

<p><strong>Ventajas CGM:</strong></p>
<ul>
<li>Captura variabilidad glucémica (invisible en HbA1c/SMBG)</li>
<li>Detecta hipoglucemia asintomática (especialmente nocturna)</li>
<li>Reduce hipoglucemia severa 50-70% (estudios tipo 1)</li>
<li>Mejora HbA1c 0.3-0.5% vs SMBG (diabetes tipo 1 y tipo 2 insulina)</li>
<li>Insights patrones (respuesta alimentos, ejercicio, medicación timing)</li>
<li>Satisfacción paciente alta</li>
</ul>

<p><strong>Indicaciones CGM (expansión progresiva):</strong></p>
<ul>
<li>Diabetes tipo 1 (todos - estándar cuidado)</li>
<li>Diabetes tipo 2 insulina intensiva</li>
<li>Historia hipoglucemia severa/desapercibida</li>
<li>HbA1c >8.0% pese tratamiento</li>
<li>Embarazo con diabetes</li>
<li>Futuro: Probablemente todos diabéticos (costo disminuyendo)</li>
</ul>

<p><strong>Barrera principal:</strong> Costo ($150-300/mes), cobertura seguros expandiendo</p>
</div>

<h3>💊 Farmacoterapia Diabetes Tipo 2</h3>

<div class="t2d-pharmacotherapy">
<h4>Algoritmo Tratamiento (ADA/EASD 2023)</h4>

<p><strong>Principio fundamental:</strong> Enfoque centrado paciente, individualizado, considerando:</p>
<ul>
<li>Comorbilidades (ASCVD, IC, ERC)</li>
<li>Riesgo hipoglucemia</li>
<li>Impacto peso</li>
<li>Costo</li>
<li>Preferencias paciente</li>
</ul>

<h4>Primera Línea - TODOS los Pacientes</h4>

<div class="first-line">
<p><strong>1. Modificación Estilo Vida (fundamento)</strong></p>
<ul>
<li>Dieta, actividad física, pérdida peso, cesación tabaco</li>
<li>Educación diabetes (DSMES - Diabetes Self-Management Education and Support)</li>
<li>NUNCA discontinuar (permanente)</li>
</ul>

<p><strong>2. Metformina (si no contraindicada)</strong></p>
<ul>
<li><strong>Dosis:</strong> Iniciar 500-850 mg diarios con comida, titular gradualmente (500 mg/semana) hasta 2,000-2,550 mg/día (dividido BID-TID)</li>
<li><strong>Mecanismo:</strong> ↓ Gluconeogénesis hepática, mejora sensibilidad insulina periférica, ↓ absorción intestinal glucosa</li>
<li><strong>Eficacia:</strong> ↓ HbA1c 1.0-1.5%</li>
<li><strong>Ventajas:</strong>
  <ul>
    <li>Sin hipoglucemia (como monoterapia)</li>
    <li>Neutral/leve ↓ peso (-1-2 kg)</li>
    <li>Bajo costo ($4-20/mes genérico)</li>
    <li>Beneficio CV (UKPDS: ↓ 32% eventos CV diabéticos obesos)</li>
    <li>Experiencia décadas</li>
  </ul>
</li>
<li><strong>Efectos adversos:</strong>
  <ul>
    <li>GI (diarrea, náusea, malestar abdominal) 20-30% - generalmente transitorios, mejor tolerancia ER (extended-release)</li>
    <li>Déficit vitamina B12 (5-10% pacientes largo plazo) - monitorear, suplementar si necesario</li>
    <li>Acidosis láctica (rarísima <1:100,000 - mayoría casos ERC avanzada, hipoxia severa)</li>
  </ul>
</li>
<li><strong>Contraindicaciones:</strong>
  <ul>
    <li>eGFR <30 mL/min/1.73m² (reducir dosis eGFR 30-45)</li>
    <li>Acidosis metabólica aguda</li>
    <li>Insuficiencia hepática severa</li>
    <li>Insuficiencia cardíaca descompensada</li>
    <li>Hipoxia tisular (shock, sepsis, IAM, insuficiencia respiratoria)</li>
  </ul>
</li>
<li><strong>Notas:</strong> Suspender temporalmente cirugías mayores, estudios contraste iodado (reanudar 48h post si función renal estable)</li>
</ul>
</div>

