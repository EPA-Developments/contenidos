<h4>Insulina - Hormona Anabólica Central</h4>

<p><strong>Estructura:</strong> Péptido 51 aminoácidos (cadena A 21aa, cadena B 30aa, unidas puentes disulfuro)</p>

<p><strong>Síntesis:</strong> Células β islotes Langerhans → pre-proinsulina → proinsulina → insulina + péptido C</p>

<p><strong>Secreción:</strong></p>
<ul>
<li><strong>Basal:</strong> 0.5-1.0 U/hora (mantiene glucosa ayunas)</li>
<li><strong>Postprandial:</strong> 5-10× basal (pico 30-60 min post-ingesta)</li>
<li><strong>Secreción total:</strong> ~40-50 U/día adulto 70 kg</li>
<li><strong>Vida media:</strong> 5-8 minutos (clearance hepático 50%, renal 50%)</li>
</ul>

<p><strong>Mecanismo Acción:</strong></p>
<ol>
<li>Insulina se une receptor tirosina quinasa membrana celular</li>
<li>Autofosforilación receptor → cascada señalización intracelular</li>
<li>Vías principales:
  <ul>
    <li><strong>PI3K/AKT:</strong> Metabolismo glucosa/lípidos (GLUT4 translocación, síntesis glucógeno, lipogénesis)</li>
    <li><strong>MAPK:</strong> Crecimiento, proliferación celular</li>
  </ul>
</li>
</ol>

<p><strong>Efectos Metabólicos Insulina:</strong></p>

<div class="insulin-effects">
<h5>Metabolismo Carbohidratos:</h5>
<ul>
<li>↑ Captación glucosa (músculo, adiposo) vía GLUT4</li>
<li>↑ Glucólisis</li>
<li>↑ Glucogénesis (síntesis glucógeno)</li>
<li>↓ Gluconeogénesis hepática</li>
<li>↓ Glucogenólisis</li>
</ul>

<h5>Metabolismo Lípidos:</h5>
<ul>
<li>↑ Lipogénesis (síntesis ácidos grasos)</li>
<li>↑ Síntesis triglicéridos</li>
<li>↓ Lipólisis (movilización ácidos grasos desde adipocitos)</li>
<li>↓ Cetogénesis</li>
<li>↑ Actividad lipoproteína lipasa (LPL)</li>
</ul>

<h5>Metabolismo Proteínas:</h5>
<ul>
<li>↑ Síntesis proteica</li>
