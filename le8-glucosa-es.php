<div class="diagnostic-criteria">
<h4>📋 Criterios Diagnóstico Diabetes (ADA 2024)</h4>

<p><strong>Cualquiera de los siguientes (repetir para confirmar si asintomático):</strong></p>

<ol>
<li><strong>HbA1c ≥6.5%</strong> (método certificado NGSP, estandarizado DCCT)</li>
<li><strong>Glucosa ayunas ≥126 mg/dL</strong> (ayuno = sin ingesta calórica ≥8 horas)</li>
<li><strong>Glucosa 2h post-PTOG ≥200 mg/dL</strong> (prueba tolerancia oral glucosa - 75g)</li>
<li><strong>Glucosa aleatoria ≥200 mg/dL + síntomas hiperglucemia</strong> (poliuria, polidipsia, pérdida peso inexplicable)</li>
</ol>

<p><strong>Prediabetes (riesgo alto diabetes):</strong></p>
<ul>
<li>HbA1c 5.7-6.4%, O</li>
<li>Glucosa ayunas 100-125 mg/dL (IFG - Impaired Fasting Glucose), O</li>
<li>Glucosa 2h post-PTOG 140-199 mg/dL (IGT - Impaired Glucose Tolerance)</li>
</ul>

<p><strong>⚠️ Nota Importante:</strong> Prediabetes NO es "pre-enfermedad" - ya existe ↑ riesgo CV 10-20%, daño microvascular incipiente. Es VENTANA DE INTERVENCIÓN.</p>
