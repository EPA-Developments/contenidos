<li>↓ Proteólisis</li>
</ul>

<h5>Efectos Vasculares:</h5>
<ul>
<li>↑ Producción óxido nítrico (NO) endotelial → vasodilatación</li>
<li>↑ Captación aminoácidos endotelio</li>
