<h4>🚨 Crisis Diabetes Tipo 2 Pediátrica</h4>

<p><strong>Epidemiología alarmante:</strong></p>
<ul>
<li>Incidencia diabetes tipo 2 pediátrica ↑ 4.8%/año (2002-2012)</li>
<li>Obesidad infantil principal factor impulsor</li>
<li>Frecuentemente diagnóstico adolescencia temprana (pico 12-16 años)</li>
<li>Disparidades raciales marcadas: Nativos Americanos > Asiáticos/Isleños Pacífico > Afroamericanos > Hispanos >> Blancos</li>
<li>Prediabetes: 18% adolescentes (estimado), 25% adolescentes obesos</li>
</ul>

<p><strong>Consecuencias:</strong></p>
<ul>
<li>Progresión más rápida vs adultos (fallo células β acelerado)</li>
<li>Complicaciones microvasculares en juventud (retinopatía, nefropatía)</li>
<li>Enfermedad CV prematura (30s-40s)</li>
<li>Impacto psicosocial: Depresión, ansiedad, estigma</li>
<li>Opciones terapéuticas limitadas (pocos fármacos aprobados <18 años)</li>
</ul>
