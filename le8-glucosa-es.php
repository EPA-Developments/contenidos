<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>UKPDS (UK Prospective Diabetes Study) - Estudio Índice Diabetes Tipo 2</h4>
<p><strong>Diseño:</strong> RCT, 5,102 diabéticos tipo 2 recién diagnosticados, seguimiento 10 años (1977-1997)</p>
<p><strong>Intervenciones:</strong> Terapia intensiva (sulfonilurea/insulina, meta glucosa ayunas <108 mg/dL) vs convencional (dieta sola, meta <270 mg/dL)</p>
<p><strong>Resultados - Control Glucémico:</strong></p>
<ul>
<li>HbA1c: 7.0% (intensivo) vs 7.9% (convencional) - diferencia 0.9%</li>
<li><strong>↓ 25% complicaciones microvasculares</strong> (retinopatía, nefropatía, neuropatía)</li>
<li>↓ 16% IAM (P=0.052, marginalmente no significativo)</li>
<li><strong>Cada 1% ↓ HbA1c → 37% ↓ complicaciones microvasculares, 14% ↓ IAM</strong></li>
</ul>
<p><strong>Seguimiento post-estudio (10 años adicionales):</strong></p>
<ul>
<li><strong>"Legacy effect" (memoria metabólica):</strong> Beneficio inicial persistió pese convergencia HbA1c</li>
<li>↓ 24% complicaciones microvasculares (P<0.001)</li>
<li>↓ 15% IAM (P=0.01 - finalmente significativo)</li>
<li>↓ 13% mortalidad total (P=0.007)</li>
</ul>
<p><strong>Subgrupo metformina (sobrepeso):</strong></p>
<ul>
<li>↓ 32% eventos diabetes-relacionados</li>
<li>↓ 42% mortalidad diabetes-relacionada</li>
<li>↓ 36% mortalidad total</li>
<li>Único fármaco mostrar ↓ mortalidad → estableció metformina primera línea</li>
</ul>
<p><strong>Mensaje:</strong> Control glucémico intensivo reduce complicaciones micro y macrovasculares; beneficios persisten largo plazo incluso tras cese intervención intensiva.</p>
</div>
<div class="evidence-box">
<h4>ACCORD (Action to Control Cardiovascular Risk in Diabetes) - Controversia</h4>
<p><strong>Diseño:</strong> RCT, 10,251 diabéticos tipo 2 alto riesgo CV (historia ASCVD o múltiples factores riesgo), seguimiento 3.5 años (detenido temprano)</p>
<p><strong>Intervención:</strong> Terapia intensiva (meta HbA1c <6.0%) vs estándar (7.0-7.9%)</p>
<p><strong>HbA1c alcanzado:</strong> 6.4% (intensivo) vs 7.5% (estándar)</p>
<p><strong>Resultados (SORPRESA NEGATIVA):</strong></p>
<ul>
<li>Outcome primario (eventos CV mayores): Sin diferencia significativa (HR 0.90, P=0.16)</li>
<li><strong>↑ 22% mortalidad total</strong> en grupo intensivo (HR 1.22, P=0.04) - INESPERADO</li>
<li>↑ Hipoglucemia severa 3× grupo intensivo</li>
<li>↑ Ganancia peso +3.5 kg (intensivo) vs +0.4 kg (estándar)</li>
</ul>
<p><strong>Posibles explicaciones ↑ mortalidad:</strong></p>
<ul>
<li>Hipoglucemia severa frecuente (arritmias, eventos CV agudos)</li>
<li>Ganancia peso rápida</li>
<li>Población muy alto riesgo, larga duración diabetes (media 10 años)</li>
<li>Titulación muy rápida múltiples fármacos</li>
<li>Variabilidad glucémica (no solo nivel promedio)</li>
</ul>
<p><strong>Implicancia:</strong> Metas muy agresivas (<6.0%) NO apropiadas todos pacientes, especialmente alto riesgo CV/hipoglucemia. Individualización crítica.</p>
</div>
<div class="evidence-box">
<h4>ADVANCE (Action in Diabetes and Vascular Disease) - Contraste ACCORD</h4>
<p><strong>Diseño:</strong> RCT, 11,140 diabéticos tipo 2, seguimiento 5 años</p>
<p><strong>Intervención:</strong> Intensivo (meta HbA1c <6.5%) vs estándar (guías locales)</p>
<p><strong>HbA1c:</strong> 6.5% (intensivo) vs 7.3% (estándar)</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>↓ 10% eventos micro/macrovasculares combinados (P=0.01)</li>
<li>↓ 21% nefropatía (P=0.006) - BENEFICIO RENAL claro</li>
<li><strong>Sin ↑ mortalidad</strong> (a diferencia ACCORD)</li>
<li>Hipoglucemia severa 2.7% (intensivo) vs 1.5% (estándar) - menor que ACCORD</li>
</ul>
<p><strong>Diferencias vs ACCORD (por qué resultados divergentes):</strong></p>
<ul>
<li>Meta menos agresiva (6.5% vs 6.0%)</li>
<li>Titulación más gradual</li>
<li>Menor tasa hipoglucemia severa</li>
<li>Uso gliclazida MR (sulfonilurea menos hipoglucemiante)</li>
</ul>
<p><strong>Mensaje:</strong> Meta <6.5% segura y beneficiosa, especialmente beneficio renal.</p>
</div>
<div class="evidence-box">
<h4>LEADER (Liraglutide Effect and Action in Diabetes) - GLP-1 RA Beneficio CV</h4>
<p><strong>Diseño:</strong> RCT outcomes CV, 9,340 diabéticos tipo 2 alto riesgo CV, seguimiento 3.8 años</p>
<p><strong>Intervención:</strong> Liraglutida 1.8 mg SC diaria vs placebo (ambos grupos terapia estándar)</p>
<p><strong>Resultados:</strong></p>
<ul>
<li><strong>↓ 13% eventos CV mayores (3P-MACE)</strong>: Muerte CV, IAM no-fatal, stroke no-fatal (HR 0.87, P=0.01)</li>
<li>↓ 22% mortalidad CV (HR 0.78, P=0.007)</li>
<li>↓ 15% mortalidad total (HR 0.85, P=0.02)</li>
<li>↓ 22% nefropatía (nuevo/empeoramiento)</li>
<li>↓ HbA1c 0.4% más vs placebo</li>
<li>Pérdida peso -2.3 kg vs placebo</li>
</ul>
<p><strong>Impacto:</strong> Primer GLP-1 RA demostrar ↓ eventos CV y mortalidad → cambió algoritmos tratamiento DM2 alto riesgo CV</p>
</div>
<div class="evidence-box">
<h4>EMPA-REG OUTCOME - iSGLT2 Beneficio CV</h4>
<p><strong>Diseño:</strong> RCT outcomes CV, 7,020 diabéticos tipo 2 con ASCVD establecida, seguimiento 3.1 años</p>
<p><strong>Intervención:</strong> Empagliflozina 10/25 mg vs placebo</p>
<p><strong>Resultados (DRAMÁTICOS):</strong></p>
<ul>
<li><strong>↓ 14% eventos CV mayores</strong> (HR 0.86, P=0.04)</li>
<li><strong>↓ 38% mortalidad CV</strong> (HR 0.62, P<0.001) - REDUCCIÓN MAYOR que control glucémico solo explicaría</li>
<li><strong>↓ 35% hospitalización insuficiencia cardíaca</strong> (HR 0.65, P=0.002)</li>
<li>↓ 32% mortalidad total (HR 0.68, P<0.001)</li>
<li>Beneficio emergente RÁPIDO (separación curvas 3 meses) - sugiere mecanismos más allá glucemia</li>
</ul>
<p><strong>Mecanismos propuestos beneficio (más allá glucemia):</strong></p>
<ul>
<li>Diuresis osmótica → ↓ precarga</li>
<li>↓ Presión arterial 3-5 mmHg</li>
<li>Pérdida peso 2-3 kg</li>
<li>↓ Ácido úrico</li>
<li>Cambio metabolismo energético miocárdico (↑ cetones - combustible eficiente)</li>
<li>↓ Rigidez arterial</li>
<li>Efectos antiinflamatorios, antifibróticos</li>
</ul>
<p><strong>Impacto:</strong> Revolucionó tratamiento DM2 con ASCVD; expandió indicaciones iSGLT2 incluso sin diabetes (IC, ERC)</p>
</div>
