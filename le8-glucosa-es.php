      <h2 class="title" id="faqs">Preguntas Frecuentes - Glucosa</h2>
    </div>
    
    <h3>¿Por qué Life's Essential 8™ usa HbA1c en lugar de glucosa en ayunas?</h3>
    <p>HbA1c refleja control glucémico promedio 2-3 meses (vida media eritrocitos), proporcionando visión integral vs instantánea puntual glucosa ayunas. Ventajas críticas: (1) NO requiere ayuno - mayor conveniencia, elimina barrera screening, (2) Menos variabilidad día-a-día - no afectada estrés agudo, enfermedad reciente, ejercicio, (3) Predictor superior outcomes cardiovasculares, (4) Unifica diagnóstico y monitoreo - misma prueba ambos propósitos, (5) Métrica terapéutica universal - todos diabéticos familiarizados. Limitaciones: anemias/hemoglobinopatías (resultados inexactos), ligeramente más cara. En casos especiales (anemia severa, embarazo), glucosa ayunas preferible.</p>
    
    <h3>¿La prediabetes es realmente peligrosa o solo un "pre-enfermedad"?</h3>
    <p>Prediabetes NO es benigna - es estado enfermedad con consecuencias reales AHORA, no solo riesgo futuro. Datos: (1) ↑ Riesgo CV 10-20% vs glucemia normal (daño vascular ya iniciado), (2) Daño microvascular incipiente detectable (retinopatía temprana 8% prediabéticos), (3) Progresión diabetes 5-10%/año sin intervención (50% en 10 años), (4) 84 millones adultos EE.UU. con prediabetes (90% no saben). PERO: Prediabetes es REVERSIBLE - intervención estilo vida (DPP) reduce progresión diabetes 58%, metformina 31%. Mensaje: Prediabetes es ventana crítica intervención preventiva, NO etapa ignorable.</p>
    
    <h3>¿Puedo revertir diabetes tipo 2 con dieta/ejercicio?</h3>
    <p>Posible en casos selectos, especialmente diagnóstico reciente. Definición "remisión" (preferible "reversión"): HbA1c <6.5% sin medicaciones hipoglucemiantes ≥3 meses. Estudios: DiRECT trial - dieta muy baja calorías (825-850 kcal/día 12-20 semanas) → 46% remisión a 1 año (86% si pérdida peso ≥15 kg). Factores favorables: (1) Diabetes <6 años duración, (2) Pérdida peso sustancial (10-15%), (3) Sin dependencia insulina, (4) Función células β residual preservada. Mecanismo: ↓ Grasa ectópica (hígado, páncreas) → ↑ sensibilidad insulina, recuperación función células β. IMPORTANTE: Remisión ≠ curación - requiere mantenimiento peso, riesgo recurrencia si re-gana. Mayoría diabéticos NO logran remisión completa pero TODOS benefician control glucémico mejorado.</p>
    
    <h3>¿Qué tan bajo debería ser mi HbA1c? ¿Puede ser demasiado bajo?</h3>
    <p>Meta estándar <7.0% para mayoría diabéticos tipo 2, PERO individualizar. Metas más estrictas (<6.5%, incluso <6.0%) apropiadas SI: (1) Diagnóstico reciente, (2) Sin complicaciones, (3) Expectativa vida larga, (4) Alcanzable SIN hipoglucemia severa/frecuente. Metas más laxas (<8.0%) apropiadas SI: (1) Diabetes larga evolución (>10-15 años), (2) Complicaciones establecidas, (3) Comorbilidades múltiples, (4) Historia hipoglucemia severa, (5) Expectativa vida limitada, (6) Ancianos frágiles. ACCORD mostró: Meta <6.0% con terapia intensiva agresiva → ↑ 22% mortalidad (posibles causas: hipoglucemia severa frecuente, variabilidad glucémica, ganancia peso rápida). Balance clave: Beneficio microvascular (más estricto mejor) vs riesgo hipoglucemia/efectos adversos tratamiento.</p>
    
    <h3>¿Son los edulcorantes artificiales seguros para diabéticos?</h3>
    <p>Consenso actual: Seguros y útiles herramienta reducir azúcares/calorías. FDA aprobó: Sacarina, aspartamo, acesulfamo-K, sucralosa, neotamo, advantamo, stevia, monk fruit. NO elevan glucosa directamente (sin calorías/carbohidratos). PERO debates recientes: (1) Posible alteración microbioma intestinal (estudios animales, evidencia humana mixta), (2) Posible perpetuación preferencia sabores dulces, (3) Asociaciones epidemiológicas con peso/diabetes (pero confusión - personas alto riesgo más usan). Recomendación pragmática: Uso moderado preferible exceso azúcares añadidos, pero agua/bebidas no endulzadas óptimo. Stevia/monk fruit (naturales) no claramente superiores artificiales. Evitar exceso cualquier edulcorante.</p>
    
    <h3>¿La insulina causa que la diabetes empeore o me hace dependiente?</h3>
    <p>MITO común - realidad: Diabetes tipo 2 es enfermedad progresiva (deterioro continuo función células β ~4-5%/año), independiente tratamiento. Insulina NO acelera progresión, de hecho: (1) Reduce glucotoxicidad (hiperglucemia crónica daña células β remanentes), (2) Permite "descanso" células β (potencialmente preserva función residual), (3) Logra control glucémico cuando orales insuficientes. "Dependencia" insulina refleja progresión natural enfermedad, NO efecto insulina per se. Insulina NO es "fracaso" paciente/tratamiento - es herramienta efectiva control cuando otros agentes inadecuados. Diabetes tipo 1: Dependencia absoluta desde inicio (destrucción autoinmune células β). Diabetes tipo 2: Dependencia eventual muchos pacientes (pero no todos) - timing variable.</p>
    
    <h3>¿Debo preocuparme por hipoglucemia si no uso insulina/sulfonilureas?</h3>
    <p>Riesgo hipoglucemia clínicamente significativa (<70 mg/dL) MUY bajo con mayoría agentes modernos. Clases BAJO riesgo hipoglucemia: Metformina, iDPP-4, GLP-1 RA, iSGLT2, pioglitazona - mecanismo glucosa-dependiente o independiente secreción insulina. ALTO riesgo: Insulina, sulfonilureas (estimulan secreción insulina independiente glucosa), meglitinidas. Situaciones ↑ riesgo hipoglucemia incluso agentes "seguros": (1) Combinación con insulina/SU, (2) Enfermedad renal avanzada (↓ clearance fármacos/insulina), (3) Omisión comidas, (4) Ejercicio vigoroso sin ajuste, (5) Alcohol excesivo. Síntomas hipoglucemia: Temblor, sudoración, palpitaciones, hambre, confusión; severa: convulsiones, pérdida consciencia. Prevención: Educación, monitoreo glucosa, ajuste medicaciones ejercicio/comidas.</p>
    
    <h3>¿Qué tan efectivo es realmente el Diabetes Prevention Program? ¿Vale la pena el esfuerzo?</h3>
    <p>DPP es intervención MÁS efectiva prevención diabetes validada - evidencia clase A. Eficacia: 58% reducción incidencia diabetes vs placebo (NNT=7 para 3 años), beneficio sostenido 10 años (34% reducción persistente). Estilo vida DUPLICA eficacia vs metformina (31% reducción). Componentes clave: (1) Meta 7% pérdida peso, (2) 150 min/semana actividad física moderada, (3) Soporte conductual estructurado (case manager, 16 sesiones iniciales + mensual), (4) Herramientas tracking. ¿Vale esfuerzo? Análisis costo-beneficio: $1,100/QALY (altamente costo-efectivo). Beneficios más allá diabetes: ↓ Riesgo CV, mejora presión arterial/lípidos, calidad vida ↑. Desafío: Adherencia largo plazo - peso recupera parcialmente pero beneficio persiste. Programas comunitarios/online hacen accesible (CDC National DPP). Respuesta: SÍ, definitivamente vale esfuerzo si prediabetes.</p>
    
    <h3>¿Los GLP-1 agonistas (semaglutida, etc.) son seguros a largo plazo?</h3>
    <p>Evidencia actual apoya seguridad largo plazo con vigilancia apropiada. Estudios outcomes CV (LEADER, SUSTAIN-6, REWIND) - seguimiento 2-5 años sin señales seguridad alarmantes. Efectos adversos principales: (1) GI (náusea 20-40%, vómitos, diarrea) - generalmente transitorios, mejoran semanas/meses, titulación gradual ayuda, (2) Pancreatitis aguda - riesgo pequeño incrementado (0.1-0.2% vs 0.09% placebo) - suspender si pancreatitis, (3) Enfermedad vesícula biliar (colelitiasis/colecistitis) - asociado pérdida peso rápida, (4) Retinopatía diabética empeoramiento - observado SUSTAIN-6 (pacientes retinopatía establecida, mejora glucémica muy rápida), precaución mejora muy rápida HbA1c si retinopatía avanzada. Preocupaciones teóricas NO confirmadas: Cáncer tiroides medular (estudios animales, NO humanos - contraindicado historia personal/familiar), cáncer páncreas (NO evidencia causal). Embarazo: Suspender. Balance: Beneficios (↓ CV, pérdida peso, control glucémico) >> riesgos mayoría pacientes.</p>
    
    <h3>¿Necesito monitorear glucosa en casa si mi HbA1c está en meta?</h3>
    <p>Depende tratamiento y estabilidad. SI usa insulina (múltiples dosis/bomba): SMBG esencial 4-10 veces/día (titulación dosis, detección hipoglucemia). SI usa agentes alto riesgo hipoglucemia (sulfonilureas, meglitinidas): SMBG útil periódicamente, especialmente si síntomas. SI usa agentes bajo riesgo hipoglucemia (metformina, iDPP-4, GLP-1 RA, iSGLT2) Y HbA1c meta estable: SMBG rutinario frecuentemente innecesario - HbA1c trimestral/semestral suficiente. Excepciones incluso si estable: (1) Durante enfermedad (riesgo hiperglucemia severa), (2) Cambios medicación, (3) Cambios estilo vida significativos. Alternativa emergente: CGM (monitoreo continuo) - captura variabilidad invisible HbA1c, identifica hipoglucemia asintomática, insights patrones. Futuro probable: CGM accesible todos diabéticos (costo ↓). Consultar equipo diabetes para plan monitoreo personalizado.</p>
    
