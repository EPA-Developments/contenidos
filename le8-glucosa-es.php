<h4>Terapia Insulina</h4>

<p><strong>Indicaciones iniciar insulina:</strong></p>
<ul>
<li>HbA1c >10% (especialmente si síntomas hiperglucemia)</li>
<li>Glucosa >300 mg/dL</li>
<li>Cetosis/cetonuria</li>
<li>Fracaso terapia oral múltiple (HbA1c >meta pese 3 agentes orales)</li>
<li>Contraindicaciones otros agentes</li>
<li>Embarazo (insulina gold standard)</li>
<li>Enfermedad crítica, cirugía mayor</li>
</ul>

<p><strong>Esquemas insulina diabetes tipo 2:</strong></p>
<ol>
<li><strong>Basal sola</strong> (inicio frecuente):
  <ul>
    <li>Insulina NPH bedtime O glargina/detemir/degludec (análogos acción prolongada) 1×/día</li>
    <li>Continuar metformina + otros orales</li>
    <li>Titular dosis basado glucosa ayunas (meta 80-130 mg/dL)</li>
    <li>Inicio típico: 10 U o 0.1-0.2 U/kg/día</li>
  </ul>
</li>

<li><strong>Basal-Plus</strong> (si prandial elevado):
  <ul>
    <li>Insulina basal + 1-2 dosis rápida comidas principales</li>
  </ul>
</li>

<li><strong>Basal-Bolus</strong> (intensivo):
  <ul>
    <li>Insulina basal (glargina/detemir/degludec/NPH) + insulina rápida (lispro/aspart/glulisina) pre-cada comida</li>
    <li>Similar manejo tipo 1 (requiere educación extensiva, SMBG frecuente)</li>
  </ul>
</li>

<li><strong>Premezcladas</strong> (bifásica):
  <ul>
    <li>70/30 (70% NPH, 30% regular) o análogos (75/25, 70/30 lispro/aspart)</li>
    <li>BID típicamente</li>
    <li>Menos flexible, pero simplicidad (menos inyecciones)</li>
  </ul>
</li>
</ol>

<p><strong>⚠️ Riesgos insulina:</strong> Hipoglucemia, ganancia peso (3-5 kg promedio)</p>

<p><strong>Combinaciones efectivas:</strong></p>
<ul>
<li>Insulina + metformina (↓ dosis insulina, mejor peso)</li>
<li>Insulina basal + GLP-1 RA (sinergia, menos hipoglucemia, mejor peso) - productos combinados disponibles (iGlarLixi, IDegLira)</li>
<li>Insulina + iSGLT2 (↓ dosis insulina, pérdida peso)</li>
