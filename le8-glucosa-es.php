<h4>Factores Contribuyentes Resistencia Insulina</h4>

<div class="ir-contributors">
<h5>1. Obesidad (Especialmente Visceral) - FACTOR DOMINANTE</h5>
<ul>
<li><strong>Adiposidad visceral:</strong> Adipocitos hipertrofiados, inflamados</li>
<li><strong>Lipotoxicidad:</strong> Acumulación ectópica lípidos (músculo, hígado, páncreas)</li>
<li><strong>Adipocinas disfuncionales:</strong>
  <ul>
    <li>↑ Leptina (resistencia leptina desarrolla)</li>
    <li>↓ Adiponectina (↓ sensibilidad insulina)</li>
    <li>↑ Resistina, visfatina (pro-resistencia insulina)</li>
  </ul>
</li>
<li><strong>Ácidos grasos libres (FFA) elevados:</strong> Interfieren señalización insulina (ciclo Randle)</li>
<li><strong>Cada 10 kg adiposidad:</strong> ↑ 40% riesgo diabetes tipo 2</li>
</ul>

<h5>2. Inactividad Física / Sedentarismo</h5>
<ul>
<li>↓ Masa muscular (principal sitio disposición glucosa)</li>
<li>↓ Densidad mitocondrial muscular</li>
<li>↓ Captación glucosa independiente insulina (contracción muscular)</li>
<li>Efecto agudo ejercicio: ↑ Sensibilidad insulina 24-48h post-ejercicio</li>
</ul>

<h5>3. Dieta (Calidad y Cantidad)</h5>
<ul>
<li><strong>Exceso calórico crónico:</strong> Sobrecarga metabólica</li>
<li><strong>Alto índice glucémico/carga:</strong> Picos glucemia/insulina repetidos</li>
<li><strong>Grasas saturadas excesivas:</strong> Acumulación lípidos intramusculares</li>
<li><strong>Bajo fibra:</strong> Pérdida efectos beneficiosos fermentación colónica (ácidos grasos cadena corta)</li>
<li><strong>Bebidas azucaradas:</strong> Fructosa → hígado graso, resistencia insulina hepática</li>
</ul>

<h5>4. Genética</h5>
<ul>
<li>Heredabilidad diabetes tipo 2: 40-70%</li>
<li>>400 loci genéticos asociados (GWAS)</li>
<li>Genes clave: TCF7L2, PPARG, KCNJ11, IRS1, ADAMTS9</li>
<li>Variantes afectan: Secreción insulina (60%), sensibilidad insulina (20%), ambos (20%)</li>
<li>Etnicidad: Asiáticos, Hispanos, Afroamericanos, Nativos Americanos > riesgo vs Caucásicos</li>
</ul>

<h5>5. Inflamación Crónica</h5>
<ul>
<li>↑ TNF-α (interfiere IRS-1 fosforilación)</li>
<li>↑ IL-6, IL-1β</li>
<li>Activación NFkB, JNK (vías pro-inflamatorias)</li>
<li>Infiltración macrófagos tejido adiposo</li>
<li>Estado inflamatorio bajo grado → resistencia insulina</li>
</ul>

<h5>6. Otros Factores</h5>
<ul>
<li><strong>Privación sueño:</strong> ↓ Sensibilidad insulina 30-40% (una noche)</li>
<li><strong>Estrés crónico:</strong> ↑ Cortisol → hiperglucemia, resistencia insulina</li>
<li><strong>Edad:</strong> Sarcopenia, ↓ actividad física, adiposidad visceral</li>
<li><strong>Medicaciones:</strong> Corticosteroides, antipsicóticos atípicos, antirretrovirales</li>
<li><strong>Hígado graso no alcohólico (NAFLD):</strong> Fuertemente asociado, relación bidireccional</li>
<li><strong>Microbioma intestinal:</strong> Disbiosis asociada resistencia insulina (mecanismos emergentes)</li>
</ul>
</div>
</div>

<h3>💔 Consecuencias Cardiovasculares Hiperglucemia/Diabetes</h3>

<div class="cv-consequences-diabetes">
<h4>Magnitud del Problema</h4>

<p><strong>Diabetes = Equivalente Riesgo CV:</strong> Persona con diabetes sin IAM previo tiene mismo riesgo evento CV que persona sin diabetes CON IAM previo (estudio Haffner 1998 - concepto fundamental).</p>

<p><strong>Datos epidemiológicos:</strong></p>
<ul>
<li>↑ 2-4× riesgo enfermedad coronaria</li>
<li>↑ 2-3× riesgo stroke isquémico</li>
<li>↑ 2-4× riesgo insuficiencia cardíaca</li>
<li>↑ 2× riesgo enfermedad arterial periférica</li>
<li>Mortalidad CV: 65-80% muertes personas con diabetes</li>
<li>Eventos CV ocurren 10-15 años más temprano vs sin diabetes</li>
<li>Mujeres con diabetes pierden protección pre-menopáusica (ratio riesgo H:M se iguala)</li>
</ul>

<h4>Mecanismos Daño Cardiovascular</h4>

<div class="cv-damage-mechanisms">
<h5>🔥 Glucotoxicidad - Daño Directo Hiperglucemia</h5>

<p><strong>1. Productos Finales Glucación Avanzada (AGEs)</strong></p>
<ul>
<li>Glucosa + proteínas → productos glucación no-enzimáticos (base Schiff → Amadori → AGEs)</li>
<li>AGEs se acumulan: Colágeno vascular, elastina, LDL, proteínas matriz</li>
<li>Consecuencias:
  <ul>
    <li>↑ Rigidez arterial (crosslinking colágeno)</li>
    <li>Disfunción endotelial</li>
    <li>↑ Estrés oxidativo (vía RAGE - receptor AGE)</li>
    <li>↑ Inflamación (activación NFkB)</li>
    <li>↑ Permeabilidad vascular</li>
  </ul>
</li>
<li>HbA1c es AGE (refleja glucación hemoglobina - análogo proceso ocurriendo tejidos)</li>
</ul>

<p><strong>2. Estrés Oxidativo</strong></p>
<ul>
<li>Hiperglucemia → ↑ producción ROS (especies reactivas oxígeno) mitocondrial</li>
<li>↑ NADH/NAD+ ratio → sobrecarga cadena transporte electrones</li>
<li>Activación vías alternativas metabolismo glucosa:
  <ul>
    <li>Vía poliol (aldosa reductasa): Glucosa → sorbitol → fructosa (consume NADPH, ↓ glutatión)</li>
    <li>Vía hexosamina (glucosamina)</li>
    <li>PKC (proteína quinasa C) activación</li>
  </ul>
</li>
<li>ROS daña: DNA, lípidos (peroxidación), proteínas (oxidación)</li>
<li>↓ Biodisponibilidad óxido nítrico (NO) → disfunción endotelial</li>
</ul>

<p><strong>3. Disfunción Endotelial</strong></p>
<ul>
<li>↓ Producción/biodisponibilidad NO</li>
<li>↑ Endotelina-1 (vasoconstrictor)</li>
<li>↑ Moléculas adhesión (VCAM-1, ICAM-1)</li>
<li>↑ Permeabilidad a lipoproteínas</li>
<li>Estado protrombótico (↑ PAI-1, ↑ factor von Willebrand)</li>
<li>Vasodilatación deteriorada (flujo-mediada)</li>
</ul>

<h5>💊 Resistencia Insulina y Hiperinsulinemia</h5>
<ul>
<li><strong>Efectos directos insulina:</strong>
  <ul>
    <li>Mitogénica (proliferación células músculo liso vascular)</li>
    <li>↑ Actividad simpática</li>
    <li>↑ Reabsorción renal sodio (expansión volumen)</li>
    <li>Pro-inflamatoria (dosis altas)</li>
  </ul>
</li>
<li><strong>Resistencia selectiva:</strong> Vías metabólicas resistentes, pero vías mitogénicas/pro-inflamatorias preservadas → efectos adversos sin beneficios</li>
</ul>

<h5>🩸 Dislipidemia Aterogénica (Tríada Diabética)</h5>
<ul>
<li>↑ Triglicéridos (resistencia insulina → ↑ VLDL producción hepática)</li>
<li>↓ HDL-C (↑ catabolismo, transferencia lipídica)</li>
<li>LDL pequeñas-densas (más aterogénicas - oxidación fácil, penetración pared arterial)</li>
<li>↑ ApoB (↑ partículas aterogénicas)</li>
<li>LDL glucosilada (AGE-LDL) - captación aumentada macrófagos</li>
</ul>

<h5>🩺 Hipertensión</h5>
<ul>
<li>60-80% diabéticos tienen hipertensión</li>
<li>Mecanismos:
  <ul>
    <li>Hiperinsulinemia → ↑ reabsorción Na+, activación simpática</li>
    <li>Resistencia insulina → disfunción endotelial → ↓ vasodilatación</li>
    <li>Nefropatía diabética → HTA (relación bidireccional)</li>
    <li>↑ Rigidez arterial (AGEs, fibrosis)</li>
  </ul>
</li>
</ul>

<h5>🔥 Inflamación Sistémica</h5>
<ul>
<li>↑ PCR (2-3× vs sin diabetes)</li>
<li>↑ IL-6, TNF-α, IL-1β</li>
<li>Activación NFkB</li>
<li>Estado proinflamatorio crónico → aterogénesis acelerada</li>
</ul>

<h5>🩸 Estado Protrombótico</h5>
<ul>
<li>↑ PAI-1 (inhibidor activador plasminógeno) → ↓ fibrinólisis</li>
<li>↑ Fibrinógeno</li>
<li>↑ Factores coagulación (VII, VIII, von Willebrand)</li>
<li>↑ Agregación plaquetaria</li>
<li>Disfunción plaquetaria (↑ reactividad)</li>
</ul>

<h5>🫀 Miocardiopatía Diabética</h5>
<ul>
<li>Daño miocárdico independiente aterosclerosis coronaria</li>
<li>Mecanismos:
  <ul>
    <li>Fibrosis miocárdica (AGEs, metabolitos tóxicos)</li>
    <li>Disfunción mitocondrial cardiomiocitos</li>
    <li>Lipotoxicidad (acumulación lípidos intramiocárdicos)</li>
    <li>Microangiopatía coronaria</li>
  </ul>
</li>
<li>Manifestación: Disfunción diastólica precoz → insuficiencia cardíaca HFpEF</li>
</ul>

<h5>🧠 Neuropatía Autonómica Cardiovascular</h5>
<ul>
<li>Daño nervios autonómicos cardíacos</li>
<li>Consecuencias:
  <ul>
    <li>↓ Variabilidad frecuencia cardíaca (HRV) - predictor mortalidad</li>
    <li>Taquicardia reposo</li>
    <li>Intolerancia ortostática</li>
    <li>Isquemia silente (↓ dolor anginoso - "ángeles silenciosa")</li>
    <li>↑ Riesgo arritmias, muerte súbita</li>
  </ul>
</li>
</ul>
</div>
</div>

