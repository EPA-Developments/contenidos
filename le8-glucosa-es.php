<h1>Glucosa en Sangre: La Métrica #7 de Life's Essential 8™</h1>

<p>La <strong>glucosa en sangre</strong> es la séptima métrica esencial para salud cardiovascular. Life's Essential 8™ utiliza <strong>hemoglobina glucosilada (HbA1c)</strong> como métrica preferida sobre glucosa en ayunas, reflejando el control glucémico promedio durante 2-3 meses previos - una medición más integral y sin requisito de ayuno.</p>

<p>La <strong>diabetes es un equivalente de riesgo cardiovascular</strong>: personas con diabetes sin enfermedad CV previa tienen el mismo riesgo de eventos que personas sin diabetes pero con IAM previo. <strong>Cada 1% incremento en HbA1c aumenta 18% el riesgo cardiovascular</strong>. Con una prevalencia global de diabetes alcanzando <strong>10.5% (537 millones adultos en 2021)</strong> y proyectándose a 12.2% (783 millones) para 2045, el control glucémico es crítico para prevención cardiovascular.</p>

<h2 id="puntuacion">Sistema de Puntuación de Glucosa</h2>

<h3>★ Innovación: HbA1c como Métrica Preferida</h3>

<div class="innovation-highlight">
<p><strong>¿Por qué HbA1c en lugar de glucosa en ayunas?</strong></p>

<h4>Ventajas HbA1c:</h4>
<ul>
<li><strong>NO requiere ayuno:</strong> Mayor conveniencia, menos barreras screening</li>
<li><strong>Refleja control prolongado:</strong> Promedio glucémico 2-3 meses (vida media eritrocitos) vs instantánea puntual</li>
<li><strong>Menos variabilidad día-a-día:</strong> No afectada por estrés agudo, enfermedad, ejercicio reciente</li>
<li><strong>Predictor CV superior:</strong> Correlación más fuerte con outcomes cardiovasculares que glucosa ayunas</li>
<li><strong>Métrica terapéutica establecida:</strong> Usada universalmente monitoreo diabetes - pacientes familiarizados</li>
<li><strong>Unificación diagnóstico/monitoreo:</strong> Misma prueba sirve diagnóstico inicial y seguimiento</li>
</ul>

<h4>Limitaciones HbA1c (Reconocer):</h4>
<ul>
<li><strong>Anemias/hemoglobinopatías:</strong> Resultados inexactos (deficiencia Fe, hemólisis, talasemia, anemia células falciformes)</li>
<li><strong>Variación étnica:</strong> Africanos tienen HbA1c 0.3-0.4% más alta que caucásicos con misma glucemia promedio</li>
<li><strong>Embarazo:</strong> Cambios rápidos metabólicos - glucosa capilar preferida</li>
<li><strong>Cambios recientes:</strong> No detecta hiperglucemia de nueva aparición (últimas 2-3 semanas)</li>
<li><strong>Costo:</strong> Ligeramente más cara que glucosa ayunas (pero diferencia mínima)</li>
</ul>

