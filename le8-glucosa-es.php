<h3>⚠️ Resistencia a la Insulina - Patogénesis Diabetes Tipo 2</h3>

<div class="insulin-resistance">
<h4>Definición</h4>

<p><strong>Resistencia insulina:</strong> Respuesta biológica disminuida a concentraciones normales de insulina → requiere hiperinsulinemia compensatoria para mantener euglucemia.</p>

<h4>Progresión Natural: Resistencia Insulina → Prediabetes → Diabetes Tipo 2</h4>

<div class="progression-stages">
<h5>Etapa 1: Resistencia Insulina Compensada (Años-Décadas)</h5>
<ul>
<li><strong>Defecto primario:</strong> ↓ Sensibilidad insulina tejidos periféricos (músculo 40%, adiposo 30%, hígado 30%)</li>
<li><strong>Compensación:</strong> Células β páncreas ↑ secreción insulina (hiperinsulinemia compensatoria)</li>
<li><strong>Glucosa:</strong> NORMAL (euglucemia mantenida por hiperinsulinemia)</li>
<li><strong>Insulina ayunas:</strong> ELEVADA (>15-20 μU/mL)</li>
<li><strong>Clínica:</strong> Asintomático, frecuentemente obesidad visceral, acantosis nigricans</li>
<li><strong>Duración:</strong> Variable (10-30 años posible antes progresión)</li>
</ul>

<h5>Etapa 2: Prediabetes (Fallo Células β Inicial)</h5>
<ul>
<li><strong>Defecto dual:</strong> Resistencia insulina persistente + inicio disfunción células β (↓ primera fase secreción insulina)</li>
<li><strong>Glucosa ayunas:</strong> 100-125 mg/dL (IFG)</li>
<li><strong>Glucosa 2h post-carga:</strong> 140-199 mg/dL (IGT)</li>
<li><strong>HbA1c:</strong> 5.7-6.4%</li>
<li><strong>Insulina:</strong> Aún elevada pero respuesta inadecuada para demanda</li>
<li><strong>Riesgo progresión diabetes:</strong> 5-10%/año</li>
<li><strong>Consecuencias:</strong> ↑ Riesgo CV 10-20%, daño microvascular incipiente</li>
</ul>

<h5>Etapa 3: Diabetes Tipo 2 (Fallo Células β Significativo)</h5>
<ul>
<li><strong>Defecto dual severo:</strong> Resistencia insulina + fallo células β (~50% función perdida al diagnóstico)</li>
<li><strong>Glucosa ayunas:</strong> ≥126 mg/dL</li>
<li><strong>HbA1c:</strong> ≥6.5%</li>
<li><strong>Insulina:</strong> Variable (puede ser elevada temprano, pero inadecuada; eventualmente ↓)</li>
<li><strong>Clínica:</strong> Frecuentemente asintomático temprano; síntomas hiperglucemia si severa (poliuria, polidipsia, pérdida peso, visión borrosa)</li>
<li><strong>Complicaciones:</strong> Microvasculares (retinopatía, nefropatía, neuropatía), macrovasculares (CAD, stroke, PAD)</li>
<li><strong>Progresión:</strong> Continua deterioro función células β (~4-5%/año) → dependencia insulina eventual en muchos</li>
</ul>
</div>

