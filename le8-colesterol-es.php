      <h2 class="title" id="faqs">Preguntas Frecuentes - Colesterol</h2>
    </div>
    
    <h3>¿Por qué Life's Essential 8™ usa colesterol no-HDL en lugar de LDL-C?</h3>
    <p>Colesterol no-HDL captura TODAS las lipoproteínas aterogénicas (LDL + VLDL + IDL + Lp(a) + remanentes) en una sola medición simple: Colesterol Total - HDL-C. Ventajas: (1) No requiere ayuno, (2) Calculable directamente sin fórmulas, (3) Preciso incluso con triglicéridos altos (>400 mg/dL donde LDL-C calculado es inexacto), (4) Superior predicción riesgo CV que LDL-C aislado en múltiples estudios, (5) Refleja mejor carga total partículas aterogénicas. Meta no-HDL = Meta LDL-C + 30 mg/dL (ej: si meta LDL <100, entonces meta no-HDL <130).</p>
    
    <h3>¿Cuál es el nivel LDL-C "ideal"? ¿Puede ser demasiado bajo?</h3>
    <p>Evidencia genética y estudios PCSK9i demuestran que LDL-C <30-40 mg/dL es SEGURO - personas con mutaciones protectoras viven con LDL 30-50 mg/dL desde nacimiento sin efectos adversos. Relación LDL ↔ riesgo CV es log-lineal sin umbral inferior aparente - "lower is better". Preocupaciones teóricas (deterioro cognitivo, hemorragia intracraneal) NO confirmadas en RCTs grandes. Sin embargo, reducción LDL requiere INDICACIÓN (enfermedad CV, riesgo alto) - no tratamos número aislado sino riesgo global. Para prevención primaria bajo riesgo, objetivo <130 mg/dL razonable; prevención secundaria/alto riesgo: <70 o <55 mg/dL.</p>
    
    <h3>¿Las estatinas realmente causan diabetes? ¿Debería evitarlas por esto?</h3>
    <p>Sí, estatinas aumentan modestamente riesgo diabetes incidente: 9% riesgo relativo (~0.5-1% absoluto en 4 años), especialmente dosis altas y personas pre-diabéticas. PERO beneficio cardiovascular >> riesgo diabetes. Cálculo: Por cada diabetes causada, estatinas previenen 5-10 eventos CV mayores. Diabetes inducida-estatina típicamente leve, manejable con intervenciones estilo vida/metformina. Meta-análisis CTT: Incluso diabéticos benefician dramáticamente de estatinas (↓ 22% eventos CV por 39 mg/dL ↓ LDL). Recomendación: NO evitar estatinas por riesgo diabetes si indicación clara (ASCVD, alto riesgo) - beneficio neto altamente positivo.</p>
    
    <h3>¿Son los dolores musculares (mialgias) reales o placebo?</h3>
    <p>Complejo - ambos componentes. Mialgias reportadas 5-10% pacientes en práctica clínica, PERO en RCTs controlados placebo, diferencia estatina vs placebo solo 0.1-1% (efecto nocebo significativo). Estudios re-challenge: Cuando pacientes con "intolerancia estatina" son re-expuestos ciego, 60-90% toleran sin síntomas. Verdadera miopatía severa (CK >10× normal) rarísima (0.1%). Estrategias si mialgias: (1) Descartar otras causas (hipotiroidismo, vitamina D deficiencia), (2) "Wash-out" 2-4 semanas, re-introducir, (3) Cambiar estatina/reducir dosis, (4) Dosificación días alternos, (5) Si intolerancia múltiples estatinas, considerar ezetimibe, ácido bempedoico, PCSK9i.</p>
    
    <h3>¿El HDL "bueno" alto me protege si mi LDL es elevado?</h3>
    <p>Parcialmente, pero NO compensa LDL alto. HDL elevado asociado epidemiológicamente con menor riesgo CV (cada 1 mg/dL ↑ HDL → 2-3% ↓ riesgo), pero relación más compleja que LDL. Estudios genéticos/farmacológicos fallaron demostrar causalidad (elevar HDL farmacológicamente NO reduce eventos CV - ensayos CETP inhibidores fallaron). HDL puede ser disfuncional a pesar de niveles altos. Mensaje clave: Enfoque terapéutico es REDUCIR LDL/no-HDL, NO elevar HDL per se. HDL bajo (<40 H, <50 M) es marcador riesgo que intensifica indicación reducir LDL, pero HDL alto no es "licencia" ignorar LDL elevado.</p>
    
    <h3>¿Debo tomar estatina si tengo riesgo 10 años 7.5-10% (límite)?</h3>
    <p>Decisión individualizada - zona gris donde considerar "enhancers de riesgo": (1) Historia familiar enfermedad CV prematura, (2) LDL-C persistentemente ≥160 mg/dL, (3) Síndrome metabólico, (4) Enfermedad renal crónica, (5) Condiciones inflamatorias (artritis reumatoide), (6) Triglicéridos ≥175 mg/dL, (7) hsCRP ≥2 mg/L, (8) ApoB ≥130 mg/dL, (9) Lp(a) ≥50 mg/dL. Si ≥1 enhancer presente, estatina razonable. Considerar CAC score: si 0 → estatina frecuentemente NO (warranty period); si >100 → estatina SÍ. Discusión riesgo/beneficio con paciente esencial - preferencias importan. NNT prevención primaria riesgo intermedio ~100 (5 años) prevenir 1 evento CV.</p>
    
    <h3>¿Los suplementos (omega-3, niacina, ajo, levadura arroz rojo) funcionan?</h3>
    <p>Evidencia variable: <strong>Omega-3 prescripción (EPA puro, icosapent etil 4g):</strong> SÍ - ↓ 25% eventos CV en REDUCE-IT (pacientes TG 135-499 + ASCVD/diabetes). Omega-3 OTC dosis bajas: beneficio mínimo. <strong>Niacina:</strong> ↑ HDL-C potentemente pero NO reduce eventos CV en estudios modernos (AIM-HIGH, HPS2-THRIVE) - NO recomendada. <strong>Ajo:</strong> Reducción LDL-C modesta (~5%) evidencia débil, sin datos outcomes CV. <strong>Levadura arroz rojo:</strong> Contiene lovastatina natural - efectiva ↓ LDL 15-25% pero problemas: (1) Concentración variable, (2) Mismos efectos adversos estatinas, (3) No regulada FDA, (4) Sin evidencia outcomes CV. Preferir estatinas (dosis conocida, evidencia sólida, monitoreadas).</p>
    
    <h3>¿La dieta realmente puede reducir el colesterol significativamente?</h3>
    <p>SÍ, pero requiere cambios sustanciales. Dieta Portfolio (fibra soluble + esteroles vegetales + proteína soja + nueces) puede ↓ LDL-C 20-30%, comparable estatina moderada intensidad. Sin embargo, adherencia es desafío - más restrictiva que dieta típica. Cambios más factibles: (1) Reducir grasas saturadas <6% calorías → ↓ LDL 5-10%, (2) Eliminar grasas trans → ↓ LDL 5%, (3) Aumentar fibra soluble 10 g/día → ↓ LDL 5%, (4) Esteroles vegetales 2g/día (margarinas fortificadas) → ↓ LDL 6-10%. Dieta sola RARAMENTE suficiente si LDL muy elevado (≥190 - HF probable) o riesgo CV alto - farmacoterapia necesaria. Dieta + estatina = óptimo (efectos aditivos).</p>
    
    <h3>¿Debería preocuparme si mi hijo tiene colesterol alto?</h3>
    <p>Depende nivel y contexto. Screening recomendado 9-11 años (todos niños). <strong>LDL-C <110 mg/dL:</strong> Normal, tranquilizar. <strong>LDL 110-129 mg/dL:</strong> Límite - enfatizar dieta saludable, actividad física, repetir 1 año. <strong>LDL ≥130 mg/dL:</strong> Alto - investigar causas secundarias (obesidad, hipotiroidismo, diabetes), considerar screening familiar (hipercolesterolemia familiar - HF), intervención dietética intensiva, repetir 3 meses. <strong>LDL ≥160 mg/dL O ≥130 + historia familiar HF/CV prematura:</strong> Probable HF - referencia especialista, considerar test genético, estatinas ≥10 años. HF no tratada → aterosclerosis desde infancia, eventos CV jóvenes. Tratamiento temprano HF altera dramáticamente pronóstico.</p>
    
    <h3>¿Cuándo debería considerar terapias más allá de estatinas (ezetimibe, PCSK9i)?</h3>
    <p>Algoritmo escalonado: <strong>Paso 1:</strong> Estatina moderada-alta intensidad. <strong>Paso 2:</strong> Si NO alcanza meta LDL con estatina máxima tolerada → AÑADIR ezetimibe 10mg (↓ adicional 15-20% LDL, bien tolerado, costo razonable ~$20-50/mes). <strong>Paso 3:</strong> Si aún NO meta con estatina + ezetimibe → considerar: (a) <strong>Ácido bempedoico</strong> 180mg (↓ 15-25% LDL, útil intolerancia estatina, costo moderado), O (b) <strong>PCSK9 inhibidor</strong> (evolocumab/alirocumab) SI enfermedad CV establecida O HF + LDL ≥100 mg/dL (↓ 50-60% LDL, costoso $5,000-14,000/año, requiere aprobación seguro). <strong>Indicación urgente PCSK9i:</strong> Eventos CV recurrentes a pesar tratamiento óptimo, HF severa, riesgo muy alto. Inclisiran (siRNA dosificación 6 meses) alternativa emergente.</p>
    
