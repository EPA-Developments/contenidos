<h4>Metabolismo Lipoproteínas - Vías Clave</h4>

<div class="metabolism-pathways">
<h5>1. Vía Exógena (Lípidos Dietéticos)</h5>
<ol>
<li>Intestino absorbe grasas → empaqueta en <strong>quilomicrones</strong></li>
<li>Quilomicrones → circulación → <strong>lipoproteína lipasa (LPL)</strong> capilar hidroliza TG</li>
<li>Ácidos grasos liberados → músculo (energía) o tejido adiposo (almacenamiento)</li>
<li>Quilomicrones depletados TG → <strong>remanentes quilomicrón</strong> (aterogénicos)</li>
<li>Remanentes captados hígado vía receptor LDL/LRP</li>
</ol>

<h5>2. Vía Endógena (Lípidos Hepáticos)</h5>
<ol>
<li>Hígado sintetiza TG (exceso carbohidratos, ácidos grasos) → empaqueta en <strong>VLDL</strong></li>
<li>VLDL → circulación → LPL hidroliza TG (igual quilomicrones)</li>
<li>VLDL pierde TG → se vuelve más densa → <strong>IDL</strong></li>
<li>IDL opciones:
  <ul>
    <li>Captada hígado (ApoE) - 50%</li>
    <li>Lipasa hepática → <strong>LDL</strong> (rica colesterol) - 50%</li>
  </ul>
</li>
<li>LDL circula (vida media 2-3 días) → captada células vía <strong>receptor LDL (LDLR)</strong></li>
<li>LDLR regula homeostasis colesterol celular (feedback negativo síntesis colesterol endógeno)</li>
</ol>

<h5>3. Transporte Reverso Colesterol (HDL)</h5>
<ol>
<li>Hígado/intestino secretan <strong>HDL nacientes</strong> (discoidales, pobres colesterol)</li>
<li>HDL interactúa con células periféricas vía <strong>ABCA1</strong> (transportador ATP-binding cassette)</li>
<li>Células expulsan colesterol libre → HDL</li>
<li>Enzima <strong>LCAT</strong> (lecithin-cholesterol acyltransferase) esterifica colesterol → HDL madura (esférica)</li>
<li>HDL madura opciones:
  <ul>
    <li>Entrega colesterol hígado directamente (<strong>SR-B1</strong> receptor) → excreción biliar</li>
    <li>Intercambia ésteres colesterol por TG con VLDL/LDL (<strong>CETP</strong> - colesterol ester transfer protein)</li>
  </ul>
</li>
<li>HDL catabolizada (riñón) o recirculada</li>
</ol>
</div>
</div>

<h3>🔥 Aterogénesis: Proceso Paso a Paso</h3>

<div class="atherogenesis-process">
<p><strong>Aterosclerosis = enfermedad inflamatoria crónica de pared arterial iniciada y perpetuada por retención lipoproteínas aterogénicas</strong></p>

<h4>Fase 1: Retención Lipoproteínas (Evento Iniciador)</h4>

<ul>
<li><strong>Sitios predilectos:</strong> Bifurcaciones arteriales, curvaturas (estrés de cizallamiento turbulento)</li>
<li>LDL, VLDL, IDL, Lp(a), remanentes cruzan endotelio (intacto inicialmente)</li>
<li><strong>Retención:</strong> Partículas se unen proteoglicanos matriz subendotelial (interacciones electrostáticas)</li>
<li>ApoB en partícula → unión proteoglicano (especialmente partículas pequeñas-densas)</li>
<li>Concentración subendotelial LDL >> plasma</li>
</ul>

<h4>Fase 2: Modificación Lipoproteínas</h4>

<ul>
<li>LDL retenida sometida a <strong>modificaciones oxidativas</strong>:
  <ul>
    <li>Especies reactivas oxígeno (ROS) de células residentes</li>
    <li>Mieloperoxidasa (MPO) de neutrófilos</li>
    <li>Lipoxigenasas</li>
  </ul>
</li>
<li><strong>LDL oxidada (oxLDL):</strong>
  <ul>
    <li>No reconocida por receptor LDL (evade regulación feedback)</li>
    <li>Reconocida por receptores scavenger (SR-A, CD36) en macrófagos</li>
    <li>Citotóxica para células endoteliales</li>
    <li>Pro-inflamatoria (activa NFkB)</li>
  </ul>
</li>
</ul>

<h4>Fase 3: Disfunción Endotelial</h4>

<ul>
<li>OxLDL + otros factores (hipertensión, diabetes, tabaco) → <strong>activación endotelio</strong></li>
<li>↑ Expresión moléculas adhesión: <strong>VCAM-1, ICAM-1, selectinas</strong></li>
<li>↑ Secreción quimioquinas: <strong>MCP-1</strong> (monocyte chemoattractant protein-1)</li>
<li>↓ Óxido nítrico (NO) - pérdida propiedades antiadhesivas/vasodilatadoras</li>
<li>↑ Permeabilidad endotelial (brecha uniones estrechas)</li>
</ul>

<h4>Fase 4: Reclutamiento Leucocitos</h4>

<ul>
<li><strong>Monocitos</strong> circulantes adhieren endotelio (VCAM-1/ICAM-1)</li>
<li>Monocitos migran subendotelio (MCP-1 gradiente)</li>
<li>Monocitos → <strong>macrófagos</strong> (diferenciación M-CSF)</li>
<li>Macrófagos expresan receptores scavenger (SR-A, CD36)</li>
</ul>

<h4>Fase 5: Formación Células Espumosas (Foam Cells)</h4>

<ul>
<li>Macrófagos ingieren oxLDL vía receptores scavenger (captación NO regulada - sin feedback negativo)</li>
<li>Acumulación masiva ésteres colesterol → <strong>células espumosas</strong> (aspecto espumoso microscópico)</li>
<li>Células espumosas secretan citoquinas pro-inflamatorias: <strong>TNF-α, IL-1β, IL-6, IL-8</strong></li>
<li>Perpetúan inflamación, reclutan más monocitos</li>
<li>Lesión temprana: <strong>Estría grasa</strong> (fatty streak) - acumulación células espumosas subendotelial</li>
</ul>

<h4>Fase 6: Migración y Proliferación Células Músculo Liso (SMC)</h4>

<ul>
<li>Factores crecimiento (PDGF, TGF-β) de macrófagos/plaquetas estimulan SMC</li>
<li>SMC migran capa media → íntima</li>
<li>SMC proliferan y secretan <strong>matriz extracelular</strong> (colágeno, elastina, proteoglicanos)</li>
<li>Formación <strong>cápsula fibrosa</strong> sobre núcleo lipídico</li>
<li>Lesión intermedia: <strong>Placa fibroateroma</strong></li>
</ul>

<h4>Fase 7: Progresión y Complicaciones Placa</h4>

<p><strong>Placa estable:</strong></p>
<ul>
<li>Cápsula fibrosa gruesa (muchas SMC, matriz densa)</li>
<li>Núcleo lipídico pequeño-moderado</li>
<li>Inflamación baja</li>
<li>Puede producir estenosis significativa pero raramente ruptura</li>
</ul>

<p><strong>Placa vulnerable (de alto riesgo):</strong></p>
<ul>
<li>Cápsula fibrosa DELGADA (<65 μm)</li>
<li>Núcleo lipídico GRANDE (>40% volumen placa)</li>
<li>Inflamación ALTA (macrófagos abundantes en cápsula)</li>
<li>Pocas SMC</li>
<li>Neovascularización intraplaca (vasos frágiles → hemorragia)</li>
<li><strong>Alto riesgo ruptura/erosión</strong></li>
</ul>

<h4>Fase 8: Eventos Agudos</h4>

<p><strong>A. Ruptura Placa (60-70% síndromes coronarios agudos)</strong></p>
<ul>
<li>Metaloproteinasas matriz (MMPs) de macrófagos degradan colágeno cápsula</li>
<li>Estrés mecánico (PA, vasospasmo) → <strong>fisura/ruptura</strong> cápsula</li>
<li>Núcleo lipídico altamente trombogénico expuesto</li>
<li>Factor tisular, colágeno → activación cascada coagulación</li>
<li><strong>Formación trombo</strong> (plaquetas + fibrina)</li>
</ul>

<p><strong>B. Erosión Placa (30-35% síndromes agudos)</strong></p>
<ul>
<li>Pérdida endotelio sin ruptura cápsula fibrosa</li>
<li>Matriz subendotelial (colágeno) expuesta</li>
<li>Adhesión plaquetaria, formación trombo</li>
<li>Más frecuente mujeres, fumadores, diabetes</li>
</ul>

<p><strong>Consecuencias trombosis:</strong></p>
<ul>
<li><strong>Oclusión completa:</strong> IAM con elevación ST (STEMI), stroke isquémico</li>
<li><strong>Oclusión parcial:</strong> IAM sin elevación ST (NSTEMI), angina inestable</li>
<li><strong>Embolización distal:</strong> Infartos pequeños, isquemia transitoria</li>
<li><strong>Organización trombo:</strong> Crecimiento rápido placa, estenosis crónica</li>
</ul>
</div>

<h3>💊 Papel Central LDL-C en Aterogénesis</h3>

<div class="ldl-centrality">
<h4>Evidencia Causalidad LDL → Aterosclerosis</h4>

<p><strong>Criterios causalidad de Bradford Hill satisfechos:</strong></p>

<ol>
<li><strong>Fuerza asociación:</strong> Relación dosis-respuesta log-lineal LDL-C ↔ riesgo CV (sin umbral inferior aparente)</li>
<li><strong>Consistencia:</strong> Reproducible en múltiples poblaciones, etnias, geografías</li>
<li><strong>Especificidad:</strong> LDL elevado asociado específicamente con aterosclerosis (no otras enfermedades)</li>
<li><strong>Temporalidad:</strong> Exposición LDL precede eventos CV por décadas</li>
<li><strong>Gradiente biológico:</strong> Mayor exposición acumulativa (LDL × años) → mayor riesgo</li>
<li><strong>Plausibilidad:</strong> Mecanismos moleculares retención/oxidación/inflamación bien caracterizados</li>
<li><strong>Coherencia:</strong> Hallazgos compatibles con modelos animales, estudios genéticos, ensayos intervención</li>
<li><strong>Experimento:</strong> <strong>Reducción LDL (estatinas, ezetimibe, PCSK9i) reduce eventos CV proporcionalmente</strong></li>
<li><strong>Analogía:</strong> Otras lipoproteínas ApoB (VLDL, Lp(a)) también aterogénicas</li>
</ol>

<h4>Estudios Genéticos Mendelianos (Naturaleza)</h4>

<p><strong>Hipercolesterolemia Familiar (HF):</strong></p>
<ul>
<li>Mutaciones LDLR, APOB, PCSK9 (gain-of-function) → ↑↑ LDL-C desde nacimiento</li>
<li>HF heterocigota (LDL-C 190-400 mg/dL): Riesgo CV 13× vs población general</li>
<li>HF homocigota (LDL-C 400-1,000 mg/dL): IAM infancia/adolescencia sin tratamiento</li>
<li><strong>Demostración inequívoca:</strong> LDL-C elevado crónico → aterosclerosis acelerada</li>
</ul>

<p><strong>Variantes Genéticas Protectoras:</strong></p>
<ul>
<li>Mutaciones PCSK9 (loss-of-function) → ↓ LDL-C 15-28% desde nacimiento</li>
<li>↓ 88% riesgo enfermedad coronaria a lo largo de la vida</li>
<li>Personas con LDL-C genéticamente bajo (40-60 mg/dL) viven más, sin efectos adversos</li>
</ul>

<p><strong>Meta-análisis Randomización Mendeliana (2016):</strong></p>
<ul>
<li>50+ estudios, >300,000 participantes</li>
<li><strong>Hallazgo:</strong> Cada 39 mg/dL (1 mmol/L) ↓ LDL-C → 54% ↓ riesgo CV si exposición vitalicia</li>
<li>Comparación: Misma reducción LDL con estatinas (corto plazo) → solo 22% ↓ riesgo</li>
<li><strong>Implicación:</strong> Duración exposición LDL importa tanto como magnitud - beneficio acumulativo</li>
</ul>
</div>

