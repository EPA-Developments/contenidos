<h1>Colesterol (Lípidos): La Métrica #6 de Life's Essential 8™</h1>

<p>El <strong>colesterol (lípidos sanguíneos)</strong> es la sexta métrica esencial para salud cardiovascular. Life's Essential 8™ introduce un <strong>cambio paradigmático importante</strong>: la métrica preferida ya NO es el colesterol total, sino el <strong>colesterol no-HDL</strong>, que captura todas las partículas aterogénicas (LDL + VLDL + IDL + lipoproteína(a) + remanentes) en una sola medición.</p>

<p>La evidencia es inequívoca: <strong>cada reducción de 39 mg/dL (1 mmol/L) en colesterol LDL reduce 22% el riesgo de eventos cardiovasculares</strong>. La aterosclerosis es fundamentalmente una <strong>enfermedad de retención de lipoproteínas aterogénicas</strong> en la pared arterial - proceso que comienza en la infancia/adolescencia y progresa silenciosamente durante décadas antes de manifestarse clínicamente.</p>

<h2 id="puntuacion">Sistema de Puntuación de Colesterol</h2>

<h3>★ Innovación: Colesterol No-HDL como Métrica Preferida</h3>

<div class="innovation-highlight">
<p><strong>¿Por qué colesterol no-HDL en lugar de LDL-C?</strong></p>

<h4>Ventajas Colesterol No-HDL:</h4>
<ul>
<li><strong>Captura TODAS partículas aterogénicas:</strong> LDL + VLDL + IDL + Lp(a) + remanentes</li>
<li><strong>No requiere ayuno:</strong> Estable postprandial (LDL-C cambia con alimentos)</li>
<li><strong>Calculable directamente:</strong> No-HDL = Colesterol Total - HDL-C (simple, precisa)</li>
<li><strong>Superior predicción riesgo:</strong> Mejor que LDL-C aislado en múltiples estudios</li>
<li><strong>Útil hipertrigliceridemia:</strong> LDL-C calculado (Friedewald) impreciso si TG >400 mg/dL; no-HDL no afectado</li>
<li><strong>Refleja carga partículas:</strong> Personas con partículas LDL pequeñas-densas (más aterogénicas) tienen no-HDL elevado vs LDL-C normal</li>
</ul>

<h4>Cálculo Colesterol No-HDL:</h4>
<div class="calculation-box">
<p><strong>Colesterol No-HDL = Colesterol Total - HDL-C</strong></p>

<p><strong>Ejemplo:</strong></p>
<ul>
<li>Colesterol Total: 200 mg/dL</li>
<li>HDL-C: 50 mg/dL</li>
<li>No-HDL = 200 - 50 = <strong>150 mg/dL</strong></li>
</ul>

<p><strong>Meta general:</strong> <130 mg/dL (óptimo <100 mg/dL prevención primaria agresiva)</p>
</div>

<p><strong>Relación con LDL-C:</strong> Meta no-HDL = Meta LDL-C + 30 mg/dL</p>
<ul>
<li>Si meta LDL-C <70 mg/dL → Meta no-HDL <100 mg/dL</li>
<li>Si meta LDL-C <100 mg/dL → Meta no-HDL <130 mg/dL</li>
<li>Si meta LDL-C <130 mg/dL → Meta no-HDL <160 mg/dL</li>
</ul>
</div>

