<h4>⚠️ Hipercolesterolemia Familiar (HF) Pediátrica</h4>

<p><strong>Prevalencia:</strong> 1:250 nacimientos (heterocigota), 1:300,000 (homocigota)</p>

<p><strong>Criterios diagnóstico HF (niños):</strong></p>
<ul>
<li>LDL-C ≥160 mg/dL (sin factores secundarios)</li>
<li>O LDL-C ≥130 mg/dL + historia familiar HF o enfermedad CV prematura</li>
<li>Confirmación: Test genético (mutación LDLR, APOB, PCSK9)</li>
</ul>

<p><strong>Consecuencias HF no tratada:</strong></p>
<ul>
<li>Aterosclerosis comienza infancia</li>
<li>Hombres HF heterocigota: 50% eventos CV antes 50 años (sin tratamiento)</li>
<li>Mujeres HF heterocigota: 30% eventos CV antes 60 años</li>
<li>HF homocigota: IAM infancia/adolescencia si no tratamiento agresivo</li>
</ul>

<p><strong>Tratamiento HF pediátrica:</strong></p>
<ul>
<li>Dieta bajo colesterol/grasas saturadas (TODA la familia)</li>
<li>Estatinas: Iniciar ≥10 años (seguras, bien toleradas largo plazo)</li>
<li>Meta LDL-C: <130 mg/dL (idealmente <100 mg/dL)</li>
<li>HF homocigota: Aféresis LDL, inhibidores PCSK9 desde temprana edad</li>
</ul>
