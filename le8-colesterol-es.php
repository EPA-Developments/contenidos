<h4>Tratamiento Hipertrigliceridemia</h4>

<p><strong>TG 150-499 mg/dL (Sin riesgo pancreatitis inmediato):</strong></p>

<ol>
<li><strong>Intervenciones estilo vida (PRIORITARIO):</strong>
  <ul>
    <li>Pérdida peso si sobrepeso (5-10% → ↓ TG 20-30%)</li>
    <li>↓ Alcohol (abstinencia si TG >300 mg/dL)</li>
    <li>↓ Carbohidratos simples/azúcares añadidos</li>
    <li>↑ Actividad física</li>
    <li>Optimizar control glucémico diabéticos</li>
  </ul>
</li>

<li><strong>Estatina (si riesgo CV elevado):</strong>
  <ul>
    <li>Objetivo primario ↓ LDL-C</li>
    <li>Beneficio TG secundario (↓ 10-30%)</li>
  </ul>
</li>

<li><strong>Considerar omega-3 prescripción (EPA):</strong>
  <ul>
    <li><strong>Icosapent etil (Vascepa):</strong> 4 g/día (EPA puro)
      <ul>
        <li>REDUCE-IT trial: ↓ 25% eventos CV (pacientes TG 135-499, LDL controlado estatina)</li>
        <li>Indicación: TG 150-499 + enfermedad CV o diabetes + ≥2 factores riesgo</li>
      </ul>
    </li>
    <li>Omega-3 mixtos (EPA+DHA) dosis altas (2-4 g/día): ↓ TG 20-50% pero sin beneficio CV demostrado</li>
  </ul>
</li>

<li><strong>Fibratos (si TG persiste elevado >200 mg/dL):</strong>
  <ul>
    <li><strong>Fenofibrato:</strong> 48-145 mg/día
      <ul>
        <li>↓ TG 30-50%</li>
        <li>↑ HDL-C 10-25%</li>
        <li>Leve ↑ LDL-C posible (especialmente si TG muy altos)</li>
      </ul>
    </li>
    <li>Combinación fenofibrato + estatina: Segura (evitar gemfibrozil+estatina - alto riesgo miopatía)</li>
    <li>Evidencia CV fibratos: Modesta/mixta
      <ul>
        <li>ACCORD-Lipid: Sin beneficio adicional fenofibrato+estatina vs estatina sola (población general)</li>
        <li>Sub-análisis: Beneficio en hipertrigliceridemia + HDL bajo (↓ 27% eventos CV)</li>
      </ul>
    </li>
  </ul>
</li>
</ol>

<p><strong>TG ≥500 mg/dL (Riesgo Pancreatitis - URGENTE):</strong></p>

<ol>
<li><strong>Objetivo primario: ↓ TG <500 mg/dL para prevenir pancreatitis</strong></li>

<li><strong>Intervenciones agresivas inmediatas:</strong>
  <ul>
    <li>Dieta muy baja grasa (<15% calorías, <20-30 g/día)</li>
    <li>Abstinencia alcohol completa</li>
    <li>Suspender medicaciones contribuyentes si posible</li>
    <li>Optimizar control glucémico agresivamente (insulina si necesario)</li>
  </ul>
</li>

<li><strong>Farmacoterapia combinada:</strong>
  <ul>
    <li>Fenofibrato 145 mg/día</li>
    <li>+ Omega-3 prescripción 4 g/día</li>
    <li>± Estatina (iniciar tras ↓ TG <500 mg/dL)</li>
  </ul>
</li>

<li><strong>TG ≥1,000 mg/dL:</strong>
  <ul>
    <li>Hospitalización considerar (especialmente si síntomas abdominales)</li>
    <li>NPO temporal si pancreatitis</li>
    <li>Plasmaféresis casos refractarios extremos</li>
  </ul>
</li>

<li><strong>Investigar causas genéticas:</strong>
  <ul>
    <li>Hipertrigliceridemia familiar</li>
    <li>Déficit lipoproteína lipasa (LPL)</li>
    <li>Déficit ApoCII</li>
    <li>Referencia especialista lípidos/genética</li>
  </ul>
</li>
</ol>
