<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>4S (Scandinavian Simvastatin Survival Study) - Estudio Índice Estatinas</h4>
<p><strong>Diseño:</strong> RCT, 4,444 pacientes angina o IAM previo, LDL-C 188-309 mg/dL, seguimiento 5.4 años</p>
<p><strong>Intervención:</strong> Simvastatina 20-40 mg vs placebo</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>↓ LDL-C 35% (simvastatina) vs 1% (placebo)</li>
<li><strong>↓ 30% mortalidad total</strong> (HR 0.70, P=0.0003) - PRIMER estudio estatina mostrar ↓ mortalidad</li>
<li>↓ 42% mortalidad coronaria</li>
<li>↓ 34% eventos coronarios mayores</li>
<li>↓ 37% revascularización</li>
<li>NNT=30 (5 años) prevenir 1 muerte</li>
</ul>
<p><strong>Impacto:</strong> Estableció beneficio mortalidad estatinas prevención secundaria, catalizó adopción masiva</p>
</div>

<div class="evidence-box">
<h4>WOSCOPS (West of Scotland Coronary Prevention Study) - Prevención Primaria</h4>
<p><strong>Diseño:</strong> RCT, 6,595 hombres 45-64 años sin IAM previo, LDL-C 155-232 mg/dL, seguimiento 4.9 años</p>
<p><strong>Intervención:</strong> Pravastatina 40 mg vs placebo</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>↓ LDL-C 26%</li>
<li>↓ 31% eventos coronarios (IAM no-fatal + muerte coronaria)</li>
<li>↓ 32% IAM no-fatal</li>
<li>↓ 22% mortalidad total (P=0.051, marginalmente no significativo)</li>
<li>NNT=111 (5 años) prevenir 1 evento coronario</li>
</ul>
<p><strong>Impacto:</strong> Extendió evidencia estatinas a prevención primaria hombres alto riesgo</p>
</div>

<div class="evidence-box">
<h4>Heart Protection Study (HPS) - Población Amplia</h4>
<p><strong>Diseño:</strong> RCT, 20,536 adultos 40-80 años con enfermedad CV, diabetes o hipertensión, seguimiento 5 años</p>
<p><strong>Intervención:</strong> Simvastatina 40 mg vs placebo</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>↓ LDL-C 39 mg/dL (48 → 88 mg/dL)</li>
<li>↓ 24% eventos vasculares mayores (eventos coronarios, stroke, revascularización)</li>
<li>↓ 27% eventos coronarios</li>
<li>↓ 25% stroke</li>
<li>↓ 13% mortalidad total (marginalmente significativo)</li>
<li><strong>Beneficio independiente LDL-C basal:</strong> Incluso pacientes LDL <100 mg/dL beneficiaron</li>
<li>Beneficio consistente en diabéticos SIN enfermedad CV previa (estableció diabetes como equivalente riesgo CV)</li>
</ul>
<p><strong>Impacto:</strong> Expandió indicaciones estatinas a diabéticos prevención primaria, demostró beneficio independiente nivel LDL basal</p>
</div>

<div class="evidence-box">
<h4>JUPITER - PCR Elevada, LDL Normal</h4>
<p><strong>Diseño:</strong> RCT, 17,802 adultos sin enfermedad CV, LDL-C <130 mg/dL PERO hsCRP ≥2 mg/L, seguimiento 1.9 años (detenido temprano por beneficio)</p>
<p><strong>Intervención:</strong> Rosuvastatina 20 mg vs placebo</p>
<p><strong>Razón:</strong> Evaluar si estatinas benefician personas LDL "normal" pero inflamación elevada</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>↓ LDL-C 50% (55 → 108 mg/dL)</li>
<li>↓ hsCRP 37%</li>
<li><strong>↓ 44% eventos CV mayores</strong> (IAM, stroke, revascularización, muerte CV)</li>
<li>↓ 54% IAM</li>
<li>↓ 48% stroke</li>
<li>↓ 20% mortalidad total</li>
<li>NNT=25 (2 años) prevenir 1 evento CV</li>
</ul>
<p><strong>Controversia:</strong> Sponsorship industria, detención temprana, costo-efectividad debatido</p>
<p><strong>Impacto:</strong> Influyó guías hacia estatinas prevención primaria riesgo intermedio (especialmente si hsCRP elevada), aunque implementación variable</p>
</div>

<div class="evidence-box">
<h4>IMPROVE-IT - Valor Ezetimibe Adición</h4>
<p><strong>Diseño:</strong> RCT, 18,144 pacientes síndrome coronario agudo reciente, LDL-C 50-100 mg/dL (ya en simvastatina), seguimiento 7 años</p>
<p><strong>Intervención:</strong> Simvastatina 40 mg + ezetimibe 10 mg vs simvastatina sola</p>
<p><strong>Razón:</strong> ¿Reducción LDL adicional (más allá estatina) con fármaco no-estatina beneficia?</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>LDL-C: 54 mg/dL (combo) vs 70 mg/dL (mono)</li>
<li>↓ 6.4% eventos CV (HR 0.936, P=0.016) - modesto pero significativo</li>
<li>Beneficio mayor en diabéticos, edad >75, enfermedad multivaso</li>
<li>NNT=50 (7 años) prevenir 1 evento CV</li>
</ul>
<p><strong>Impacto:</strong> Validó principio "lower is better" LDL-C independiente método reducción (no solo estatinas)</p>
</div>
<div class="evidence-box">
<h4>FOURIER - Inhibidores PCSK9 Reducción CV</h4>
<p><strong>Diseño:</strong> RCT, 27,564 pacientes ASCVD estable, LDL-C ≥70 mg/dL (mayoría en estatina alta intensidad), seguimiento 2.2 años</p>
<p><strong>Intervención:</strong> Evolocumab SC cada 2 semanas vs placebo</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>LDL-C: 30 mg/dL (evolocumab) vs 92 mg/dL (placebo) - LDL más bajo alcanzado estudio gran escala</li>
<li>↓ 15% eventos CV mayores (HR 0.85, P<0.001)</li>
<li>↓ 27% IAM</li>
<li>↓ 21% stroke</li>
<li>↓ 22% revascularización coronaria</li>
<li>Beneficio emergente ~12 meses, acelerándose con tiempo</li>
<li><strong>Sin ↑ eventos adversos serios</strong> (incluyendo sin deterioro cognitivo pese LDL <20 mg/dL)</li>
<li>No mortalidad total (insuficientemente potenciado para este endpoint)</li>
</ul>
<p><strong>Implicación:</strong> LDL <30 mg/dL seguro y efectivo; validó PCSK9i como terapia adicional efectiva</p>
</div>
<div class="evidence-box">
<h4>Meta-análisis CTT Collaboration - Síntesis Evidencia Estatinas</h4>
<p><strong>Análisis:</strong> 26 RCTs estatinas, 170,000 participantes, seguimiento promedio 5 años</p>
<p><strong>Hallazgos Clave:</strong></p>
<ul>
<li><strong>Cada 39 mg/dL (1 mmol/L) ↓ LDL-C:</strong>
  <ul>
    <li>↓ 22% eventos CV mayores (RR 0.78, IC95% 0.76-0.80)</li>
    <li>↓ 21% mortalidad coronaria</li>
    <li>↓ 17% stroke isquémico</li>
    <li>↓ 10% mortalidad total</li>
    <li>↓ 24% revascularización</li>
  </ul>
</li>
<li>Beneficio proporcional <strong>independiente</strong> de:
  <ul>
    <li>LDL-C basal (beneficio incluso LDL <100 mg/dL)</li>
    <li>Tipo estatina</li>
    <li>Edad, sexo</li>
    <li>Prevención primaria vs secundaria (magnitud absoluta difiere, proporcional similar)</li>
  </ul>
</li>
<li><strong>No umbral inferior:</strong> Relación log-lineal LDL ↔ riesgo CV sin plateau</li>
<li><strong>Seguridad:</strong> ↑ Diabetes 9% (0.5% absoluto), ↑ miopatía 0.5/1,000 pte-años, sin otros efectos serios</li>
</ul>
<p><strong>Conclusión:</strong> Evidencia inequívoca beneficio estatinas, justifica tratamiento intensivo</p>
