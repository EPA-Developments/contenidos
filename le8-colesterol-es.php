<h4>Ezetimibe (Inhibidor Absorción Colesterol) - SEGUNDA LÍNEA/TERAPIA COMBINADA</h4>

<p><strong>Mecanismo:</strong> Inhibe NPC1L1 (transportador colesterol intestinal) → ↓ absorción colesterol dietético y biliar 50% → ↓ entrega colesterol hepático → ↑ LDLR expresión</p>

<p><strong>Eficacia:</strong></p>
<ul>
<li>Monoterapia: ↓ LDL-C 15-20%</li>
<li>Combinación con estatina: ↓ LDL-C adicional 15-20% (efecto aditivo)</li>
<li>Ej: Estatina moderada (↓ 35%) + ezetimibe (↓ 18%) = ↓ 50% total</li>
</ul>

<p><strong>Evidencia Clínica:</strong></p>
<ul>
<li><strong>IMPROVE-IT (2014):</strong> 18,144 pacientes post-síndrome coronario agudo
  <ul>
    <li>Simvastatina 40mg + ezetimibe 10mg vs simvastatina sola</li>
    <li>LDL-C: 54 mg/dL (combo) vs 70 mg/dL (mono)</li>
    <li>↓ 6.4% eventos CV (HR 0.936, P=0.016) - modesto pero significativo</li>
    <li>NNT=50 (7 años) prevenir 1 evento CV</li>
  </ul>
</li>
</ul>

<p><strong>Indicaciones:</strong></p>
<ul>
<li>Adicionar a estatina si NO alcanza meta LDL-C con estatina máxima tolerada</li>
<li>Monoterapia si intolerancia estatina absoluta (menos común)</li>
<li>Primera adición antes de considerar PCSK9 inhibidores (costo)</li>
</ul>

<p><strong>Efectos Adversos:</strong> Muy bien tolerado, efectos adversos mínimos (similar placebo)</p>

<p><strong>Dosis:</strong> Ezetimibe 10 mg diario (única dosis)</p>

<h4>Inhibidores PCSK9 (Anticuerpos Monoclonales) - TERCERA LÍNEA</h4>

<p><strong>Mecanismo:</strong> PCSK9 (Proprotein Convertase Subtilisin/Kexin type 9) normalmente degrada receptores LDL. Inhibidores PCSK9 (anticuerpos monoclonales) bloquean PCSK9 → ↑ reciclaje LDLR → ↑ clearance LDL dramático</p>

<p><strong>Agentes disponibles:</strong></p>
<ul>
<li><strong>Evolocumab (Repatha):</strong> 140 mg SC cada 2 semanas O 420 mg SC mensual</li>
<li><strong>Alirocumab (Praluent):</strong> 75-150 mg SC cada 2 semanas</li>
</ul>

<p><strong>Eficacia:</strong></p>
<ul>
<li>↓ LDL-C <strong>50-60%</strong> adicional (sobre estatina+ezetimibe)</li>
<li>Puede alcanzar LDL-C <30 mg/dL</li>
<li>También ↓ Lp(a) 25-30% (único fármaco con efecto significativo)</li>
</ul>

<p><strong>Evidencia Clínica:</strong></p>
<ul>
<li><strong>FOURIER (2017) - Evolocumab:</strong> 27,564 pacientes ASCVD establecida
  <ul>
    <li>LDL-C basal 92 mg/dL (ya en estatina) → 30 mg/dL con evolocumab</li>
    <li>↓ 15% eventos CV mayores (HR 0.85, P<0.001)</li>
    <li>↓ 20% IAM, ↓ 27% stroke</li>
    <li>Beneficio emergente 1 año, mayor con tiempo</li>
  </ul>
</li>
<li><strong>ODYSSEY Outcomes (2018) - Alirocumab:</strong> 18,924 pacientes post-síndrome coronario agudo reciente
  <ul>
    <li>LDL-C 87 mg/dL → 48 mg/dL</li>
    <li>↓ 15% eventos CV (HR 0.85, P<0.001)</li>
    <li>↓ 15% mortalidad total (HR 0.85, P=0.026) - ÚNICO estudio lípidos mostrar ↓ mortalidad total</li>
  </ul>
</li>
</ul>

<p><strong>Indicaciones (Guías):</strong></p>
<ul>
<li><strong>Prevención secundaria:</strong> ASCVD + LDL-C ≥70 mg/dL pese estatina máxima + ezetimibe</li>
<li><strong>Prevención primaria:</strong> HF heterocigota + LDL-C ≥100 mg/dL pese tratamiento máximo</li>
<li><strong>HF homocigota:</strong> Independiente nivel LDL (combinación con otros tratamientos)</li>
</ul>

<p><strong>Barrera Principal: COSTO</strong></p>
<ul>
<li>$5,000-14,000/año (antes descuentos/copay assistance)</li>
<li>Cobertura seguros mejoró post-estudios outcomes, pero aún restrictiva</li>
<li>Requiere step therapy (fracaso estatina+ezetimibe primero)</li>
</ul>

<p><strong>Efectos Adversos:</strong></p>
<ul>
<li>Muy bien tolerados</li>
<li>Reacciones sitio inyección (3-5%)</li>
<li>Mialgias similares placebo</li>
<li>Preocupación teórica deterioro cognitivo con LDL muy bajo - NO confirmada estudios</li>
</ul>

<h4>Ácido Bempedoico (Inhibidor ATP Citrato Liasa) - NUEVA OPCIÓN</h4>

<p><strong>Mecanismo:</strong> Inhibe ATP citrato liasa (upstream HMG-CoA reductasa en vía síntesis colesterol) - SOLO en hígado (no músculo, por eso menos mialgias)</p>

<p><strong>Eficacia:</strong> ↓ LDL-C 15-25% (monoterapia o adición a estatina)</p>

<p><strong>Evidencia:</strong></p>
<ul>
<li><strong>CLEAR Outcomes (2023):</strong> 13,970 pacientes intolerancia estatina, prevención primaria/secundaria
  <ul>
    <li>↓ 13% eventos CV (HR 0.87, P=0.004)</li>
    <li>↓ 23% IAM, ↓ 19% revascularización</li>
    <li>Primer estudio gran escala en pacientes intolerancia estatina</li>
  </ul>
</li>
</ul>

<p><strong>Indicaciones:</strong></p>
<ul>
<li>Intolerancia estatina (mialgias) - alternativa bien tolerada</li>
<li>Adición a estatina si no alcanza meta (antes PCSK9i por costo)</li>
</ul>

<p><strong>Dosis:</strong> 180 mg diario</p>

<p><strong>Efectos Adversos:</strong></p>
<ul>
<li>Hiperuricemia (↑ ácido úrico, ↑ riesgo gota) - monitorear</li>
<li>↑ Ligera creatinina (reversible, sin daño renal real)</li>
<li>Ruptura tendón (raro, <1%)</li>
<li>Menos mialgias que estatinas (ventaja clave)</li>
</ul>

<h4>Inclisiran (siRNA PCSK9) - TERAPIA MÁS RECIENTE</h4>

<p><strong>Mecanismo:</strong> RNA interferencia pequeño (siRNA) silencia gen PCSK9 en hepatocitos → ↓ producción proteína PCSK9 → ↑ LDLR</p>

<p><strong>Ventaja única: Dosificación**</strong></p>
<ul>
<li>284 mg SC inicial</li>
<li>Segunda dosis 3 meses</li>
<li>Luego <strong>cada 6 meses</strong> (vs PCSK9i cada 2-4 semanas)</li>
<li>Mejora adherencia dramáticamente</li>
</ul>

<p><strong>Eficacia:</strong> ↓ LDL-C 50% sostenido</p>

<p><strong>Evidencia:</strong></p>
<ul>
<li><strong>ORION-10, ORION-11:</strong> ↓ LDL-C 52-54% a 18 meses</li>
<li>Estudios outcomes CV en curso (ORION-4 - resultados pendientes)</li>
</ul>

<p><strong>Costo:</strong> Similar PCSK9i (~$6,500/año)</p>

<h4>Resinas Secuestradoras Ácidos Biliares - USO LIMITADO</h4>

<p><strong>Mecanismo:</strong> Unen ácidos biliares intestino → excreción fecal → hígado convierte colesterol en ácidos biliares → ↓ colesterol hepático → ↑ LDLR</p>

<p><strong>Agentes:</strong> Colestiramina, colestipol, colesevelam</p>

<p><strong>Eficacia:</strong> ↓ LDL-C 15-30% (dosis-dependiente)</p>

<p><strong>Limitaciones:</strong></p>
<ul>
<li>Efectos GI severos (constipación, flatulencia, náusea) - adherencia pobre</li>
<li>↑ Triglicéridos (contraindicado si TG >300 mg/dL)</li>
<li>Interfiere absorción múltiples fármacos (tomar otros medicamentos 1h antes o 4h después)</li>
<li>Múltiples dosis diarias necesarias</li>
</ul>

<p><strong>Uso actual:</strong> Raramente - reservado para intolerancia todas otras opciones, o niños/embarazo (seguridad establecida)</p>
</div>

