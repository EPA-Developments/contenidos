<li>Síndrome metabólico</li>
<li>Enfermedad renal crónica (eGFR 15-59)</li>
<li>Condiciones específicas: Preeclampsia, menopausia prematura, artritis reumatoide, VIH</li>
<li>Etnias alto riesgo: Surasiáticos</li>
<li>Triglicéridos persistentemente ≥175 mg/dL</li>
<li>hsCRP ≥2.0 mg/L</li>
<li>ApoB ≥130 mg/dL</li>
<li>Lp(a) ≥50 mg/dL</li>
