            <p>Yes, ATTR-CM can be hereditary due to genetic mutations affecting the transthyretin protein.</p>
            <h3>What is the role of medication in managing ATTR-CM?</h3>
            <p>Medications help manage ATTR-CM by stabilizing transthyretin, reducing amyloid deposits, and improving heart function.</p>
