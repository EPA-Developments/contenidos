            <h3>What is Transthyretin Amyloidosis (ATTR-CM)?</h3>
            <p>Transthyretin Amyloidosis (ATTR-CM) is a rare and progressive condition where abnormal protein build-up affects the heart's function.</p>
            <h3>What causes Transthyretin Amyloidosis?</h3>
            <p>Transthyretin Amyloidosis is caused by the buildup of abnormal protein deposits in tissues and organs, leading to damage and dysfunction.</p>
            <h3>How is ATTR-CM diagnosed?</h3>
            <p>Doctors diagnose ATTR-CM through imaging tests like echocardiograms, cardiac MRI, and biopsy to detect abnormal protein deposits.</p>
            <h3>What are the symptoms of ATTR-CM?</h3>
            <p>Symptoms of ATTR-CM include shortness of breath, fatigue, heart palpitations, swelling in legs, dizziness, and fainting episodes.</p>
