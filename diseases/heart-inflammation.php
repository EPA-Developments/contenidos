            <h3>How does heart inflammation affect heart function?</h3>
            <p>Heart inflammation impairs heart function by causing swelling, stiffness, and potential damage to the heart muscle, impacting its ability to pump blood efficiently.</p>
            <h3>What are the long-term effects of heart inflammation?</h3>
            <p>Long-term effects of heart inflammation can include heart failure, arrhythmias, and increased risk of cardiovascular events. Regular monitoring is crucial.</p>
