            <p>Common treatments for heart inflammation include anti-inflammatory medications, rest, lifestyle changes, and in severe cases, surgery.</p>
            <h3>Can heart inflammation cause arrhythmias?</h3>
            <p>Yes, heart inflammation can cause arrhythmias. Inflammation disrupts the heart's electrical system, leading to irregular heartbeats.</p>
            <h3>How is heart inflammation diagnosed?</h3>
            <p>Doctors diagnose heart inflammation through tests like blood tests, imaging studies, and heart biopsies to assess inflammation levels accurately.</p>
