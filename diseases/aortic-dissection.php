            <p>Aortic dissection is commonly caused by high blood pressure and weakened aortic walls, leading to a tear in the inner layer of the aorta.</p>
            <h3>Can an aortic dissection cause sudden death?</h3>
            <p>Yes, an aortic dissection can lead to sudden death due to severe internal bleeding or organ damage if not promptly treated.</p>
            <h3>How is an aortic dissection diagnosed?</h3>
            <p>Aortic dissection is diagnosed using imaging tests like CT scans or MRIs to visualize the tear in the aorta and determine its extent and location.</p>
            <h3>Is surgery always needed for an aortic dissection?</h3>
            <p>Surgery is often necessary for aortic dissection, especially in cases of complications or when the dissection involves the ascending aorta.</p>
