            <h3>What are the common causes of pericarditis?</h3>
            <p>Common causes of pericarditis include viral infections, autoimmune disorders, heart attack, trauma, cancer, and certain medications.</p>
            <h3>How is pericarditis diagnosed?</h3>
            <p>Doctors diagnose pericarditis through a physical exam, medical history review, blood tests, imaging (like echocardiogram), and sometimes a pericardial biopsy.</p>
            <h3>Can pericarditis cause chest pain?</h3>
            <p>Yes, pericarditis can cause chest pain due to inflammation of the pericardium surrounding the heart.</p>
            <h3>Is pericarditis always caused by an infection?</h3>
            <p>Pericarditis is not always caused by an infection; it can also be triggered by autoimmune conditions, heart attacks, or trauma.</p>
            <h3>What are the treatment options for pericarditis?</h3>
            <p>Treatment for pericarditis includes NSAIDs, colchicine, corticosteroids, and in severe cases, pericardiocentesis or pericardial window surgery.</p>
            <h3>How long does pericarditis typically last?</h3>
            <p>Pericarditis typically lasts for a few weeks to a few months, depending on the underlying cause and treatment effectiveness.</p>
            <h3>Can pericarditis lead to complications like cardiac tamponade?</h3>
            <p>Yes, pericarditis can lead to complications such as cardiac tamponade due to inflammation and fluid buildup around the heart.</p>
            <h3>Is pericarditis more common in certain age groups?</h3>
            <p>Pericarditis can occur at any age, but it's more common in adults aged 20-50. Regular exercise and a healthy lifestyle can help prevent it.</p>
            <h3>Can pericarditis recur after treatment?</h3>
            <p>Yes, pericarditis can recur after treatment, requiring careful monitoring and management to prevent further episodes.</p>
            <h3>How does pericarditis affect the heart’s ability to pump blood?</h3>
            <p>Pericarditis can impair the heart's ability to pump blood by causing inflammation around the heart, leading to decreased cardiac output.</p>
