            <p>Symptoms of acute heart failure include shortness of breath, fatigue, swelling in the legs, rapid heartbeat, and coughing.</p>
            <h3>How is acute heart failure diagnosed?</h3>
            <p>Doctors diagnose acute heart failure using physical exams, blood tests, imaging tests like echocardiograms, and monitoring symptoms.</p>
