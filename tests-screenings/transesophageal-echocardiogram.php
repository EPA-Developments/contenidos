<h2 class="title" id="faqs">Frequently Asked Questions</h2>
</div>
<h3>What is a transesophageal echocardiogram (TEE)?</h3>
<p>A transesophageal echocardiogram (TEE) is a test that uses sound waves to create detailed images of the heart from inside the esophagus to evaluate its structure and function.</p>
<h3>How is a TEE performed?</h3>
<p>During a Transesophageal Echocardiogram (TEE), a small ultrasound probe is passed through the mouth into the esophagus to take detailed images of the heart and its structures. It is a safe procedure and usually takes about 30-60 minutes.</p>
<h3>Why do I need a transesophageal echocardiogram?</h3>
<p>A transesophageal echocardiogram gives more detailed images of your heart than a regular echocardiogram, helping your doctor evaluate the structure and function of your heart more accurately.</p>
<h3>What conditions can be diagnosed with a TEE?</h3>
<p>A transesophageal echocardiogram (TEE) can help diagnose conditions such as heart valve problems, blood clots, infections, and heart defects.</p>
<h3>How accurate is TEE?</h3>
<p>Transesophageal echocardiogram (TEE) is a highly accurate test for evaluating the heart and its structures. It provides detailed images of the heart and is often used when a more precise assessment is needed than a standard echocardiogram can provide.</p>
<h3>Is TEE painful?</h3>
<p>During a transesophageal echocardiogram (TEE), patients are usually given medication to relax and numb the throat, so discomfort is minimal.</p>
<h3>How long does a TEE take?</h3>
<p>A transesophageal echocardiogram (TEE) typically takes around 30 to 60 minutes to complete.</p>
<h3>What are the risks of a TEE?</h3>
<p>The risks of a transesophageal echocardiogram (TEE) include a sore throat, minor bleeding, and a very rare risk of more serious complications like perforation of the esophagus.</p>
<h3>What should I expect during a TEE?</h3>
<p>During a transesophageal echocardiogram (TEE), a healthcare provider will lead a small ultrasound probe into your esophagus to get detailed images of your heart. You will be given medication to help you relax and numb your throat to make the procedure more comfortable.</p>
<h3>How is a TEE different from a standard echocardiogram?</h3>
<p>A TEE (transesophageal echocardiogram) is a type of echocardiogram that involves inserting a probe into the esophagus to get clearer images of the heart. It is more invasive but provides more detailed images compared to a standard echocardiogram done on the chest wall.</p>
