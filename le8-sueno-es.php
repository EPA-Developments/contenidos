<h1>Duración del Sueño: La Métrica #4 de Life's Essential 8™</h1>

<p>La <strong>duración del sueño</strong> es la cuarta métrica esencial para salud cardiovascular y representa la <strong>principal innovación de Life's Essential 8™</strong> sobre Life's Simple 7. Su inclusión refleja el reconocimiento científico creciente de que el sueño no es simplemente "tiempo de descanso", sino un <strong>proceso fisiológico activo crítico</strong> para la salud cardiovascular, metabólica, cognitiva e inmunológica.</p>

<p>La evidencia es clara: <strong>tanto el sueño insuficiente (<7 horas) como el excesivo (>9 horas) aumentan el riesgo de enfermedad cardiovascular</strong>. Esta relación en "U" significa que existe un rango óptimo - 7-9 horas para adultos - donde el riesgo cardiovascular es mínimo. Dormir <6 horas aumenta 20% el riesgo de enfermedad coronaria y 15% el riesgo de stroke; dormir >9 horas aumenta 38% el riesgo cardiovascular.</p>

<h2 id="puntuacion">Sistema de Puntuación de Duración del Sueño</h2>

<h3>★ Novedad Clave de Life's Essential 8™</h3>

<div class="innovation-highlight">
<p><strong>¿Por qué se añadió el sueño?</strong></p>
<ul>
<li>Evidencia epidemiológica robusta: >300 estudios vinculando duración sueño con outcomes cardiovasculares</li>
<li>Prevalencia alta de sueño inadecuado: 30-35% adultos EE.UU. duermen <7 horas/noche</li>
<li>Modificabilidad: Intervenciones pueden mejorar duración y calidad sueño</li>
<li>Independencia: Asociación con riesgo CV persiste tras ajustar otros factores de riesgo</li>
<li>Mecanismos plausibles: Múltiples vías fisiopatológicas identificadas</li>
</ul>
</div>

