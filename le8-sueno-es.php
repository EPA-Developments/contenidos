<li>↑ Agregación plaquetaria</li>
<li>↑ Actividad factor VII coagulación</li>
<li>↑ Fibrinógeno</li>
<li>↓ Actividad fibrinolítica</li>
<li>Estado protrombótico → ↑ riesgo trombosis coronaria/cerebral</li>
</ul>
</div>

<div class="mechanism">
<h4>💔 Remodelado Cardíaco</h4>
<ul>
<li>Privación crónica → sobrecarga presión/volumen sostenida</li>
