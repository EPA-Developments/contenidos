<h3>👩 Mujeres (Cambios Hormonales)</h3>

<div class="women-sleep">
<h4>Ciclo Menstrual</h4>
<ul>
<li><strong>Fase lútea:</strong> ↑ Temperatura corporal 0.3-0.5°C → calidad sueño ligeramente ↓</li>
<li><strong>Período menstrual:</strong> Dolor, sangrado → fragmentación sueño</li>
<li><strong>Síndrome premenstrual (SPM):</strong> 70% mujeres reportan insomnio transitorio</li>
</ul>

<h4>Embarazo</h4>
<ul>
<li><strong>Primer trimestre:</strong> ↑ Somnolencia diurna (progesterona), nocturia</li>
<li><strong>Tercer trimestre:</strong> Fragmentación sueño severa (incomodidad física, movimientos fetales, reflujo)</li>
<li><strong>Apnea sueño gestacional:</strong> 10-26% embarazadas (vs 2-4% pre-embarazo) → screening importante</li>
<li><strong>Síndrome piernas inquietas:</strong> 25-30% embarazadas (vs 10% población general)</li>
<li><strong>Consecuencias sueño pobre:</strong> ↑ Riesgo preeclampsia, diabetes gestacional, parto prematuro</li>
</ul>

<h4>Menopausia</h4>
<ul>
<li><strong>Prevalencia insomnio:</strong> 40-60% mujeres peri/postmenopáusicas</li>
<li><strong>Síntomas vasomotores:</strong> Sofocones nocturnos → despertares (correlación fuerte)</li>
<li><strong>Cambios hormonales:</strong> ↓ Estrógeno/progesterona afecta neurotransmisores sueño (GABA, serotonina)</li>
<li><strong>↑ Apnea sueño:</strong> Prevalencia iguala hombres post-menopausia (pérdida efecto protector estrogénico)</li>
<li><strong>Tratamientos:</strong>
  <ul>
    <li>TCC-I (primera línea) - eficacia equivalente a mujeres jóvenes</li>
    <li>Terapia hormonal (HT): Mejora síntomas vasomotores → mejor sueño indirectamente</li>
    <li>Antidepresivos ISRS/IRSN: Para sofocones si HT contraindicada (efecto moderado sueño)</li>
    <li>Hipnóticos: Uso juicioso, corto plazo solamente</li>
  </ul>
</li>
</ul>
</div>

<h3>🧓 Adultos Mayores (≥65 años)</h3>

<div class="elderly-sleep">
<h4>Cambios Arquitectura Sueño con Envejecimiento</h4>
<ul>
<li>↓ Sueño profundo (N3): 20% (20s) → 5-10% (70s)</li>
<li>↑ Sueño ligero (N1, N2): Más fragmentación</li>
<li>↓ REM levemente</li>
<li>↑ Despertares nocturnos: 1-2 (jóvenes) → 5-7 (ancianos)</li>
<li>↑ Latencia sueño: 10-15 min → 20-30 min</li>
<li>Avance fase circadiana: "Alondras matutinas" - somnolencia temprana, despertar precoz</li>
</ul>

<h4>Factores Contribuyentes Insomnio Geriátrico</h4>
<ul>
<li><strong>Comorbilidades médicas:</strong> Dolor crónico, nocturia (HBP, IC), reflujo, EPOC</li>
<li><strong>Medicaciones:</strong> Diuréticos, agonistas β, corticosteroides, estimulantes</li>
<li><strong>Trastornos sueño primarios:</strong> ↑ Prevalencia AOS, síndrome piernas inquietas, trastorno conducta REM</li>
<li><strong>Salud mental:</strong> Depresión (15-20% ancianos), ansiedad, duelo</li>
<li><strong>Cambios sociales:</strong> Jubilación → pérdida estructura día, menos actividad física</li>
<li><strong>↓ Exposición luz:</strong> Menos tiempo exterior → debilitación señales circadianas</li>
</ul>

<h4>Estrategias Específicas Adultos Mayores</h4>
<ul>
<li><strong>Aceptar cambios normales:</strong> Expectativas realistas (6-7h sueño puede ser suficiente si se siente descansado)</li>
<li><strong>Optimizar tratamiento comorbilidades:</strong> Manejo dolor, BPH, IC, reflujo</li>
<li><strong>Revisión medicaciones:</strong> Timing diuréticos (AM, no PM), evitar estimulantes tarde</li>
<li><strong>↑ Exposición luz diurna:</strong> 30-60 min luz brillante outdoor (fortalece ritmo circadiano)</li>
<li><strong>Actividad física regular:</strong> Crítica - mejora sueño profundo, reduce latencia</li>
<li><strong>Evitar siestas largas:</strong> Máximo 30 min, antes 3pm</li>
<li><strong>TCC-I adaptada:</strong> Igualmente efectiva vs adultos jóvenes</li>
<li><strong>Precaución hipnóticos:</strong> ↑ Riesgo caídas, deterioro cognitivo - evitar benzodiacepinas; si necesario, preferir Z-drugs dosis bajas corto plazo</li>
</ul>
</div>

