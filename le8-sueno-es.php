<h2>Consideraciones Especiales por Población</h2>

<h3>👨‍⚕️ Profesionales de Salud (Médicos, Residentes, Enfermeras)</h3>

<div class="healthcare-sleep">
<h4>Epidemiología del Problema</h4>
<ul>
<li><strong>Residentes médicos:</strong> 65-80% duermen <7h durante rotaciones clínicas</li>
<li><strong>Enfermeras turnos nocturnos:</strong> 50-60% sueño insuficiente crónico</li>
<li><strong>Médicos asistentes:</strong> 40% reportan calidad sueño pobre</li>
<li><strong>Guardias 24h:</strong> Privación severa (0-3h) → equivalente 0.10% alcohol intoxicación en performance</li>
</ul>

<h4>Consecuencias Específicas</h4>
<ul>
<li><strong>Errores médicos:</strong> ↑ 36% tras guardias prolongadas (>24h)</li>
<li><strong>Accidentes automovilísticos:</strong> ↑ 168% conduciendo post-guardia extendida</li>
<li><strong>Agotamiento profesional (burnout):</strong> Privación sueño factor contribuyente mayor</li>
<li><strong>Salud CV propia:</strong> ↑ Riesgo hipertensión, IAM en médicos con turnos nocturnos frecuentes</li>
</ul>

<h4>Estrategias Específicas</h4>
<ul>
<li><strong>Siestas estratégicas:</strong> 20-30 min durante guardia (si factible) mejora alerta 34%</li>
<li><strong>Cafeína táctica:</strong> 200mg (2 cafés) mejora vigilia 3-4h, pero evitar <6h pre-sueño post-guardia</li>
<li><strong>Luz brillante:</strong> Exposición 10,000 lux durante turno nocturno mejora alerta</li>
<li><strong>Recuperación post-guardia:</strong>
  <ul>
    <li>NO conducir inmediatamente (riesgo accidente ↑↑)</li>
    <li>Siesta recuperación 2-3h al llegar casa</li>
    <li>Reestablecer ritmo: exposición luz matutina siguiente día</li>
    <li>Evitar alcohol como "ayuda dormir" (contraproducente)</li>
  </ul>
</li>
<li><strong>Límites trabajo (ACGME 2011, actualizaciones):</strong>
  <ul>
    <li>Máximo 80h/semana promediado 4 semanas</li>
    <li>Turnos máximo 16h (PGY-1) o 24h + 4h transición (PGY-2+)</li>
    <li>Mínimo 8h entre turnos</li>
    <li>1 día libre/semana promediado mes</li>
  </ul>
</li>
</ul>

