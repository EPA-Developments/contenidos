<div class="u-shape-explanation">
<h4>⚠️ Relación en "U" - Importante Concepto</h4>
<p>A diferencia de otras métricas LE8™ donde "más es mejor" o "menos es mejor", el sueño tiene una <strong>relación bidireccional</strong> con riesgo cardiovascular:</p>
<ul>
<li><strong>Sueño insuficiente (<7h):</strong> Privación crónica → activación simpática, inflamación, resistencia insulina</li>
<li><strong>Sueño excesivo (>9h):</strong> Marcador de comorbilidades subyacentes, fragmentación sueño, condiciones médicas</li>
<li><strong>Zona óptima (7-9h):</strong> Permite consolidación memoria, restauración cardiovascular, regulación metabólica</li>
</ul>
<p><strong>Implicancia clínica:</strong> Tanto dormir muy poco como dormir demasiado requiere evaluación e intervención.</p>
