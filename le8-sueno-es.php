<h4>🚨 Crisis de Sueño Pediátrico</h4>
<p><strong>Datos alarmantes:</strong></p>
<ul>
<li>Solo <strong>48% de adolescentes</strong> alcanzan 8+ horas sueño en noches escolares</li>
<li><strong>73% estudiantes secundaria</strong> reportan somnolencia diurna</li>
<li>Inicio clases tempranas (<8am): Factor contribuyente mayor (conflicto con ritmo circadiano adolescente)</li>
<li>Tiempo pantalla: Adolescentes promedian 7+ horas/día (luz azul → retraso melatonina)</li>
</ul>

<p><strong>Consecuencias:</strong></p>
<ul>
<li>↓ Rendimiento académico (0.5-1.0 desviación estándar)</li>
<li>↑ Obesidad infantil (20-30% en durmientes cortos vs adecuados)</li>
<li>↑ Depresión/ansiedad adolescente</li>
<li>↑ Accidentes automovilísticos (conductores adolescentes con <6h sueño)</li>
</ul>
