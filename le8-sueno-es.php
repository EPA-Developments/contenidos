</table>
</div>

<h3>✅ Estrategias de Mejora Sueño (Implementación Gradual)</h3>

<div class="improvement-strategies">
<h4>Fase 1: Semanas 1-2 (Fundamentos)</h4>
<ul>
<li><strong>Horario fijo:</strong> Establecer hora acostarse y despertar (misma TODOS días)</li>
<li><strong>Tracking:</strong> Diario de sueño (hora acostarse, latencia, despertares, hora despertar, calidad subjetiva 1-10)</li>
<li><strong>Optimizar dormitorio:</strong> Oscuridad, temperatura 15-19°C, silencio</li>
<li><strong>Eliminar cafeína post-2pm:</strong> Primera intervención fácil, impacto significativo</li>
<li><strong>Meta:</strong> Reducir variabilidad horario sueño <30 min entre días</li>
</ul>

<h4>Fase 2: Semanas 3-4 (Higiene Avanzada)</h4>
<ul>
<li><strong>Ritual pre-sueño 60 min:</strong> Actividades relajantes consistentes</li>
<li><strong>Screen curfew:</strong> Dispositivos electrónicos off 1h pre-sueño</li>
<li><strong>Exposición luz:</strong> 15-30 min luz brillante matutina (outdoor ideal)</li>
<li><strong>Ejercicio regular:</strong> Mínimo 30 min actividad moderada, >3h pre-sueño</li>
<li><strong>Limitar alcohol:</strong> Máximo 1-2 bebidas, >3h pre-sueño</li>
</ul>

<h4>Fase 3: Semanas 5-8 (Técnicas Conductuales)</h4>
<ul>
<li><strong>Restricción sueño (si insomnio):</strong>
  <ul>
    <li>Calcular promedio horas dormidas (diario semana)</li>
    <li>Limitar tiempo en cama = promedio horas + 30 min</li>
    <li>Ejemplo: Si duerme 6h promedio → permitir solo 6.5h en cama</li>
    <li>↑ Presión homeostática sueño → mejor consolidación</li>
    <li>Gradualmente aumentar 15 min/semana si eficiencia sueño >85%</li>
  </ul>
</li>
<li><strong>Control de estímulos:</strong>
  <ul>
    <li>Si no duerme en 20 min → levantarse, ir a otra habitación</li>
    <li>Actividad relajante hasta tener sueño, luego regresar a cama</li>
    <li>Repetir si necesario</li>
    <li>Rompe asociación "cama = frustración despierto"</li>
  </ul>
</li>
<li><strong>Relajación muscular progresiva:</strong>
  <ul>
    <li>Tensar/relajar grupos musculares secuencialmente</li>
    <li>5-10 min pre-sueño en cama</li>
  </ul>
</li>
<li><strong>Mindfulness/Meditación:</strong>
  <ul>
    <li>Apps guiadas: Calm, Headspace (secciones específicas sueño)</li>
    <li>10-20 min diarios (no necesariamente pre-sueño)</li>
    <li>Reduce rumiación, ansiedad pre-sueño</li>
  </ul>
</li>
</ul>

<h4>Fase 4: Evaluación y Mantenimiento (Semana 9+)</h4>
<ul>
<li><strong>Re-evaluar diario sueño:</strong> Comparar semanas 1-2 vs 8-9</li>
<li><strong>Métricas clave:</strong>
  <ul>
    <li>Latencia sueño: ¿<30 min?</li>
    <li>Despertares nocturnos: ¿≤1-2?</li>
    <li>Eficiencia sueño: (Tiempo dormido / Tiempo en cama) × 100 ≥85%</li>
    <li>Duración: ¿7-9h?</li>
    <li>Calidad subjetiva: ¿≥7/10?</li>
  </ul>
</li>
<li><strong>Identificar estrategias más efectivas:</strong> Personalizar protocolo</li>
<li><strong>Mantenimiento a largo plazo:</strong> Horarios consistentes, higiene básica perpetua</li>
</ul>
</div>

<h3>🩺 Cuándo Buscar Evaluación Médica</h3>

<div class="medical-evaluation">
<p><strong>Señales de alarma - consultar especialista sueño:</strong></p>

<ul>
<li><strong>Insomnio crónico:</strong> ≥3 noches/semana por >3 meses a pesar de higiene sueño adecuada</li>
<li><strong>Somnolencia diurna excesiva:</strong> Quedarse dormido situaciones inapropiadas (conversaciones, conduciendo)</li>
<li><strong>Ronquidos fuertes + pausas respiratorias:</strong> Sospecha apnea obstructiva del sueño</li>
<li><strong>Movimientos anormales sueño:</strong> Piernas inquietas, movimientos periódicos extremidades</li>
<li><strong>Parasomnias:</strong> Sonambulismo, terrores nocturnos (adultos), pesadillas recurrentes</li>
<li><strong>Sueño excesivo persistente:</strong> >10h regularmente + fatiga diurna</li>
<li><strong>Síntomas depresión/ansiedad:</strong> Insomnio frecuentemente comórbido</li>
</ul>

<h4>Apnea Obstructiva del Sueño (AOS) - Alta Prevalencia Subdiagnosticada</h4>

<p><strong>Prevalencia:</strong> 15-30% adultos (↑ con obesidad, edad), 80% sin diagnosticar</p>

<p><strong>Factores de riesgo:</strong></p>
<ul>
<li>Obesidad (IMC >30): Factor de riesgo #1</li>
<li>Cuello circunferencia: >43 cm hombres, >41 cm mujeres</li>
<li>Edad >50 años</li>
<li>Sexo masculino (2-3× prevalencia vs mujeres premenopáusicas)</li>
<li>Congestión nasal crónica</li>
<li>Hipertensión resistente</li>
<li>Fibrilación atrial</li>
</ul>

<p><strong>Screening (cuestionario STOP-BANG):</strong></p>
<ul>
<li><strong>S</strong>noring (ronquido fuerte)</li>
<li><strong>T</strong>ired (fatiga diurna)</li>
<li><strong>O</strong>bserved apneas (pausas respiratorias observadas)</li>
<li><strong>P</strong>ressure (hipertensión)</li>
<li><strong>B</strong>MI >35 kg/m²</li>
<li><strong>A</strong>ge >50 años</li>
<li><strong>N</strong>eck circunference >40 cm</li>
<li><strong>G</strong>ender masculino</li>
</ul>
<p>≥3 positivos: Alto riesgo AOS → polisomnografía</p>

<p><strong>Consecuencias CV de AOS no tratada:</strong></p>
<ul>
<li>↑ Hipertensión 2-3×</li>
<li>↑ Stroke 3-4×</li>
<li>↑ IAM 2×</li>
<li>↑ Fibrilación atrial 2-4×</li>
<li>↑ Insuficiencia cardíaca 2×</li>
<li>↑ Mortalidad CV 30-40%</li>
</ul>

<p><strong>Tratamiento:</strong></p>
<ul>
<li><strong>CPAP (presión positiva continua vía aérea):</strong> Gold standard, reduce eventos respiratorios 90%+</li>
<li><strong>Pérdida peso:</strong> 10% peso → 26% reducción AHI (índice apnea-hipopnea)</li>
<li><strong>Terapia posicional:</strong> Evitar decúbito supino si AOS posicional</li>
<li><strong>Dispositivos orales:</strong> Avance mandibular (AOS leve-moderada)</li>
<li><strong>Cirugía:</strong> Casos selectos (UPPP, cirugía maxilofacial)</li>
</ul>

<p><strong>Adherencia CPAP:</strong> 30-40% descontinúan primer año - apoyo conductual crítico</p>
</div>

<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>Meta-análisis Prospectivo: Duración Sueño y Enfermedad Cardiovascular (2011)</h4>
<p><strong>Análisis:</strong> 15 estudios prospectivos, 474,684 participantes, seguimiento 7-25 años</p>
<p><strong>Hallazgos (comparado con 7-8h sueño):</strong></p>
<table class="meta-analysis-results">
<tr>
<td><strong>Sueño corto (≤5-6h):</strong></td>
<td>RR 1.48 enfermedad coronaria (IC95% 1.22-1.80)</td>
</tr>
<tr>
<td></td>
<td>RR 1.15 stroke (IC95% 1.00-1.31)</td>
</tr>
<tr>
<td><strong>Sueño largo (≥9h):</strong></td>
<td>RR 1.38 enfermedad coronaria (IC95% 1.15-1.66)</td>
</tr>
<tr>
<td></td>
<td>RR 1.65 stroke (IC95% 1.45-1.87)</td>
</tr>
</table>
<p><strong>Conclusión:</strong> Relación en "U" confirmada - tanto sueño insuficiente como excesivo asociados con ↑ riesgo CV</p>
</div>

<div class="evidence-box">
<h4>Nurses' Health Study - Sueño e Hipertensión (2013)</h4>
<p><strong>Diseño:</strong> Cohorte prospectiva, 98,594 mujeres sin hipertensión baseline, seguimiento 10 años</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li><strong>≤5h sueño:</strong> RR 1.19 hipertensión incidente (IC95% 1.10-1.29)</li>
<li><strong>6h sueño:</strong> RR 1.07 (IC95% 1.02-1.13)</li>
<li><strong>7-8h sueño:</strong> Referencia</li>
<li><strong>≥9h sueño:</strong> RR 1.09 (IC95% 1.00-1.18)</li>
<li>Asociación más fuerte en <60 años vs ≥60 años</li>
<li>Independiente de IMC, actividad física, otros factores de riesgo</li>
</ul>
<p><strong>Implicancia:</strong> Privación sueño factor de riesgo independiente hipertensión</p>
</div>

<div class="evidence-box">
<h4>Estudio Experimental: Privación Sueño Aguda y Función Endotelial</h4>
<p><strong>Diseño:</strong> Crossover controlado, 15 adultos jóvenes sanos, privación total sueño 24h</p>
<p><strong>Medición:</strong> Vasodilatación mediada por flujo (FMD) arteria braquial</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>FMD basal (tras sueño normal): 13.2% ± 2.1%</li>
<li>FMD post-privación 24h: 6.8% ± 1.9% (<strong>↓ 48%, P<0.001</strong>)</li>
<li>Recuperación: FMD normaliza tras 2 noches sueño recuperación</li>
<li>Mecanismo: ↓ Biodisponibilidad óxido nítrico, ↑ estrés oxidativo</li>
</ul>
<p><strong>Conclusión:</strong> Una sola noche sin dormir deteriora dramáticamente función endotelial</p>
</div>

<div class="evidence-box">
<h4>Whitehall II Study - Cambio Duración Sueño y Mortalidad CV</h4>
<p><strong>Diseño:</strong> Cohorte prospectiva, 7,470 funcionarios UK, evaluación sueño 1985-1988 y 1997-1999</p>
<p><strong>Hallazgos (cambio duración sueño):</strong></p>
<ul>
<li><strong>Reducción ≥7h → ≤5h:</strong> HR 1.68 mortalidad CV (IC95% 1.07-2.64)</li>
<li><strong>Aumento ≤5h → ≥7h:</strong> No reducción significativa mortalidad (posiblemente tarde)</li>
<li><strong>Mantenimiento 7-8h:</strong> Mejor pronóstico a largo plazo</li>
</ul>
<p><strong>Mensaje:</strong> Prevención superior a intervención - mantener sueño adecuado crucial</p>
</div>

<div class="evidence-box">
<h4>Meta-análisis: TCC-Insomnio (Terapia Cognitivo-Conductual)</h4>
<p><strong>Análisis:</strong> 20 RCTs, 1,162 pacientes insomnio crónico</p>
<p><strong>Comparación:</strong> TCC-I vs control lista espera o educación sueño</p>
<p><strong>Resultados (post-tratamiento):</strong></p>
<ul>
<li>↓ Latencia sueño: -20 minutos (Cohen's d = 0.56)</li>
<li>↓ Tiempo despierto tras inicio sueño: -30 minutos (d = 0.65)</li>
<li>↑ Eficiencia sueño: +10% (d = 0.71)</li>
<li>↑ Calidad sueño subjetiva: d = 0.94</li>
<li>Remisión insomnio: 40% vs 17% control</li>
<li>Efectos sostenidos a 12 meses seguimiento</li>
</ul>
<p><strong>Componentes TCC-I:</strong> Restricción sueño, control estímulos, higiene sueño, reestructuración cognitiva, relajación</p>
<p><strong>Conclusión:</strong> TCC-I tratamiento de primera línea insomnio crónico (superior a hipnóticos largo plazo)</p>
</div>

<h3>Mecanismos Fisiopatológicos</h3>

<div class="mechanisms-grid">
<div class="mechanism">
<h4>⚡ Activación Sistema Simpático</h4>
<ul>
<li>Privación sueño → ↑ actividad simpática 24h (no solo durante vigilia)</li>
<li>↑ Norepinefrina, epinefrina plasmática</li>
<li>↑ Frecuencia cardíaca basal</li>
<li>↑ Presión arterial (ausencia "dipping" nocturno)</li>
<li>↓ Variabilidad frecuencia cardíaca (HRV)</li>
<li>Consecuencia: Estado hipervigilancia → sobrecarga cardiovascular crónica</li>
</ul>
</div>

<div class="mechanism">
<h4>🔥 Inflamación Sistémica</h4>
<ul>
<li>Privación sueño → activación eje HPA (hipotálamo-pituitaria-adrenal)</li>
<li>↑ Cortisol (pérdida ritmo circadiano normal)</li>
<li>↑ PCR 25-100% (dependiendo severidad privación)</li>
<li>↑ IL-6, IL-1β, TNF-α</li>
<li>Activación NFkB (factor transcripción proinflamatorio)</li>
<li>Contribución aterogénesis, desestabilización placas</li>
</ul>
</div>

<div class="mechanism">
<h4>🧬 Disfunción Endotelial</h4>
<ul>
<li>↓ Óxido nítrico (NO) biodisponibilidad</li>
<li>↑ Endotelina-1 (vasoconstrictor potente)</li>
<li>↑ Estrés oxidativo (ROS)</li>
<li>↓ Vasodilatación mediada por flujo (FMD) 30-50%</li>
<li>↑ Expresión moléculas adhesión (VCAM-1, ICAM-1)</li>
<li>Inicio aterosclerosis, progresión lesiones existentes</li>
</ul>
</div>

<div class="mechanism">
<h4>📊 Desregulación Metabólica</h4>
<ul>
<li>↓ Sensibilidad insulina 30-40% (una sola noche privación severa)</li>
<li>↑ Glucosa en ayunas</li>
<li>↓ Tolerancia glucosa (curva respuesta aplanada)</li>
<li>↑ Grelina (hormona hambre) 15-20%</li>
<li>↓ Leptina (hormona saciedad) 15-20%</li>
<li>Preferencia alimentos altos carbohidratos/grasas</li>
<li>↑ Ingesta calórica 300-500 kcal/día</li>
</ul>
</div>

<div class="mechanism">
<h4>🩸 Efectos Hematológicos</h4>
