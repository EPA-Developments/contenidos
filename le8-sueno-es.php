<h3>😴 Consecuencias de Sueño Excesivo (>9 horas)</h3>

<div class="excessive-sleep">
<p><strong>Paradoja del sueño excesivo:</strong> Asociación con ↑ mortalidad, pero mecanismos menos claros que privación</p>

<h4>Hipótesis Explicativas</h4>

<ol>
<li><strong>Marcador de enfermedad subyacente:</strong>
  <ul>
    <li>Depresión (hipersomnia como síntoma)</li>
    <li>Apnea del sueño (compensación por mala calidad)</li>
    <li>Enfermedades crónicas (fatiga, anemia, hipotiroidismo)</li>
    <li>Medicaciones sedantes</li>
    <li>Bajo nivel socioeconómico (menos oportunidades, más comorbilidades)</li>
  </ul>
</li>

<li><strong>Fragmentación del sueño:</strong>
  <ul>
    <li>Tiempo en cama ≠ sueño consolidado de calidad</li>
    <li>Múltiples despertares → menos sueño profundo</li>
    <li>Apnea obstructiva frecuente en durmientes largos</li>
  </ul>
</li>

<li><strong>Desregulación circadiana:</strong>
  <ul>
    <li>Horarios irregulares de sueño</li>
    <li>Exposición luz inadecuada (demasiado poco durante día)</li>
    <li>Inactividad física</li>
  </ul>
</li>

<li><strong>Efectos directos potenciales:</strong>
  <ul>
    <li>↑ Inflamación (evidencia mixta)</li>
    <li>Alteraciones metabólicas glucosa</li>
    <li>↓ Actividad física diurna</li>
  </ul>
</li>
</ol>

<p><strong>Implicancia clínica:</strong> Sueño excesivo (>9h regular) requiere <strong>evaluación médica</strong> para identificar causas subyacentes, especialmente:</p>
<ul>
<li>Screening apnea del sueño (polisomnografía si sospecha)</li>
<li>Evaluación depresión/salud mental</li>
<li>Laboratorio: TSH, hemograma, función renal</li>
<li>Revisión medicaciones</li>
</ul>
</div>

<h2 id="higiene">Higiene del Sueño: Estrategias Basadas en Evidencia</h2>

<h3>💡 Principios Fundamentales</h3>

<div class="sleep-hygiene-principles">
<h4>Los 3 Pilares de la Higiene del Sueño</h4>

<div class="pillar">
<h5>1. Regularidad (Ritmo Circadiano)</h5>
<p>Mantener horarios consistentes de sueño/vigilia sincroniza reloj biológico interno</p>
<ul>
<li>Acostarse y despertar misma hora TODOS los días (incluyendo fines de semana)</li>
<li>Variación máxima permitida: ±30-60 minutos</li>
<li>Exposición luz brillante matutina (15-30 min dentro de 1h despertar)</li>
<li>Evitar siestas largas (>30 min) o tardías (post-3pm)</li>
</ul>
<p><strong>Evidencia:</strong> Irregularidad sueño aumenta 30% riesgo síndrome metabólico, independiente de duración total</p>
</div>

<div class="pillar">
<h5>2. Ambiente Propicio</h5>
<p>Optimizar condiciones físicas del dormitorio para facilitar sueño</p>
<ul>
<li><strong>Oscuridad:</strong> Blackout curtains, eliminar LEDs dispositivos, antifaz si necesario</li>
<li><strong>Temperatura:</strong> 15.5-19.4°C (60-67°F) óptima - cuerpo necesita enfriarse para iniciar sueño</li>
<li><strong>Silencio:</strong> Tapones oídos, máquina ruido blanco si ambiente ruidoso</li>
<li><strong>Comodidad:</strong> Colchón y almohadas apropiadas (reemplazar colchón cada 7-10 años)</li>
<li><strong>Asociación:</strong> Cama = solo dormir/sexo (no trabajo, TV, comer en cama)</li>
</ul>
</div>

<div class="pillar">
<h5>3. Ritual Pre-Sueño (Wind-Down)</h5>
<p>Transición gradual de actividad a descanso prepara cerebro/cuerpo para sueño</p>
<ul>
<li>Período 60-90 min pre-sueño de actividades relajantes</li>
<li>Evitar estímulos activadores (trabajo, email, noticias estresantes, discusiones)</li>
<li>Luz tenue (preferiblemente cálida <2700K, evitar luz azul)</li>
<li>Actividades ejemplos: lectura placentera, baño caliente, estiramientos suaves, meditación</li>
<li>Temperatura corporal: Baño caliente 90 min pre-sueño → enfriamiento posterior facilita sueño</li>
</ul>
</div>
</div>

