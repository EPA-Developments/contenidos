<h4>Importancia de N3 (Sueño Profundo) para Salud CV</h4>
<ul>
<li><strong>"Dipping" presión arterial nocturna:</strong> Reducción 10-20% PA durante sueño profundo</li>
<li><strong>No-dippers</strong> (PA no reduce ≥10% nocturno): ↑ 20-40% riesgo eventos CV</li>
<li>N3 disminuye con edad: 20s = 20% sueño, 60s = 5-10% sueño</li>
<li>Fragmentación N3: Asociada con hipertensión resistente, rigidez arterial</li>
<li>Farmacoterapia (benzodiacepinas): Suprimen N3 → menos beneficio CV que sueño natural</li>
</ul>
