          <h2 class="title" id="faqs">Preguntas Frecuentes - Duración del Sueño</h2>
        </div>
        
        <h3>¿Por qué tanto el sueño corto como el largo aumentan el riesgo cardiovascular?</h3>
        <p>El sueño tiene una relación en "U" con riesgo cardiovascular. Sueño insuficiente (<7h) causa activación simpática sostenida, inflamación, resistencia insulina y disfunción endotelial - mecanismos directos de daño. Sueño excesivo (>9h) generalmente refleja comorbilidades subyacentes (depresión, apnea del sueño, enfermedades crónicas) o fragmentación severa del sueño (muchas horas en cama ≠ sueño de calidad). El rango óptimo 7-9h permite restauración cardiovascular adecuada sin ser marcador de patología subyacente.</p>
        
        <h3>¿Las siestas cuentan para la duración total de sueño?</h3>
        <p>No para adultos en Life's Essential 8™. La métrica evalúa duración de sueño nocturno consolidado, no sueño total 24h. Sin embargo, siestas breves (20-30 min) pueden ser beneficiosas para compensar parcialmente privación nocturna aguda (ej. trabajadores turnos). Siestas >30 min o tardías (post-3pm) pueden interferir con sueño nocturno (reducen presión homeostática). Para niños pequeños, las siestas SÍ cuentan hacia el total recomendado 24h (ej. 1-2 años: 11-14h incluye siestas).</p>
        
        <h3>¿Puedo "recuperar" sueño perdido durmiendo más los fines de semana?</h3>
        <p>Parcialmente, pero no completamente. "Sleep extension" en fines de semana puede mejorar temporalmente alerta y función cognitiva, pero NO revierte completamente efectos metabólicos/cardiovasculares de privación crónica semanal. Estudios muestran que variabilidad horario sueño (diferencia >2h entre días laborables/fines de semana) se asocia independientemente con peores outcomes metabólicos. Lo óptimo es mantener horario consistente 7 días/semana. Si deuda sueño significativa, incrementar gradualmente duración nocturna regular en lugar de "binge sleeping" fin de semana.</p>
        
        <h3>¿La calidad del sueño importa tanto como la duración?</h3>
        <p>SÍ, absolutamente. Life's Essential 8™ enfoca duración por ser más fácilmente cuantificable, pero calidad es igualmente crítica. Fragmentación severa del sueño (apnea obstructiva, movimientos periódicos extremidades, insomnio de mantenimiento) puede resultar en 8h en cama pero solo 5-6h sueño consolidado de calidad. Sueño profundo (N3) es particularmente importante para beneficios cardiovasculares ("dipping" presión arterial nocturna). Si duerme 7-9h pero se despierta no descansado o somnoliento diurno, evaluación calidad sueño (posible polisomnografía) está indicada.</p>
        
        <h3>¿Los dispositivos wearables miden el sueño con precisión?</h3>
        <p>Moderadamente. Wearables modernos (Oura Ring, Apple Watch, Whoop, Fitbit) son razonablemente precisos para duración total y detección vigilia/sueño (80-90% concordancia vs polisomnografía). Sin embargo, clasificación de etapas específicas (ligero/profundo/REM) tiene precisión variable (50-80% dependiendo dispositivo/etapa). Son útiles para tracking tendencias y motivación, pero NO diagnóstico clínico. Si sospecha trastorno sueño significativo (apnea, narcolepsia, parasomnias), polisomnografía en laboratorio sigue siendo gold standard.</p>
        
        <h3>¿Necesito exactamente 8 horas? ¿Qué pasa si me siento bien con 6 horas?</h3>
        <p>El rango 7-9h es recomendación basada en evidencia epidemiológica de menor riesgo cardiovascular y mortalidad. Variabilidad individual existe (genética, edad), pero es menor de lo que muchos creen. Estudios demuestran que personas que "se sienten bien" con 6h frecuentemente muestran deficiencias objetivas (tiempo reacción, función ejecutiva, marcadores metabólicos) que ellos mismos no perciben - fenómeno "adaptación subjetiva sin recuperación objetiva". Solo ~1-3% población son verdaderos "short sleepers" genéticos (<7h sin consecuencias). Si genuinamente duerme <7h sin somnolencia diurna, buena salud, y mantiene >85% eficiencia sueño, puede ser excepción, pero evidencia sugiere mayoría se beneficiaría de 7-9h.</p>
        
        <h3>¿Qué hago si tengo insomnio crónico a pesar de buena higiene del sueño?</h3>
        <p>Consulta con especialista sueño para TCC-I (Terapia Cognitivo-Conductual para Insomnio). TCC-I es tratamiento primera línea con eficacia superior a hipnóticos a largo plazo. Componentes: restricción sueño (consolidar tiempo en cama para ↑ eficiencia), control estímulos (fortalecer asociación cama=dormir), reestructuración cognitiva (abordar pensamientos disfuncionales sobre sueño), relajación. Disponible presencial, telesalud, y plataformas digitales (Sleepio, CBT-i Coach VA). Farmacoterapia (hipnóticos) puede ser útil corto plazo (<4 semanas) pero riesgo dependencia, tolerancia, efectos adversos a largo plazo.</p>
        
        <h3>¿La melatonina ayuda para dormir?</h3>
        <p>Depende del contexto. Melatonina es efectiva para: (1) Jet lag (tomar 0.5-5mg hora deseada dormir destino), (2) Trastorno fase sueño retrasada (tomar 2-3h pre-hora acostarse deseada), (3) Trabajadores turnos (timing específico según rotación). Para insomnio primario, eficacia es modesta (reduce latencia ~7 min, aumenta duración ~8 min según meta-análisis). Melatonina NO es sedante potente como muchos creen - es cronobiótico (señal timing, no knock-out). Dosis fisiológicas 0.3-1mg frecuentemente tan efectivas como dosis farmacológicas 3-10mg. Generalmente segura corto-medio plazo, efectos adversos mínimos. No reemplaza higiene sueño o TCC-I para insomnio crónico.</p>
        
        <h3>¿Cómo afecta el trabajo por turnos al sueño y salud cardiovascular?</h3>
        <p>Trabajo por turnos (especialmente nocturnos y rotatorios) desalinea profundamente ritmo circadiano con ciclo luz-oscuridad natural, resultando en: privación sueño crónica (1-2h menos vs trabajadores diurnos), mala calidad sueño (sueño diurno más fragmentado, menos profundo), ↑ 40% riesgo enfermedad cardiovascular, ↑ síndrome metabólico, ↑ obesidad/diabetes, ↑ cáncer (IARC clasificó trabajo turnos "probable carcinógeno"). Mitigación: mantener horario consistente días libres (aunque sea nocturno), exposición luz brillante durante turno, oscuridad completa para dormir diurno (blackout curtains críticas), siestas estratégicas pre-turno (1-2h), melatonina timing apropiado, nutrición saludable (evitar snacking nocturno excesivo).</p>
        
        <h3>¿Debo consultar médico si ronco fuertemente?</h3>
        <p>SÍ, especialmente si: ronquidos fuertes con pausas respiratorias observadas, somnolencia diurna excesiva, despertares con jadeo/asfixia, hipertensión resistente, o factores riesgo apnea (obesidad, cuello grueso >43cm hombres/>41cm mujeres, edad >50). Apnea obstructiva del sueño (AOS) afecta 15-30% adultos pero 80% no están diagnosticados. AOS no tratada aumenta dramáticamente riesgo hipertensión (2-3×), stroke (3-4×), IAM (2×), fibrilación atrial (2-4×), mortalidad cardiovascular (30-40%). Screening con cuestionario STOP-BANG (≥3 positivos = alto riesgo). Diagnóstico definitivo requiere polisomnografía. Tratamiento CPAP reduce eventos respiratorios >90% y mejora outcomes cardiovasculares.</p>
        
