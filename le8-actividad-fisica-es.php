<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>Meta-análisis Actividad Física y Mortalidad CV (2019)</h4>
<p><strong>Análisis:</strong> 44 estudios prospectivos, 1.47 millones participantes</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li>35% reducción riesgo enfermedad cardiovascular (actividad alta vs sedentarismo)</li>
<li>20% reducción mortalidad por todas las causas</li>
<li>Relación dosis-respuesta: Cada 1 MET-hora/semana adicional = 3% ↓ riesgo CV</li>
<li>Beneficio hasta ~3-5× recomendación mínima (750 min/semana moderada)</li>
<li>Beneficio significativo incluso con <150 min/semana (60-90 min = 15-20% ↓ mortalidad)</li>
</ul>
</div>

<div class="evidence-box">
<h4>INTERHEART Study (2004)</h4>
<p><strong>Diseño:</strong> Caso-control, 52 países, 29,000 participantes</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li>Actividad física regular reduce 20% riesgo infarto agudo miocardio</li>
<li>Beneficio consistente en todos los países, etnias, géneros</li>
<li>Efecto protector independiente de otros factores de riesgo</li>
<li>Actividad física ligera-moderada ya confiere protección significativa</li>
</ul>
</div>

<div class="evidence-box">
<h4>Estudio de Pasos y Mortalidad (JAMA 2020)</h4>
<p><strong>Diseño:</strong> Cohorte prospectiva, 4,840 adultos, seguimiento 10 años</p>
<p><strong>Hallazgos por Pasos Diarios:</strong></p>
<ul>
<li><strong>8,000+ pasos/día:</strong> 51% ↓ mortalidad vs <4,000 pasos</li>
<li><strong>12,000+ pasos/día:</strong> 65% ↓ mortalidad</li>
