<h2 id="tipos">Tipos de Actividad Física</h2>

<h3>🚶 Actividad Física Moderada</h3>

<p><strong>Definición:</strong> Actividad que aumenta frecuencia cardíaca y respiración, pero permite mantener una conversación.</p>

<p><strong>Indicador práctico:</strong> "Talk test" - puedes hablar pero no cantar durante la actividad.</p>

<div class="activity-grid">
<div class="activity-card">
<h4>Ejercicios Cardiovasculares</h4>
<ul>
<li>Caminar rápido (5-6 km/h)</li>
<li>Ciclismo recreacional (<16 km/h)</li>
<li>Natación recreacional</li>
<li>Baile social</li>
<li>Aquaeróbicos</li>
<li>Yoga vinyasa</li>
</ul>
<p><strong>Gasto energético:</strong> 3-6 METs</p>
</div>

<div class="activity-card">
<h4>Actividades Cotidianas</h4>
<ul>
<li>Jardinería activa (cavar, plantar)</li>
<li>Limpiar casa vigorosamente</li>
<li>Lavar el auto a mano</li>
<li>Jugar activamente con niños</li>
<li>Subir escaleras (ritmo normal)</li>
<li>Pasear al perro (paso rápido)</li>
</ul>
<p><strong>Beneficio:</strong> Contabiliza para meta semanal</p>
</div>

<div class="activity-card">
<h4>Deportes Recreacionales</h4>
<ul>
<li>Tenis dobles</li>
<li>Golf (caminando, cargando palos)</li>
<li>Volleyball recreacional</li>
<li>Patinaje recreacional</li>
<li>Kayak/Canotaje</li>
<li>Esquí acuático</li>
</ul>
<p><strong>Ventaja:</strong> Componente social aumenta adherencia</p>
</div>
</div>

<h3>🏃 Actividad Física Vigorosa</h3>

<p><strong>Definición:</strong> Actividad que aumenta sustancialmente frecuencia cardíaca y respiración, dificultando mantener conversación.</p>

<p><strong>Indicador práctico:</strong> Solo puedes decir algunas palabras sin pausar para respirar.</p>

<div class="activity-grid">
<div class="activity-card">
