<h2 id="estrategias">Estrategias para Aumentar Actividad Física</h2>

<h3>🎯 Enfoque Progresivo (Para Personas Sedentarias)</h3>

<div class="progression-plan">
<h4>Fase 1: Semanas 1-2 (Establecer Base)</h4>
<p><strong>Meta:</strong> 30 minutos/semana actividad moderada</p>
<ul>
<li>Caminar 10 minutos, 3 días/semana</li>
<li>Enfoque: Consistencia, no intensidad</li>
<li>Tracking: App pedómetro, baseline pasos/día</li>
<li>Expectativa: 10-20 puntos Life's Essential 8™</li>
</ul>

<h4>Fase 2: Semanas 3-4 (Incremento Gradual)</h4>
<p><strong>Meta:</strong> 60 minutos/semana</p>
<ul>
<li>Caminar 15 minutos, 4 días/semana</li>
<li>Incremento: 10% duración por semana (regla del 10%)</li>
<li>Añadir: 1 sesión de ejercicios de fuerza con peso corporal</li>
<li>Expectativa: 30-40 puntos Life's Essential 8™</li>
</ul>

<h4>Fase 3: Semanas 5-8 (Diversificación)</h4>
<p><strong>Meta:</strong> 100 minutos/semana</p>
<ul>
<li>Caminar 20 minutos, 5 días/semana</li>
<li>Introducir: 1 sesión actividad vigorosa 10-15 min</li>
<li>Explorar: Nuevas modalidades (natación, ciclismo, clases grupales)</li>
<li>Expectativa: 60-70 puntos Life's Essential 8™</li>
</ul>

<h4>Fase 4: Semanas 9-12 (Alcanzar Meta)</h4>
<p><strong>Meta:</strong> 150 minutos/semana moderada</p>
<ul>
<li>30 minutos, 5 días/semana actividad moderada</li>
<li>O 25 minutos vigorosa, 3 días + 2 sesiones fuerza</li>
<li>Establecer: Rutina sostenible a largo plazo</li>
<li>Expectativa: <strong>100 puntos Life's Essential 8™</strong></li>
</ul>
</div>

<h3>💡 Estrategias de Adherencia Basadas en Evidencia</h3>

<div class="adherence-strategies">
<div class="strategy-card">
<h4>1. Planificación de Implementación</h4>
<p><strong>Concepto:</strong> Especificar cuándo, dónde y cómo ejercitarás</p>
<p><strong>Formato IF-THEN:</strong></p>
<ul>
<li>"Si es lunes a las 7am, entonces caminaré 30 min en el parque"</li>
<li>"Si termino de trabajar, entonces haré 20 min de yoga en casa"</li>
<li>"Si es sábado por la mañana, entonces iré a nadar 45 min"</li>
</ul>
<p><strong>Evidencia:</strong> Duplica tasas de adherencia vs intención general</p>
</div>

<div class="strategy-card">
<h4>2. Tracking y Auto-Monitoreo</h4>
<p><strong>Herramientas:</strong></p>
<ul>
<li>Wearables: Apple Watch, Fitbit, Garmin</li>
<li>Apps: Strava, Nike Run Club, MyFitnessPal</li>
<li>Diario de ejercicio: Registro manual</li>
</ul>
<p><strong>Métricas clave:</strong></p>
<ul>
<li>Minutos actividad moderada/semana</li>
<li>Minutos actividad vigorosa/semana</li>
<li>Pasos diarios (meta: 7,500-10,000)</li>
<li>Frecuencia cardíaca durante ejercicio</li>
</ul>
<p><strong>Evidencia:</strong> Auto-monitoreo aumenta actividad física 30%</p>
</div>

<div class="strategy-card">
<h4>3. Apoyo Social</h4>
<p><strong>Modalidades:</strong></p>
<ul>
<li>Compañero de ejercicio (accountability partner)</li>
<li>Grupos de caminata/running</li>
<li>Clases grupales (spinning, zumba, CrossFit)</li>
<li>Competencias amistosas (challenges con amigos)</li>
<li>Comunidades online (Strava clubs, grupos Facebook)</li>
</ul>
<p><strong>Evidencia:</strong> Apoyo social predice adherencia a largo plazo</p>
</div>

<div class="strategy-card">
<h4>4. Reducción de Barreras</h4>
<p><strong>Barrera: Falta de tiempo</strong></p>
<ul>
<li>Solución: Fragmentar en sesiones 10 min (3×10 = 30 min)</li>
<li>Ejercicio en casa (elimina viaje a gimnasio)</li>
<li>HIIT (15-20 min equivale a 30-40 min moderado)</li>
</ul>

<p><strong>Barrera: Costo</strong></p>
<ul>
<li>Solución: Actividades gratuitas (caminar, correr, YouTube workouts)</li>
<li>Parques públicos con equipamiento</li>
<li>Apps gratuitas con programas estructurados</li>
</ul>

<p><strong>Barrera: Falta de motivación</strong></p>
<ul>
<li>Solución: Actividades placenteras (bailar, deportes recreacionales)</li>
<li>Música/podcasts durante ejercicio</li>
<li>Recompensas tangibles por adherencia</li>
</ul>
</div>

<div class="strategy-card">
<h4>5. Integración con Vida Diaria (Actividad Física Incidental)</h4>
<p><strong>Oportunidades diarias:</strong></p>
<ul>
<li>Usar escaleras en lugar de ascensor (2 pisos = ~20 kcal)</li>
<li>Estacionar lejos del destino (10 min extra caminata/día)</li>
<li>Caminar durante llamadas telefónicas</li>
<li>Reuniones caminando (walking meetings)</li>
<li>Levantarse cada hora en trabajo sedentario (2 min movimiento)</li>
<li>Ciclismo/caminata como transporte activo</li>
</ul>
<p><strong>Impacto:</strong> 30-60 min adicionales actividad ligera-moderada/día</p>
</div>
