        <h3>¿Puedo fragmentar los 150 minutos semanales en sesiones cortas?</h3>
        <p>Sí, absolutamente. La evidencia demuestra que fragmentar la actividad física en sesiones de al menos 10 minutos proporciona beneficios cardiovasculares similares a sesiones continuas más largas. Por ejemplo, 3 sesiones de 10 minutos distribuidas en el día equivalen a 1 sesión de 30 minutos para alcanzar la meta diaria. Esto hace la recomendación mucho más factible para personas con agendas apretadas.</p>
        
        <h3>¿Qué cuenta como actividad física moderada vs vigorosa?</h3>
        <p>Use el "talk test": actividad moderada permite mantener conversación pero no cantar (caminar rápido, ciclismo recreacional, baile); actividad vigorosa solo permite decir algunas palabras sin pausar para respirar (correr, natación vigorosa, deportes competitivos). Alternativamente, moderada = 64-76% frecuencia cardíaca máxima, vigorosa = 77-95% FCmax. Un MET (equivalente metabólico) de 3-6 es moderado, >6 es vigoroso.</p>
        
        <h3>¿Los pasos diarios cuentan para la meta de actividad física?</h3>
        <p>Sí, los pasos diarios cuentan como actividad física si se realizan a intensidad moderada. Aproximadamente 100 pasos/minuto equivale a actividad moderada. Para alcanzar 150 minutos semanales mediante caminata, necesitarías ~15,000 pasos extras por semana (2,100-2,500 pasos/día adicionales al baseline), sumados a pasos de actividades cotidianas. La meta general de 7,500-10,000 pasos/día total típicamente incluye suficiente actividad moderada para beneficio cardiovascular.</p>
        
        <h3>¿Es mejor hacer ejercicio en la mañana o en la tarde?</h3>
        <p>El mejor momento es cuando puedes mantener consistencia a largo plazo. Dicho esto, evidencia muestra pequeñas diferencias: ejercicio matutino puede facilitar adherencia (menos interferencias), mejorar control glucémico en diabéticos, y optimizar ritmo circadiano. Ejercicio vespertino puede permitir mayor rendimiento físico (temperatura corporal más alta, músculo Algunos estudios sugieren ejercicio post-cena ayuda control glucémico nocturno. La consistencia horaria (mismo momento cada día) potencia beneficios al entrenar el ritmo circadiano.</p>
        
        <h3>¿Necesito evaluación médica antes de comenzar un programa de ejercicio?</h3>
        <p>Depende de tu estado de salud y la intensidad planificada. Personas sanas <40 años sin factores de riesgo CV pueden comenzar actividad moderada sin evaluación médica. Evaluación recomendada si: ≥40 años con ≥2 factores de riesgo CV (hipertensión, diabetes, tabaquismo, dislipidemia), enfermedad cardiovascular conocida, síntomas cardiopulmonares (dolor torácico, disnea desproporcionada, síncope), o planeas iniciar actividad vigorosa siendo previamente sedentario. Consulta con médico ante duda.</p>
        
        <h3>¿El entrenamiento de fuerza cuenta para la meta de 150 minutos?</h3>
        <p>El entrenamiento de fuerza tradicional (pesas, máquinas) generalmente no cuenta para los 150 minutos de actividad aeróbica porque típicamente no eleva frecuencia cardíaca de manera sostenida. Sin embargo, modalidades como circuit training, CrossFit, y entrenamientos funcionales de alta intensidad SÍ cuentan si mantienen FC en zona moderada-vigorosa. Life's Essential 8™ recomienda entrenamiento de fuerza 2+ días/semana como complemento (no sustituto) de actividad aeróbica, dada su importancia para salud metabólica, ósea y funcional.</p>
        
        <h3>¿Cuánto tiempo toma ver beneficios cardiovasculares del ejercicio?</h3>
        <p>Los beneficios cardiovasculares comienzan sorprendentemente rápido: reducción presión arterial detectable en 2-4 semanas, mejora sensibilidad insulina en 3-7 días de ejercicio consistente, mejora perfil lipídico (HDL, triglicéridos) en 4-8 semanas, aumento VO2max en 8-12 semanas. Adaptaciones estructurales cardíacas (hipertrofia ventricular fisiológica, aumento volumen sistólico) toman 3-6 meses. Reducción mortalidad cardiovascular observable en estudios epidemiológicos dentro del primer año de actividad física regular.</p>
        
        <h3>¿Qué hago si tengo dolor articular que limita el ejercicio?</h3>
        <p>Prioriza actividades de bajo impacto: natación/aquaeróbicos (elimina impacto gravitacional), ciclismo estacionario, elíptica, remo. Considera ejercicio en agua que permite rango completo de movimiento sin dolor. Entrenamiento de fuerza bien supervisado puede fortalecer musculatura de soporte articular reduciendo dolor a largo plazo. Fisioterapia para corregir biomecánica. Si obesidad contribuye, pérdida de peso 5-10% puede reducir dramáticamente carga articular y mejorar dolor. Nunca ejercitar "a través del dolor agudo" - ajustar modalidad/intensidad según tolerancia.</p>
        
        <h3>¿El ejercicio puede revertir enfermedad cardiovascular establecida?</h3>
        <p>El ejercicio no "revierte" completamente enfermedad cardiovascular establecida (ej. aterosclerosis coronaria), pero sí puede estabilizar placas, mejorar función endotelial, reducir progresión, y disminuir dramáticamente riesgo de eventos futuros. En insuficiencia cardíaca, el ejercicio mejora clase funcional, reduce hospitalizaciones, y puede mejorar fracción de eyección en algunos pacientes. Rehabilitación cardíaca post-IAM reduce mortalidad 26%. El ejercicio es componente esencial de prevención secundaria, con beneficios que complementan terapia farmacológica.</p>
        
