<h3>💪 Entrenamiento de Fuerza (Recomendación Adicional)</h3>

<p><strong>Meta complementaria:</strong> ≥2 días/semana trabajando todos los grupos musculares principales</p>

<div class="strength-training">
<h4>Beneficios Cardiovasculares del Entrenamiento de Fuerza</h4>
<ul>
