<h1>Actividad Física: La Métrica #2 de Life's Essential 8™</h1>

<p>La <strong>actividad física</strong> es la segunda métrica esencial para salud cardiovascular con un <strong>puntaje promedio poblacional de 51.6/100 puntos</strong>, indicando que aproximadamente la mitad de la población no alcanza los niveles recomendados de actividad física para salud cardiovascular óptima.</p>

<p>La evidencia científica es inequívoca: <strong>la actividad física regular reduce 30-35% el riesgo de enfermedad cardiovascular</strong>, 20% la mortalidad por todas las causas, y mejora múltiples marcadores cardiometabólicos. Cada incremento de 1,000 pasos/día se asocia con 6-10% reducción de mortalidad cardiovascular.</p>

