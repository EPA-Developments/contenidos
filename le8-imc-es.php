<h4>5. Índice de Adiposidad Visceral (VAI)</h4>

<p><strong>Estimación indirecta de disfunción adiposa visceral usando:</strong></p>
<ul>
<li>IMC</li>
<li>Circunferencia cintura</li>
<li>Triglicéridos</li>
<li>HDL-colesterol</li>
</ul>

<p><strong>Fórmulas complejas</strong> (calculadoras online disponibles)</p>

<p><strong>Interpretación:</strong></p>
<ul>
<li>VAI <1.5: Función adiposa normal</li>
<li>VAI 1.5-2.5: Disfunción moderada</li>
<li>VAI >2.5: Disfunción severa → ↑↑ riesgo metabólico/CV</li>
</ul>

<p><strong>Ventaja:</strong> Captura función metabólica, no solo cantidad grasa</p>
</div>

<h3>🎯 Enfoque Integrado Recomendado</h3>

<div class="integrated-approach">
<p><strong>Para evaluación completa riesgo cardiometabólico:</strong></p>

<ol>
<li><strong>IMC</strong> - Screening inicial poblacional</li>
<li><strong>+ Circunferencia cintura</strong> - Si IMC 23-35 (zona gris)</li>
<li><strong>+ Perfil metabólico:</strong> Glucosa, HbA1c, lípidos, PA</li>
<li><strong>+ % Grasa corporal</strong> (opcional) - Si discrepancia IMC/riesgo clínico</li>
<li><strong>Estratificación final:</strong> Combinación antropometría + marcadores metabólicos</li>
</ol>

<p><strong>Ejemplo estratificación:</strong></p>
<ul>
<li>Persona IMC 28, cintura 95 cm, glucosa/lípidos/PA normales → <strong>Riesgo moderado</strong> - intervención estilo de vida</li>
<li>Persona IMC 23, cintura 92 cm, pre-diabetes, TG altos → <strong>Riesgo alto</strong> - intervención agresiva estilo vida + considerar farmacoterapia</li>
</ul>
</div>

