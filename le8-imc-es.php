<h4>🚨 Crisis de Obesidad Infantil</h4>
<p><strong>Datos alarmantes:</strong></p>
<ul>
<li><strong>Prevalencia triplicada desde 1970:</strong> 5% → 20% obesidad pediátrica</li>
<li><strong>Disparidades:</strong> Hispanos 26%, Afroamericanos 24%, Asiáticos 9%, Blancos 17%</li>
<li><strong>Obesidad severa:</strong> Categoría creciente más rápido (ahora ~6% niños)</li>
<li><strong>Edad temprana:</strong> 13.9% preescolares (2-5 años) con sobrepeso/obesidad</li>
<li><strong>Persistencia:</strong> 80% adolescentes obesos → adultos obesos</li>
</ul>

<p><strong>Consecuencias:</strong></p>
<ul>
<li>↑ Diabetes tipo 2 pediátrica (antes rarísima, ahora epidémica)</li>
<li>Hipertensión pediátrica (3-5% niños, 25-30% obesos)</li>
<li>Dislipidemia (50-60% niños obesos)</li>
<li>Hígado graso no alcohólico (NAFLD) - 40-70% niños obesos</li>
<li>Apnea del sueño, problemas ortopédicos, acoso escolar, depresión</li>
<li>Aterosclerosis subclínica detectable en adolescencia (engrosamiento íntima-media carotídea)</li>
</ul>
