<div class="imc-calculation">
<h4>📐 Cálculo del IMC</h4>

<p><strong>Fórmula:</strong> IMC = Peso (kg) / [Altura (m)]²</p>

<h5>Ejemplos:</h5>
<ul>
<li><strong>Persona 1:</strong> 70 kg, 1.75 m → IMC = 70 / (1.75)² = 70 / 3.06 = <strong>22.9 kg/m²</strong> (Peso saludable, 100 puntos)</li>
<li><strong>Persona 2:</strong> 85 kg, 1.70 m → IMC = 85 / (1.70)² = 85 / 2.89 = <strong>29.4 kg/m²</strong> (Sobrepeso, ~55 puntos)</li>
<li><strong>Persona 3:</strong> 100 kg, 1.65 m → IMC = 100 / (1.65)² = 100 / 2.72 = <strong>36.7 kg/m²</strong> (Obesidad II, ~20 puntos)</li>
</ul>

<h5>Conversión Sistema Imperial:</h5>
<p>IMC = [Peso (lb) / Altura² (in)] × 703</p>
<p><strong>Ejemplo:</strong> 180 lb, 68 in → IMC = (180 / 68²) × 703 = (180 / 4624) × 703 = <strong>27.4 kg/m²</strong></p>
</div>

