<h4>Obesidad "Metabólicamente Sana" vs Peso "Normal" Metabólicamente Enfermo</h4>

<ul>
<li><strong>Obesidad metabólicamente sana (MHO):</strong>
  <ul>
    <li>10-30% personas obesas (IMC ≥30)</li>
    <li>Sin resistencia insulina, dislipidemia, hipertensión, inflamación elevada</li>
    <li>Grasa predominantemente subcutánea (no visceral)</li>
    <li><strong>Debate:</strong> ¿Verdaderamente "sana"? Estudios longitudinales muestran muchos transicionan a metabólicamente enferma con tiempo</li>
    <li>Riesgo CV intermedio (entre peso normal sano y obeso metabólicamente enfermo)</li>
  </ul>
</li>

<li><strong>Peso normal metabólicamente obeso (MONW):</strong>
  <ul>
    <li>10-20% adultos IMC <25</li>
    <li>Resistencia insulina, dislipidemia aterogénica, inflamación</li>
    <li>Grasa visceral elevada (TOFI: Thin Outside, Fat Inside)</li>
    <li>Riesgo diabetes/CV similar a personas obesas tradicionales</li>
    <li>Frecuente en asiáticos, sedentarios, genética desfavorable</li>
  </ul>
</li>
</ul>

<p><strong>Implicancia clínica:</strong> IMC solo es insuficiente - evaluación metabólica integral necesaria independiente de IMC.</p>
</div>

