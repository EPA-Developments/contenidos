<h4>3. Relación Cintura-Altura (RCA)</h4>

<p><strong>RCA = Circunferencia cintura (cm) / Altura (cm)</strong></p>

<p><strong>Regla simple:</strong> <strong>Cintura debe ser <50% de la altura</strong></p>

<ul>
<li><strong>RCA <0.50:</strong> Saludable</li>
<li><strong>RCA 0.50-0.59:</strong> Precaución - riesgo aumentado</li>
<li><strong>RCA ≥0.60:</strong> Alto riesgo - acción necesaria</li>
</ul>

<p><strong>Ventaja:</strong> Umbral universal (no varía por sexo/etnia), fácil comunicación pacientes</p>

<p><strong>Ejemplo:</strong> Persona 1.75 m altura → cintura debe ser <87.5 cm (idealmente <80 cm)</p>

