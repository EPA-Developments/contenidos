    <li>Fuentes: Verduras, frutas enteras, granos integrales, legumbres, nueces</li>
  </ul>
</li>

<li><strong>Hidratación:</strong>
  <ul>
    <li>Beber agua pre-comidas (500 ml) → ↓ ingesta 13% (estudio RCT)</li>
