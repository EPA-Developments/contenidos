<h4>Pérdida de Peso Sostenida vs Yo-Yo</h4>

<ul>
<li><strong>Ciclaje de peso (yo-yo):</strong> Pérdidas/ganancias repetidas
  <ul>
    <li>Asociado con ↑ mortalidad CV (debatido - posible sesgo por confusión)</li>
    <li>Deterioro composición corporal (↓ masa muscular, ↑ % grasa con cada ciclo)</li>
    <li>Daño psicológico (frustración, pérdida autoeficacia)</li>
  </ul>
</li>
<li><strong>Mantenimiento:</strong> El verdadero desafío
  <ul>
    <li>80% personas recuperan peso perdido en 1 año</li>
    <li>Solo 20% mantienen ≥10% pérdida a 1 año</li>
