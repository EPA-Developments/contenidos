<li><strong>Re-ganancia peso:</strong> 20-30% pacientes recuperan peso significativo largo plazo</li>
<li><strong>Cambios psicológicos:</strong> 20% desarrollan/empeoran depresión, trastornos alimentarios post-cirugía</li>
<li><strong>Piel redundante:</strong> Frecuentemente requiere cirugías reconstructivas subsecuentes</li>
</ul>

