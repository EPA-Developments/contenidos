<h3>🏃 Actividad Física para Pérdida de Peso</h3>

<div class="exercise-weight-loss">
<h4>Rol de la Actividad Física</h4>

<p><strong>Realidad:</strong> Ejercicio SOLO típicamente produce pérdida modesta (1-3 kg a 6 meses)</p>

<p><strong>¿Por qué?</strong></p>
<ul>
<li>Gasto calórico ejercicio frecuentemente sobreestimado</li>
<li>Ejemplo: Correr 5 km (30 min) = ~300 kcal quemadas = 1 muffin = fácilmente compensado comiendo</li>
<li>Compensación conductual: "Hice ejercicio, merezco postre" → ingesta ↑</li>
<li>Adaptación metabólica: Cuerpo reduce gasto no-ejercicio (NEAT) parcialmente</li>
</ul>

<p><strong>PERO:</strong> <strong>Ejercicio es CRÍTICO para mantenimiento peso perdido</strong></p>

<p><strong>National Weight Control Registry (>10,000 personas que mantuvieron ≥30 lb pérdida ≥1 año):</strong></p>
<ul>
<li>90% reportan actividad física regular</li>
<li>Promedio: <strong>60-90 min/día actividad moderada</strong> (sustancialmente > recomendación general 150 min/semana)</li>
<li>Mayoría: Caminar como ejercicio principal</li>
</ul>

