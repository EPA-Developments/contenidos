<h2 id="limitaciones">Limitaciones del IMC y Medidas Complementarias</h2>

<h3>⚠️ Limitaciones Importantes del IMC</h3>

<div class="bmi-limitations">
<p>El IMC es una herramienta de screening poblacional útil pero imperfecta. <strong>NO distingue masa grasa de masa muscular</strong> ni captura distribución de grasa corporal, crítica para riesgo cardiovascular.</p>

