<h1>Índice de Masa Corporal (IMC): La Métrica #5 de Life's Essential 8™</h1>

<p>El <strong>Índice de Masa Corporal (IMC)</strong> es la quinta métrica esencial para salud cardiovascular, representando una medida proxy de adiposidad corporal calculada como <strong>peso (kg) / altura² (m²)</strong>. Con un <strong>puntaje promedio poblacional de 57.5/100</strong>, el IMC refleja la epidemia global de sobrepeso/obesidad que afecta aproximadamente <strong>70% de adultos en países desarrollados</strong>.</p>

<p>La evidencia es contundente: <strong>cada incremento de 5 kg/m² en IMC aumenta 27% el riesgo de mortalidad cardiovascular</strong>. La obesidad (IMC ≥30) se asocia con hipertensión (3× riesgo), diabetes tipo 2 (7× riesgo), dislipidemia aterogénica, apnea del sueño, hígado graso, y estado proinflamatorio crónico. Sin embargo, <strong>pérdida de peso sostenida de 5-10% reduce dramáticamente riesgo cardiovascular</strong>, mejorando presión arterial, glucemia, perfil lipídico y marcadores inflamatorios.</p>

