<h4>Estrategias Prácticas de Reducción Calórica</h4>

<ol>
<li><strong>Control de porciones:</strong>
  <ul>
    <li>Platos más pequeños (reduce porción 20-30% sin sentir privación)</li>
    <li>Método "plato saludable": 1/2 verduras, 1/4 proteína, 1/4 carbohidrato complejo</li>
    <li>Medir porciones inicialmente (aprender tamaños reales)</li>
  </ul>
</li>

<li><strong>Densidad energética:</strong>
  <ul>
    <li>Priorizar alimentos <strong>bajo</strong> densidad energética (kcal/g): Frutas, verduras, sopas broth-based</li>
    <li>Limitar <strong>alto</strong> densidad: Fritos, snacks procesados, dulces (fácil sobre-consumo calórico)</li>
    <li>Ejemplo: 100 kcal = 500 g brócoli vs 10 g aceite → saciedad dramáticamente diferente</li>
  </ul>
</li>

<li><strong>Proteína adecuada:</strong>
  <ul>
    <li>Meta: 1.2-1.6 g/kg peso ideal (↑ vs RDA 0.8 g/kg)</li>
    <li>Preserva masa muscular durante pérdida peso</li>
    <li>Mayor saciedad (termogénesis inducida dieta 20-30% vs 5-10% carbohidratos)</li>
    <li>Fuentes: Carnes magras, pescado, huevos, lácteos bajos grasa, legumbres, tofu</li>
  </ul>
</li>

