<h3>🍽️ Intervenciones Dietéticas</h3>

<div class="dietary-interventions">
<h4>Principio Fundamental: Déficit Calórico</h4>

<p><strong>Termodinámica básica:</strong> Pérdida de peso requiere gasto energético > ingesta energética</p>

<p><strong>Déficit recomendado:</strong> 500-750 kcal/día → 0.5-1.0 kg/semana pérdida</p>

<p><strong>Cálculo necesidades:</strong></p>
<ul>
<li><strong>Gasto energético basal (GEB):</strong> Ecuación Harris-Benedict o Mifflin-St Jeor</li>
<li><strong>Factor actividad:</strong> Sedentario 1.2, Ligera 1.375, Moderada 1.55, Intensa 1.725</li>
<li><strong>Gasto total (GET):</strong> GEB × Factor actividad</li>
<li><strong>Meta calórica:</strong> GET - 500-750 kcal</li>
</ul>

<p><strong>Ejemplo:</strong></p>
<ul>
<li>Mujer 35 años, 80 kg, 1.65 m, actividad ligera</li>
<li>GEB (Mifflin-St Jeor) = (10 × 80) + (6.25 × 165) - (5 × 35) - 161 = 1,510 kcal</li>
<li>GET = 1,510 × 1.375 = 2,076 kcal</li>
<li>Meta pérdida peso = 2,076 - 600 = <strong>1,476 kcal/día</strong></li>
</ul>

