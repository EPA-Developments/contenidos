        <h3>¿Es el IMC una medida precisa de salud? Soy muy musculoso y mi IMC dice "sobrepeso".</h3>
        <p>El IMC tiene limitaciones importantes - no distingue masa muscular de grasa ni captura distribución grasa corporal. Atletas/personas muy musculosas frecuentemente tienen IMC 25-30 ("sobrepeso") con composición corporal saludable. En estos casos, medidas complementarias son esenciales: circunferencia cintura (óptimo <94 cm hombres, <80 cm mujeres), % grasa corporal (DEXA, bio-impedancia), y perfil metabólico (glucosa, lípidos, PA). Si IMC elevado pero cintura normal, perfil metabólico excelente, y masa muscular alta, el IMC es engañoso. Conversación con médico recomendada para evaluación integral.</p>
<h3>¿Cuánto peso debo perder para ver beneficios de salud?</h3>
