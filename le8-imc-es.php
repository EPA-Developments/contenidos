</div>

<div class="evidence-box">
<h4>DPP (Diabetes Prevention Program) - Prevención Diabetes con Pérdida Peso</h4>
<p><strong>Diseño:</strong> RCT, 3,234 adultos prediabéticos (IMC ≥24, ≥22 asiáticos), 2.8 años promedio</p>
<p><strong>Intervenciones:</strong></p>
<ul>
<li><strong>Estilo vida intensivo:</strong> Meta 7% pérdida peso + 150 min/semana ejercicio</li>
<li><strong>Metformina:</strong> 850 mg BID</li>
<li><strong>Placebo</strong></li>
</ul>
<p><strong>Resultados - Incidencia Diabetes:</strong></p>
<table>
<tr><td><strong>Estilo vida:</strong></td><td>58% ↓ vs placebo (NNT=7)</td></tr>
<tr><td><strong>Metformina:</strong></td><td>31% ↓ vs placebo (NNT=14)</td></tr>
</table>
<p><strong>Pérdida peso promedio (año 1):</strong> Estilo vida -7 kg, Metformina -2 kg, Placebo -0.5 kg</p>
<p><strong>Seguimiento 10 años (DPPOS):</strong> Reducción diabetes sostenida: 34% estilo vida, 18% metformina</p>
<p><strong>Costo-efectividad:</strong> Intervención estilo vida $1,100/QALY ganado (altamente costo-efectivo)</p>
<p><strong>Mensaje:</strong> Pérdida peso modesta (5-7%) con ejercicio DUPLICA eficacia vs metformina para prevención diabetes</p>
</div>

<h3>Mecanismos Fisiopatológicos Obesidad → Enfermedad CV</h3>

<div class="mechanisms-grid">
<div class="mechanism">
<h4>🔥 Inflamación Crónica de Bajo Grado</h4>
<ul>
<li>Tejido adiposo = órgano endocrino activo</li>
<li>Adipocitos hipertrofiados → hipoxia → muerte celular → infiltración macrófagos</li>
<li>Secreción citoquinas: TNF-α, IL-6, IL-1β, MCP-1</li>
<li>↑ PCR hepática (respuesta fase aguda)</li>
<li>Estado proinflamatorio sistémico → progresión aterosclerosis</li>
<li>Cada 10 kg adiposidad: ↑ 30% PCR circulante</li>
</ul>
</div>

<div class="mechanism">
<h4>📊 Resistencia a la Insulina</h4>
<ul>
<li>Adiposidad visceral → ácidos grasos libres portal → hígado</li>
<li>Acumulación lípidos ectópicos (hígado, músculo, páncreas)</li>
<li>Interferencia señalización receptor insulina (IRS-1)</li>
<li>Hiperglucemia compensatoria → hiperinsulinemia</li>
<li>Glucotoxicidad + lipotoxicidad → daño células β páncreas</li>
<li>Progresión: Resistencia insulina → prediabetes → diabetes tipo 2</li>
<li>Riesgo diabetes: IMC 35-39.9 = 7.2× vs IMC <25</li>
</ul>
</div>

<div class="mechanism">
<h4>💉 Dislipidemia Aterogénica</h4>
<ul>
<li>↑ Producción VLDL hepática (resistencia insulina)</li>
<li>↑ Triglicéridos (hipertrigliceridemia)</li>
<li>↓ HDL-C (↑ catabolismo, transferencia lipídica CETP)</li>
<li>Partículas LDL pequeñas densas (más aterogénicas)</li>
<li>↑ ApoB (marcador partículas aterogénicas)</li>
<li>"Tríada aterogénica": ↑TG, ↓HDL, LDL pequeñas-densas</li>
</ul>
</div>

<div class="mechanism">
<h4>🩺 Hipertensión</h4>
<ul>
<li>↑ Actividad sistema simpático (adipocinas → centro vasomotor)</li>
<li>↑ Reabsorción renal sodio (insulina, leptina)</li>
<li>Activación RAAS (tejido adiposo produce angiotensinógeno)</li>
<li>Disfunción endotelial (↓ vasodilatación NO-dependiente)</li>
<li>Rigidez arterial (inflamación, AGEs)</li>
<li>Apnea sueño → hipoxia intermitente → activación simpática nocturna</li>
<li>Riesgo hipertensión: IMC >30 = 3.5× vs IMC <25</li>
</ul>
</div>

<div class="mechanism">
<h4>🫀 Efectos Cardíacos Estructurales</h4>
<ul>
<li>↑ Volumen circulante (expansión volumen plasma)</li>
<li>↑ Gasto cardíaco (perfundir mayor masa corporal)</li>
<li>↑ Precarga → dilatación VI</li>
<li>↑ Postcarga (hipertensión, rigidez arterial) → hipertrofia VI</li>
<li>Remodelado excéntrico inicialmente → concéntrico tardío</li>
<li>Disfunción diastólica (rigidez miocárdica, fibrosis)</li>
<li>Progresión insuficiencia cardíaca (HFpEF prevalente)</li>
<li>Infiltración grasa epicárdica → arritmias (FA)</li>
</ul>
</div>

<div class="mechanism">
<h4>🩸 Estado Protrombótico</h4>
<ul>
<li>↑ PAI-1 (inhibidor activador plasminógeno) → ↓ fibrinólisis</li>
<li>↑ Fibrinógeno</li>
<li>↑ Factor VII, VIII, von Willebrand</li>
<li>↑ Agregación plaquetaria</li>
<li>Balance hemostático desplazado hacia trombosis</li>
</ul>
</div>

<div class="mechanism">
<h4>🧬 Adipocinas Disfuncionales</h4>
<ul>
<li><strong>Leptina ↑:</strong> Resistencia leptina → pérdida efecto saciedad, efectos CV adversos (activación simpática, proliferación células músculo liso)</li>
<li><strong>Adiponectina ↓:</strong> Pérdida efectos anti-inflamatorios, sensibilizadores insulina, anti-aterogénicos</li>
<li><strong>Resistina ↑:</strong> Pro-inflamatoria, resistencia insulina</li>
<li><strong>Visfatina ↑:</strong> Pro-inflamatoria</li>
</ul>
</div>

<div class="mechanism">
<h4>🌬️ Apnea Obstructiva del Sueño</h4>
<ul>
<li>60-70% personas obesidad severa tienen AOS</li>
<li>Grasa perifaríngea → colapso vía aérea superior</li>
<li>Hipoxia intermitente → estrés oxidativo, inflamación, activación simpática</li>
<li>Fragmentación sueño → resistencia insulina</li>
<li>Circuito vicioso: Obesidad → AOS → fatiga → ↓ actividad → ↑ obesidad</li>
</ul>
</div>
</div>

<h2>Consideraciones Especiales por Población</h2>

<h3>👶 Niños y Adolescentes</h3>

<div class="pediatric-obesity">
<h4>Enfoque Preventivo Primario</h4>
<p><strong>Ventanas críticas:</strong></p>
<ul>
<li><strong>Prenatal:</strong> Diabetes gestacional, ganancia peso excesiva materna → obesidad infantil</li>
<li><strong>Infancia temprana (0-2 años):</strong> Lactancia materna protectora (↓ 15-25% riesgo obesidad), introducción sólidos apropiada</li>
<li><strong>Adiposity rebound (5-7 años):</strong> Rebote temprano predictor obesidad adulta</li>
<li><strong>Adolescencia:</strong> 80% adolescentes obesos → adultos obesos</li>
</ul>

<h4>Intervención Familiar Integral</h4>
<p><strong>Principios:</strong></p>
<ul>
<li>Enfoque <strong>familia completa</strong> (no aislar niño)</li>
<li>Cambios graduales, sostenibles</li>
<li>Lenguaje positivo ("hábitos saludables" no "dieta")</li>
<li>Modelar comportamiento (padres ejemplos)</li>
<li>Evitar estigmatización peso</li>
</ul>

<p><strong>Componentes evidencia:</strong></p>
<ol>
<li><strong>Dietéticos:</strong>
  <ul>
    <li>Eliminar bebidas azucaradas (impacto MAYOR - fácil reducción 200+ kcal/día)</li>
    <li>↑ Frutas/verduras (accesibles, visibles)</li>
    <li>Limitar ultra-procesados, comida rápida</li>
    <li>Comidas familiares regulares (5-7×/semana asociado ↓ obesidad)</li>
    <li>Control porciones apropiadas edad</li>
  </ul>
</li>
<li><strong>Actividad física:</strong>
  <ul>
    <li>60 min/día MÍNIMO (Life's Essential 8 Kids)</li>
    <li>Reducir tiempo pantalla <2h/día recreacional</li>
    <li>Juego activo libre (parques, bicicleta, deportes)</li>
    <li>Educación física escolar diaria (idealmente)</li>
    <li>Eliminar TVs de dormitorios (asociado ↑ obesidad 30%)</li>
  </ul>
</li>
<li><strong>Conductual:</strong>
  <ul>
    <li>Sueño adecuado (9-12h según edad) - asociación fuerte sueño ↓ ↔ obesidad</li>
    <li>Desayuno diario</li>
    <li>Mindful eating</li>
    <li>Recompensas NO alimentarias</li>
  </ul>
</li>
</ol>

<h4>Tratamiento Obesidad Pediátrica Establecida</h4>

<p><strong>Obesidad leve-moderada (95º-120% del 95º):</strong></p>
<ul>
<li>Intervención estilo vida familiar intensiva</li>
<li>Programas estructurados (6-12 meses)</li>
<li>Meta: Mantenimiento peso (IMC estable mientras crecen en altura)</li>
</ul>

<p><strong>Obesidad severa (≥120% del 95º O IMC ≥35):</strong></p>
<ul>
<li>Intervención multidisciplinaria (pediatra, nutricionista, psicólogo, ejercicio)</li>
<li><strong>Farmacoterapia (≥12 años con comorbilidades):</strong>
  <ul>
    <li>Orlistat (aprobado ≥12 años) - modesta eficacia</li>
    <li>Metformina (off-label) - si resistencia insulina/prediabetes</li>
    <li>GLP-1 agonistas (semaglutida aprobada FDA ≥12 años 2022) - promisoria</li>
  </ul>
</li>
<li><strong>Cirugía bariátrica (≥13-18 años con obesidad severa + comorbilidades):</strong>
  <ul>
    <li>Consideración casos selectos</li>
    <li>Cierre placas crecimiento idealmente</li>
    <li>Teen-LABS study: -27% peso a 3 años, remisión diabetes 86%, hipertensión 68%</li>
    <li>Preocupaciones: Adherencia suplementación, desarrollo psicológico, seguimiento largo plazo</li>
  </ul>
</li>
</ul>
</div>

<h3>🧓 Adultos Mayores (≥65 años)</h3>

<div class="elderly-obesity">
<h4>Paradoja Obesidad Geriátrica</h4>

<p><strong>Observación epidemiológica:</strong> En adultos >65 años, sobrepeso (IMC 25-30) asociado con MENOR mortalidad vs peso "normal" (IMC 20-25)</p>

<p><strong>Posibles explicaciones:</strong></p>
<ul>
<li><strong>Causalidad reversa:</strong> Enfermedades crónicas → pérdida peso no intencional → IMC bajo</li>
<li><strong>Reserva metabólica:</strong> Algo grasa protege durante enfermedades agudas (infecciones, cirugías)</li>
<li><strong>Sesgo sobrevivientes:</strong> Obesos susceptibles mueren antes de llegar a 65 años</li>
<li><strong>Sarcopenia enmascarada:</strong> IMC "normal" puede ocultar masa muscular muy baja</li>
</ul>

<p><strong>Implicancia clínica:</strong></p>
<ul>
<li>Umbrales IMC menos claros en >65 años</li>
<li>IMC 25-27 puede ser óptimo (vs 20-25 adultos jóvenes)</li>
<li>Enfoque pérdida peso debe ser <strong>individualizado</strong></li>
</ul>

<h4>Consideraciones Especiales Manejo Peso Geriátrico</h4>

<p><strong>Riesgos pérdida peso en ancianos:</strong></p>
<ul>
<li>↓ Masa muscular (sarcopenia) → fragilidad, caídas, pérdida independencia</li>
<li>↓ Densidad ósea (osteoporosis) → fracturas</li>
<li>Deficiencias nutricionales (especialmente proteína, vitamina D, calcio)</li>
</ul>

<p><strong>Estrategia segura si pérdida peso indicada:</strong></p>
<ul>
<li><strong>Meta modesta:</strong> 5-7% (vs 10% adultos jóvenes)</li>
<li><strong>Ritmo lento:</strong> 0.25-0.5 kg/semana (vs 0.5-1.0 kg/semana)</li>
<li><strong>Proteína alta:</strong> 1.0-1.2 g/kg/día (preservar músculo)</li>
<li><strong>+ Ejercicio resistencia OBLIGATORIO:</strong> 2-3×/semana (prevenir sarcopenia)</li>
<li><strong>Suplementación:</strong> Vitamina D + Calcio (proteger hueso)</li>
<li><strong>Monitoreo:</strong> DEXA al inicio y 6 meses (asegurar pérdida grasa > músculo)</li>
</ul>

<p><strong>Poblaciones ancianas donde NO recomendar pérdida peso:</strong></p>
<ul>
<li>Fragilidad establecida</li>
<li>Enfermedad terminal</li>
<li>Demencia avanzada</li>
<li>Pérdida peso no intencional reciente</li>
<li>IMC <23 kg/m²</li>
</ul>
</div>

