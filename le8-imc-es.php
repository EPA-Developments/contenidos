    <h3>¿Por qué es tan difícil mantener el peso perdido?</h3>
    <p>Múltiples mecanismos adaptativos conspiran contra mantenimiento: (1) ↓ Gasto energético basal 10-15% más de lo predicho por nueva masa corporal (adaptación metabólica), (2) ↑ Hambre hormonal (↑ grelina 15-20%, ↓ leptina, ↓ PYY), (3) ↓ Saciedad post-comida, (4) Cambios neurológicos (hipersensibilidad cerebro a alimentos palatables), (5) Factores ambientales (ultra-procesados omnipresentes, porciones grandes, sedentarismo incentivado). Mantenimiento exitoso requiere: actividad física sostenida (60-90 min/día), auto-monitoreo peso (semanal), vigilancia dietética continua, apoyo social/profesional. 80% personas recuperan peso en 1 año - esto refleja dificultad fisiológica/ambiental, NO falta voluntad.</p>
    
    <h3>¿Las dietas bajas en carbohidratos son mejores que las bajas en grasa?</h3>
    <p>Meta-análisis múltiples muestran: a corto plazo (3-6 meses), dietas bajas en carbohidratos producen ligeramente mayor pérdida peso (~2 kg más vs bajas en grasa). Sin embargo, a 12+ meses, diferencias se atenúan (<1 kg diferencia). Ambas funcionan SI producen déficit calórico sostenido. Bajas en carbohidratos ventajas: ↑ saciedad (proteína alta), ↑ HDL-C marcadamente, ↓ triglicéridos 30-50%, mejora glucémica diabéticos. Bajas en grasa ventajas: ↓ LDL-C, familiaridad/aceptabilidad cultural. El factor MÁS importante es adherencia - mejor dieta es la que puedes mantener a largo plazo. Enfoque calidad (alimentos integrales, ↓ ultra-procesados) > composición macronutriente específica.</p>
    
    <h3>¿Debería considerar medicación para pérdida de peso?</h3>
    <p>Farmacoterapia anti-obesidad está indicada si: IMC ≥30, O IMC ≥27 con comorbilidades (diabetes, hipertensión, dislipidemia, apnea sueño), Y tras 6 meses intervención estilo vida sin éxito adecuado. Medicaciones modernas (GLP-1 agonistas: semaglutida, tirzepatida) producen pérdida peso 15-20% - sustancialmente superior a generaciones previas. Son ADYUVANTES, no sustitutos de dieta/ejercicio. Requieren terapia crónica (peso se re-gana al descontinuar). Costo significativo ($1,000-1,500/mes), cobertura seguro variable. Conversación riesgo/beneficio con médico esencial. Si comorbilidades severas y fracaso terapias conductuales, farmacoterapia razonable considerar.</p>
    
    <h3>¿Es la cirugía bariátrica segura y efectiva?</h3>
    <p>Cirugía bariátrica (bypass gástrico, manga gástrica) es intervención MÁS efectiva para obesidad severa. Pérdida peso promedio 25-35% peso total (vs 5-10% dieta/ejercicio, 10-15% farmacoterapia). Beneficios: ↓ 29% mortalidad total, ↓ 53% mortalidad CV, remisión diabetes 72%, remisión hipertensión 68%, apnea sueño 85% (SOS Study, 20 años seguimiento). Mortalidad perioperatoria baja (0.1-0.5%), pero riesgos existen: complicaciones 2-5%, déficits nutricionales (requiere suplementación vitalicia), re-ganancia peso 20-30% pacientes largo plazo. Indicada IMC ≥40, O IMC ≥35 con comorbilidades severas, tras fracaso terapias médicas. NO solución fácil - requiere compromiso cambios estilo vida permanentes, seguimiento médico vitalicio.</p>
    
    <h3>¿El ayuno intermitente es efectivo para pérdida de peso?</h3>
    <p>Ayuno intermitente (TRE: restricción temporal como 16:8, O ADF: días alternos) produce pérdida peso comparable a restricción calórica diaria continua (3-8% peso corporal en estudios RCT). NO es mágico - funciona primariamente reduciendo ventana alimentaria → ↓ ingesta calórica total. Beneficios potenciales adicionales: mejora sensibilidad insulina, ↓ inflamación, simplificación (no contar calorías). Sin embargo, NO claramente superior a dieta tradicional, y adherencia variable (algunos encuentran ayuno difícil socialmente/físicamente). Puede ser herramienta útil para personas que prefieren estructura horaria vs conteo calórico meticuloso. Precaución: diabetes (riesgo hipoglucemia), trastornos alimentarios, embarazo/lactancia.</p>
    
    <h3>¿La grasa visceral es más peligrosa que la subcutánea?</h3>
    <p>SÍ, absolutamente. Grasa visceral (intra-abdominal, rodeando órganos) es metabólicamente activa y altamente dañina: secreta citoquinas pro-inflamatorias (TNF-α, IL-6), ácidos grasos libres directamente al hígado vía portal (→ resistencia insulina hepática, dislipidemia), activación RAAS (hipertensión). Grasa subcutánea (bajo piel) es relativamente inerte/protectora. Personas con IMC "normal" pero grasa visceral elevada (TOFI: Thin Outside, Fat Inside) tienen riesgo metabólico/CV similar a obesos tradicionales. Circunferencia cintura mejor predictor grasa visceral que IMC. Meta: <94 cm hombres, <80 cm mujeres (caucásicos); <90/80 cm (asiáticos). Distribución grasa (dónde almacenas grasa) puede importar más que cantidad total.</p>
    
    <h3>¿Cómo evito el efecto yo-yo y la re-ganancia de peso?</h3>
    <p>Prevención re-ganancia requiere estrategias específicas basadas en National Weight Control Registry (>10,000 personas que mantuvieron ≥13 kg pérdida ≥1 año): (1) Actividad física regular ALTA (60-90 min/día moderada - sustancialmente > 150 min/semana recomendación general), (2) Auto-monitoreo peso (pesarse semanalmente - detectar ganancias pequeñas temprano), (3) Desayuno diario (asociado mantenimiento), (4) Bajo consumo TV (<10h/semana), (5) Dieta consistente días semana/fines semana (sin "cheat days" extremos), (6) Vigilancia dietética continua (restricción calórica moderada sostenida), (7) Manejo estrés no alimentario (ejercicio, meditación vs comer emocional), (8) Apoyo social/profesional continuo. Expectativa realista: Mantenimiento es TRABAJO activo permanente, no estado pasivo.</p>
    
    <h3>¿Debería preocuparme si mi IMC es normal pero mi cintura es grande?</h3>
    <p>SÍ, definitivamente. Este es el fenotipo "peso normal metabólicamente obeso" (MONW) - IMC <25 pero grasa visceral elevada (cintura ≥94 cm hombres, ≥80 cm mujeres). Frecuente en asiáticos, sedentarios, genética desfavorable. Riesgo diabetes/CV similar a personas obesas tradicionales a pesar de IMC "normal". Evaluación metabólica completa indicada: glucosa/HbA1c, lípidos, presión arterial, marcadores inflamatorios. Intervención: Mismas estrategias que obesidad (dieta calidad, ejercicio regular especialmente resistencia, manejo estrés). IMC "normal" NO garantiza salud metabólica - distribución grasa y función metabólica importan. Consulta médica recomendada.</p>
    
