<h4>Menopausia</h4>

<p><strong>Cambios composición corporal:</strong></p>
<ul>
<li>↑ Grasa visceral abdominal (redistribución de ginoide → androide)</li>
<li>↓ Masa muscular (sarcopenia acelerada)</li>
<li>↓ Gasto energético basal (~5-10%)</li>
<li>Ganancia peso promedio transición menopáusica: 2-5 kg</li>
</ul>

<p><strong>Mecanismos:</strong></p>
<ul>
<li>↓ Estrógenos → ↑ adiposidad central</li>
<li>↓ Hormona crecimiento</li>
<li>↓ Actividad física típicamente</li>
<li>Cambios apetito/saciedad</li>
</ul>

<p><strong>Implicaciones CV:</strong></p>
<ul>
<li>Grasa visceral postmenopáusica → ↑ riesgo CV (igualando hombres)</li>
<li>Pérdida efecto protector estrogénico</li>
<li>Manejo peso CRÍTICO prevención CV postmenopáusica</li>
</ul>

<p><strong>Estrategias:</strong></p>
<ul>
<li>Prevención > tratamiento: Mantener peso saludable pre-menopausia</li>
<li>↑ Actividad física (especialmente resistencia - combatir sarcopenia)</li>
<li>Vigilancia dietética (menores requerimientos calóricos)</li>
<li>TRH (terapia reemplazo hormonal): Puede atenuar ganancia peso/grasa visceral pero NO indicación primaria</li>
</ul>
