<ul>
<li>Multivitamínico + minerales diarios (vitalicio)</li>
<li>Laboratorios cada 3-6 meses primer año, luego anual (CBC, perfil metabólico, B12, folato, Fe, vitamina D, PTH)</li>
<li>Dieta progresiva: Líquida → puré → blanda → regular (8-12 semanas)</li>
<li>Proteína alta (60-80 g/día mínimo)</li>
<li>Pequeñas comidas frecuentes (5-6×/día inicialmente)</li>
<li>Evitar líquidos durante comidas (saciedad prematura, dumping)</li>
<li>Ejercicio regular (esencial mantenimiento)</li>
<li>Apoyo psicológico/grupos soporte</li>
