<h3>🩺 Factores de Salud</h3>

<div class="metric-card">
<h4>5. <a href="le8-imc-es.php">Índice de Masa Corporal</a> ⚖️</h4>
<p><strong>Puntaje promedio poblacional: 57.5/100</strong></p>
<p><strong>Adultos:</strong> IMC <25 kg/m² = 100 puntos, descendiendo a 0 para IMC ≥40</p>
<p><strong>Niños:</strong> Percentiles por edad/sexo (<5° percentil = 100 puntos)</p>
