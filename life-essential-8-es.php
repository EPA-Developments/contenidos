          <h2 class="title" id="faqs">Preguntas Frecuentes sobre Life's Essential 8™</h2>
        </div>
        
        <h3>¿Qué es Life's Essential 8™?</h3>
        <p>Life's Essential 8™ es el marco científico actualizado de la American Heart Association para medir y mejorar la salud cardiovascular. Incluye 8 métricas: calidad de la dieta, actividad física, exposición a nicotina, duración del sueño, índice de masa corporal (IMC), lípidos en sangre (colesterol no-HDL), glucosa en sangre (HbA1c), y presión arterial. Cada métrica se puntúa de 0-100, con el puntaje total calculado como promedio simple de las 8 métricas.</p>
        
        <h3>¿Cómo se calcula el puntaje de Life's Essential 8™?</h3>
        <p>El puntaje se calcula como promedio no ponderado de las 8 métricas individuales, cada una puntuada de 0-100 según algoritmos específicos. Puntajes ≥80 indican salud cardiovascular alta, 50-79 moderada, y <50 baja. El sistema de puntuación continuo permite seguimiento preciso de cambios individuales a lo largo del tiempo.</p>
        
        <h3>¿Cuál es la diferencia entre Life's Simple 7 y Life's Essential 8™?</h3>
        <p>Life's Essential 8™ añade el sueño como octava métrica y mejora el sistema de puntuación de binario (pobre/intermedio/ideal) a continuo (0-100 puntos). También actualiza la evaluación dietética usando MEPA score, considera toda exposición a nicotina incluyendo pasiva y vapeo, usa HbA1c en lugar de glucosa en ayunas, utiliza colesterol no-HDL en vez de colesterol total, y refleja mejor las inequidades en salud mediante reconocimiento explícito de determinantes sociales.</p>
        
        <h3>¿Qué beneficios demuestra alcanzar un puntaje alto en Life's Essential 8™?</h3>
        <p>Personas con puntajes altos (≥80) muestran 58% reducción en mortalidad por todas las causas y 35% reducción en mortalidad cardiovascular comparado con puntajes bajos (<50). También se asocia con mejor función cognitiva, menor riesgo de enfermedades crónicas como diabetes y cáncer, mayor esperanza de vida saludable, y mejor calidad de vida general. Estudios demuestran una relación dosis-respuesta: cada incremento de 10 puntos mejora significativamente el pronóstico.</p>
        
        <h3>¿Life's Essential 8™ es aplicable a niños?</h3>
        <p>Sí, existe Life's Essential 8™ for Kids con adaptaciones apropiadas por edad. Las principales diferencias incluyen: recomendaciones de sueño por grupo etario (12-16 horas para infantes de 4-12 meses hasta 8-10 horas para adolescentes de 13-18 años), IMC evaluado por percentiles edad/sexo en lugar de valores absolutos, actividad física de 60 minutos diarios en lugar de 150 minutos semanales, y umbrales de presión arterial basados en percentiles pediátricos hasta los 12 años.</p>
        
        <h3>¿Cómo puedo medir mi puntaje de Life's Essential 8™?</h3>
        <p>Puede utilizar varias opciones: (1) La plataforma My Life Check® de la AHA en www.heart.org/mylifecheck con evaluación de 34 preguntas, (2) Integración con registros electrónicos de salud (EHR) mediante estándares FHIR R4 que extrae datos automáticamente, (3) EPA Bienestar IA que ofrece evaluación automatizada integrada con su historia clínica digital y dispositivos wearables, o (4) Calculadoras específicas disponibles en esta plataforma para cada métrica individual.</p>
        
        <h3>¿Qué métrica de Life's Essential 8™ tiene los puntajes más bajos en la población?</h3>
        <p>La calidad dietética tiene el puntaje promedio más bajo con 36.0 puntos de 100, seguida de actividad física con 51.6 puntos e IMC con 57.5 puntos. Estas tres métricas representan las áreas prioritarias de intervención para mejorar la salud cardiovascular poblacional. La baja puntuación dietética refleja el predominio de patrones alimentarios occidentales ricos en alimentos procesados, azúcares añadidos y grasas no saludables.</p>
        
        <h3>¿Life's Essential 8™ se puede usar en programas de residencia médica?</h3>
        <p>Sí, es ideal para residentes de cardiología comenzando con auto-monitoreo personal en los primeros 12 meses y expandiendo a evaluación de pacientes después. Programas como Stanford Medicine integran Life's Essential 8™ en curricula estructurada con competencias ACGME, usando mini-CEX para evaluación bedside, desarrollo profesional continuo mediante plataforma AHA Lifelong Learning, y creación de proyectos de investigación sobre outcomes de implementación.</p>
        
        <h3>¿Existen adaptaciones de Life's Essential 8™ para la salud de la mujer?</h3>
        <p>Sí, la campaña Go Red for Women ofrece materiales específicos considerando factores hormonales (menstruación, embarazo, menopausia), transiciones de ciclo vital, y factores de riesgo género-específicos. Datos clave: menopausia temprana (<45 años) aumenta 50% el riesgo coronario, preeclampsia duplica el riesgo de enfermedad coronaria futura, y diabetes gestacional aumenta 7-12 veces el riesgo de desarrollar diabetes tipo 2. El programa WISEWOMAN demuestra implementación efectiva con enfoque de equipo multidisciplinario.</p>
        
        <h3>¿Cómo se integra Life's Essential 8™ con estándares FHIR R4?</h3>
        <p>Se utilizan recursos FHIR core: Observation para tracking de las 8 métricas (HbA1c, presión arterial, IMC, etc.), RiskAssessment para puntaje cardiovascular total y categorización de riesgo, Patient para demografía y determinantes sociales, Goal para objetivos personalizados por métrica, CarePlan para planes de intervención estructurados, y QuestionnaireResponse para datos auto-reportados de comportamiento. Plataformas EHR principales como Epic, Oracle Health (Cerner), Allscripts y Medplum soportan FHIR R4 para intercambio seamless de datos cardiovasculares.</p>
        
