<p><strong>Adultos:</strong> <130 mg/dL = 100 puntos</p>
<p><strong>Importante:</strong> Penalidad -20 puntos si está en tratamiento farmacológico (reconoce riesgo residual)</p>
<p>Refleja colesterol total menos colesterol HDL ("bueno"), capturando todas partículas aterogénicas.</p>
