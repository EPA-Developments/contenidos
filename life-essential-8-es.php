<p><strong><120/80 mmHg sin medicación = 100 puntos</strong></p>
<p>Descendiendo por etapas de hipertensión hasta 0 puntos para ≥160/100 mmHg</p>
<p><strong>Penalidad:</strong> -20 puntos si está en tratamiento farmacológico</p>
