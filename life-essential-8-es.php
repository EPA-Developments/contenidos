<p><strong>HbA1c <5.7% sin diabetes = 100 puntos</strong></p>
<p>Descendiendo a 0 puntos para ≥8.0%</p>
<p><strong>Penalidad:</strong> -20 puntos si está en tratamiento farmacológico</p>
<p>Superior a glucosa en ayunas por estabilidad y reflejo de control metabólico a largo plazo.</p>
<a href="le8-glucosa-es.php" class="btn-link">Ver detalles completos →</a>
