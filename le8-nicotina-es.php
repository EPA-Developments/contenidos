<h1>Exposición a Nicotina: La Métrica #3 de Life's Essential 8™</h1>

<p>La <strong>exposición a nicotina</strong> es la tercera métrica esencial para salud cardiovascular y representa uno de los factores de riesgo cardiovascular más devastadores y completamente prevenibles. Life's Essential 8™ actualiza significativamente el enfoque previo al incluir no solo el uso activo de tabaco combustible, sino también <strong>cigarrillos electrónicos, vapeo, productos de tabaco sin humo, y exposición pasiva al humo de segunda mano</strong>.</p>

<p>La evidencia es contundente: <strong>el tabaquismo aumenta 2-4 veces el riesgo de enfermedad cardiovascular</strong>, acorta la expectativa de vida 10 años en promedio, y es responsable de 1 de cada 5 muertes cardiovasculares. Sin embargo, <strong>la cesación tabáquica reduce el riesgo cardiovascular 50% en el primer año</strong>, con normalización casi completa después de 15 años sin fumar.</p>

