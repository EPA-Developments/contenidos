<h3>👨‍⚕️ Profesionales de Salud</h3>

<h4>Prevalencia y Paradoja</h4>
<ul>
<li><strong>Médicos:</strong> 5-10% fumadores (EE.UU.) - más bajo que población general</li>
<li><strong>Enfermeras:</strong> 15-20% fumadores - similar población general</li>
<li><strong>Paradoja:</strong> Conocimiento riesgos no elimina adicción</li>
