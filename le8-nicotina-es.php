<h3>📋 Modelo de las 5 A's (Práctica Clínica)</h3>

<div class="five-as">
<h4>1. ASK (Preguntar)</h4>
<ul>
<li>Identificar y documentar estatus tabáquico en CADA visita médica</li>
<li>Pregunta estándar: "¿Usa actualmente productos de tabaco o nicotina?"</li>
<li>Registrar en historia clínica como signo vital</li>
<li>Incluir: cigarrillos, e-cigarrillos, tabaco sin humo, exposición pasiva</li>
</ul>

<h4>2. ADVISE (Aconsejar)</h4>
<ul>
<li>Mensaje claro, fuerte, personalizado para dejar de fumar</li>
<li>Ejemplo: "Dejar de fumar es lo MÁS importante que puede hacer para su salud. Estoy aquí para ayudarle."</li>
<li>Conectar con condición médica actual: "Su [hipertensión/diabetes/etc.] mejorará significativamente si deja de fumar."</li>
<li>Evitar: Sermones o culpabilización (contraproducente)</li>
</ul>

<h4>3. ASSESS (Evaluar)</h4>
<ul>
<li>Determinar disposición para intentar cesación</li>
<li>Etapas de cambio (Prochaska): Precontemplación, Contemplación, Preparación, Acción, Mantenimiento</li>
<li>Pregunta: "¿Estaría interesado/a en dejar de fumar en los próximos 30 días?"</li>
<li>Si SÍ → Proceder a ASSIST</li>
<li>Si NO → Intervención motivacional breve, plantar semilla para futuro</li>
</ul>

<h4>4. ASSIST (Asistir)</h4>

<h5>A. Fijar Fecha de Cesación</h5>
<ul>
<li>Idealmente dentro de las próximas 2 semanas</li>
<li>Fecha significativa puede aumentar motivación (cumpleaños, aniversario)</li>
<li>Comunicar a familia/amigos para apoyo social</li>
</ul>

<h5>B. Preparación Conductual</h5>
<ul>
<li>Eliminar cigarrillos y accesorios de fumar del ambiente</li>
<li>Identificar triggers (café, alcohol, estrés, pausas laborales)</li>
<li>Planificar estrategias de afrontamiento alternativas</li>
<li>Anticipar síntomas abstinencia (irritabilidad, ansiedad, dificultad concentración)</li>
</ul>

