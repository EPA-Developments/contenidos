<h2 id="tipos">Tipos de Exposición a Nicotina</h2>

<h3>🚬 Tabaco Combustible (Riesgo Más Alto)</h3>

<div class="tobacco-types">
<h4>Cigarrillos Convencionales</h4>
<ul>
<li><strong>Prevalencia:</strong> 85-90% de todo uso de tabaco</li>
<li><strong>Riesgo CV:</strong> 2-4× aumento vs no fumadores</li>
<li><strong>Dosis-respuesta:</strong> Cada cigarrillo/día aumenta riesgo IAM 5.6%</li>
<li><strong>Componentes nocivos:</strong> Nicotina, alquitrán, CO, formaldehído, benzeno</li>
<li><strong>Efectos agudos:</strong> ↑ FC 10-15 lpm, ↑ PA 5-10 mmHg, vasoconstricción, ↑ agregación plaquetaria</li>
</ul>

<h4>Cigarros y Pipas</h4>
<ul>
<li><strong>Mito "más seguro":</strong> FALSO - riesgo CV similar a cigarrillos</li>
<li><strong>Diferencia:</strong> Menor inhalación pulmonar, pero absorción nicotina oral</li>
<li><strong>Riesgo único:</strong> Mayor riesgo cáncer oral y esofágico</li>
<li><strong>Evidencia:</strong> Fumadores exclusivos de cigarros: 1.3-1.8× riesgo IAM</li>
</ul>

<h4>Tabaco de Liar ("Roll-Your-Own")</h4>
<ul>
<li><strong>Percepción errónea:</strong> "Más natural, menos químicos"</li>
<li><strong>Realidad:</strong> Frecuentemente más nocivo (tabaco sin filtro, mayor combustión)</li>
<li><strong>Contenido nicotina:</strong> Similar o mayor que cigarrillos comerciales</li>
<li><strong>Riesgo CV:</strong> Equivalente a cigarrillos convencionales</li>
</ul>

<h4>Narguile/Hookah (Pipa de Agua)</h4>
<ul>
<li><strong>Mito "el agua filtra toxinas":</strong> FALSO - 82% toxinas pasan filtro</li>
<li><strong>Exposición:</strong> 1 sesión (45-60 min) = fumar 100+ cigarrillos (por volumen inhalado)</li>
<li><strong>CO:</strong> Niveles 7× más altos que cigarrillo</li>
<li><strong>Riesgo CV:</strong> ↑ Aterosclerosis, disfunción endotelial, rigidez arterial</li>
<li><strong>Evidencia:</strong> Uso regular aumenta riesgo CV similar a cigarrillos</li>
</ul>
</div>

<h3>💨 Cigarrillos Electrónicos y Vapeo</h3>

<div class="vaping-section">
<h4>Perfil de Riesgo Cardiovascular</h4>

<p><strong>Estado actual del conocimiento:</strong> Emergente y en evolución, pero creciente evidencia de daño CV</p>

<h5>Componentes del Aerosol de E-cigarrillos</h5>
<ul>
<li><strong>Nicotina:</strong> Dosis variables (0-59 mg/ml), frecuentemente mal etiquetado</li>
<li><strong>Propilenglicol/Glicerina vegetal:</strong> Carriers - se descomponen a formaldehído/acetaldehído a altas temperaturas</li>
<li><strong>Saborizantes:</strong> Diacetilo (bronquiolitis obliterante), cinamaldehído (citotóxico)</li>
<li><strong>Metales pesados:</strong> Níquel, plomo, cromo (de serpentín calefactor)</li>
<li><strong>Partículas ultrafinas:</strong> Penetración profunda alveolar</li>
</ul>

<h5>Efectos Cardiovasculares Demostrados</h5>
<ul>
<li>↑ Frecuencia cardíaca inmediata (15-30 lpm)</li>
<li>↑ Presión arterial (5-10 mmHg sistólica)</li>
<li>Disfunción endotelial (↓ vasodilatación mediada por flujo)</li>
<li>↑ Rigidez arterial (PWV)</li>
<li>↑ Estrés oxidativo y marcadores inflamatorios</li>
<li>↑ Agregación plaquetaria</li>
<li>Arritmias (FA, taquicardia ventricular reportadas)</li>
</ul>

<h5>Evidencia Epidemiológica Reciente</h5>
<ul>
<li><strong>Estudio AHA 2019:</strong> Uso diario e-cigarrillos → 56% ↑ riesgo IAM vs nunca usuarios</li>
<li><strong>Meta-análisis 2021:</strong> Vapeo asociado con ↑ riesgo eventos CV mayores (OR 1.71, IC95% 1.24-2.35)</li>
<li><strong>Dual use (cigarrillos + e-cig):</strong> Riesgo CV mayor que fumar solo cigarrillos convencionales</li>
</ul>

<h5>Posición en Life's Essential 8™</h5>
<p><strong>Puntuación:</strong> Uso regular de e-cigarrillos = <strong>misma penalización que tabaco combustible</strong></p>
<p><strong>Justificación:</strong> Aunque potencialmente menos nocivo que cigarrillos (evidencia limitada), NO es inocuo y sí produce daño cardiovascular medible. No debe considerarse "alternativa segura".</p>

<h5>⚠️ Consideración Especial: Reducción de Daños</h5>
<p>Para fumadores establecidos que NO pueden/quieren dejar nicotina completamente, transición de cigarrillos a e-cigarrillos PUEDE reducir exposición a algunos tóxicos. Sin embargo:</p>
<ul>
<li>Meta final debe ser cesación completa de todos productos nicotina</li>
<li>E-cigarrillos NO aprobados por FDA como terapia de cesación</li>
<li>Riesgo significativo de uso dual (cigarrillos + e-cig) que no reduce riesgo</li>
<li>Alta tasa recaída a cigarrillos convencionales</li>
</ul>
</div>

<h3>📦 Productos de Tabaco sin Humo</h3>

<div class="smokeless-tobacco">
<h4>Tipos Principales</h4>

<h5>Tabaco de Mascar (Chewing Tobacco)</h5>
<ul>
<li><strong>Formas:</strong> Hojas sueltas, plug, twist</li>
<li><strong>Uso:</strong> Masticar, mantener entre mejilla y encía</li>
<li><strong>Absorción nicotina:</strong> Similar a fumar (pico 30 min)</li>
</ul>

<h5>Rapé Seco (Snuff)</h5>
<ul>
<li><strong>Formas:</strong> Seco (nasal), húmedo (oral/snus)</li>
<li><strong>Uso:</strong> Colocar entre labio/encía o inhalar nasalmente</li>
<li><strong>Contenido nicotina:</strong> Variable, frecuentemente alto</li>
</ul>

<h4>Perfil de Riesgo Cardiovascular</h4>

<p><strong>Evidencia mixta:</strong> Menor riesgo que tabaco combustible, pero NO libre de riesgo</p>

<h5>Efectos Cardiovasculares</h5>
<ul>
<li>↑ Frecuencia cardíaca aguda (nicotina sistémica)</li>
<li>↑ Presión arterial (efecto simpaticomimético)</li>
<li>Disfunción endotelial (menor que cigarrillos)</li>
<li>↑ Riesgo stroke: 1.4× (meta-análisis 28 estudios)</li>
<li>↑ Riesgo IAM fatal: 1.13× (evidencia más débil)</li>
<li>↑ Insuficiencia cardíaca: Asociación emergente</li>
</ul>

<h5>Experiencia Sueca (Snus)</h5>
<p>Suecia tiene prevalencia tabaco sin humo más alta (snus) y tasas IAM más bajas de Europa. Esto ha generado debate "reducción de daños". Sin embargo:</p>
<ul>
<li>Snus sueco regulado estrictamente (niveles nitrosaminas bajos)</li>
<li>Productos EE.UU. frecuentemente más tóxicos</li>
<li>Riesgo cáncer oral/páncreas persiste</li>
<li>No es estrategia de primera línea para cesación</li>
</ul>

<h5>Posición Life's Essential 8™</h5>
<p><strong>Puntuación:</strong> Uso regular tabaco sin humo = <strong>penalización similar a tabaco combustible</strong> (aunque levemente menor en algunas versiones scoring)</p>
<p><strong>Recomendación AHA:</strong> Cesación completa de todos productos tabaco/nicotina</p>
</div>

<h3>🏠 Exposición Pasiva (Humo de Segunda Mano)</h3>

<div class="secondhand-smoke">
<h4>Composición del Humo de Segunda Mano</h4>

<ul>
<li><strong>Humo mainstream:</strong> Exhalado por fumador</li>
<li><strong>Humo sidestream:</strong> De extremo encendido del cigarrillo (85% exposición)</li>
<li><strong>Toxinas:</strong> >7,000 químicos, 70+ carcinógenos</li>
<li><strong>Concentración:</strong> Algunos tóxicos MÁS concentrados en sidestream que mainstream</li>
</ul>

<h4>Efectos Cardiovasculares en No Fumadores</h4>

<ul>
<li><strong>Riesgo enfermedad coronaria:</strong> ↑ 25-30%</li>
<li><strong>Riesgo stroke:</strong> ↑ 20-30%</li>
<li><strong>Mecanismos:</strong> Disfunción endotelial, ↑ agregación plaquetaria, inflamación vascular</li>
<li><strong>Efectos agudos:</strong> 30 min exposición → ↓ vasodilatación coronaria en no fumadores</li>
<li><strong>Dosis-respuesta:</strong> Exposición aumentada = mayor riesgo (no existe umbral seguro)</li>
</ul>

<h4>Poblaciones Especialmente Vulnerables</h4>

<ul>
<li><strong>Niños:</strong> ↑ Infecciones respiratorias, asma, síndrome muerte súbita infantil</li>
<li><strong>Embarazadas:</strong> Bajo peso al nacer, parto prematuro</li>
<li><strong>Cardiopatía establecida:</strong> ↑ Eventos CV agudos</li>
<li><strong>Trabajadores hospitality:</strong> Pre-legislación humo-libre, exposición crónica elevada</li>
</ul>

<h4>Evidencia de Políticas Humo-Libre</h4>

<p><strong>Legislación espacios públicos libres de humo:</strong></p>
<ul>
<li>Reducción 10-20% hospitalizaciones por IAM primer año post-implementación</li>
<li>Beneficio sostenido y creciente en años subsecuentes</li>
<li>Protección trabajadores y público general</li>
<li>Incentivo adicional para cesación en fumadores</li>
</ul>

<h4>Humo de Tercera Mano</h4>

<p><strong>Concepto emergente:</strong> Residuos nicotina y toxinas que permanecen en superficies/polvo después de fumar</p>
<ul>
<li>Reacción nicotina con ácido nitroso ambiental → nitrosaminas carcinogénicas</li>
<li>Persistencia: Semanas a meses en ambientes interiores</li>
<li>Exposición: Contacto dérmico, ingestión (niños tocando superficies)</li>
<li>Riesgo CV: Aún bajo investigación, preocupación emergente</li>
</ul>
</div>

