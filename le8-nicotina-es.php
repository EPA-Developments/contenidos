<h3>⚠️ Penalización por Exposición Pasiva</h3>

<div class="passive-exposure">
<p><strong>Regla especial:</strong> Restar 20 puntos (mínimo 0) si vive con fumadores que fuman dentro del hogar</p>

<h4>Ejemplos de Aplicación</h4>
<ul>
<li><strong>Nunca fumador + vive con fumador indoor:</strong> 100 - 20 = <strong>80 puntos</strong></li>
<li><strong>Ex-fumador 3 años + vive con fumador indoor:</strong> 65 - 20 = <strong>45 puntos</strong></li>
<li><strong>Fumador actual:</strong> 0 - 20 = <strong>0 puntos</strong> (no puede ser negativo)</li>
</ul>

<h4>Justificación Científica</h4>
<p>Exposición pasiva al humo de tabaco aumenta <strong>25-30% el riesgo de enfermedad cardiovascular</strong> en no fumadores. El humo de segunda mano contiene >7,000 químicos, 70+ carcinógenos conocidos, y produce efectos cardiovasculares agudos y crónicos similares (aunque atenuados) al fumar activo.</p>
