        <h3>¿Son los cigarrillos electrónicos una alternativa segura al tabaco?</h3>
        <p>No. Aunque los e-cigarrillos pueden contener menos tóxicos que cigarrillos convencionales, NO son seguros. Evidencia creciente demuestra efectos cardiovasculares adversos: disfunción endotelial, aumento rigidez arterial, incremento frecuencia cardíaca y presión arterial. Un estudio AHA 2019 encontró que uso diario de e-cigarrillos aumentó 56% el riesgo de infarto. Life's Essential 8™ penaliza el uso de e-cigarrillos igual que tabaco combustible. No están aprobados por FDA como terapia de cesación.</p>
        
        <h3>¿Cuánto tiempo después de dejar de fumar se reduce mi riesgo cardiovascular?</h3>
        <p>Los beneficios comienzan inmediatamente: frecuencia cardíaca y presión arterial normalizan en 20 minutos, nivel de monóxido de carbono en sangre normaliza en 12 horas. El riesgo de enfermedad coronaria se reduce 50% en el primer año post-cesación. A los 5 años, el riesgo de stroke iguala al de un nunca fumador. A los 15 años, el riesgo de enfermedad coronaria se normaliza completamente. Nunca es tarde para dejar - cesación a cualquier edad proporciona beneficios sustanciales.</p>
        
        <h3>¿Fumar "solo unos pocos cigarrillos" al día es seguro?</h3>
        <p>No existe nivel seguro de consumo de tabaco. Estudios demuestran que fumar incluso 1 cigarrillo/día aumenta significativamente el riesgo cardiovascular. Un meta-análisis de 141 estudios encontró que fumar 1 cigarrillo/día confiere aproximadamente 50% del riesgo de fumar 20 cigarrillos/día (no el 5% que matemáticamente esperaríamos). La relación dosis-respuesta no es lineal - el riesgo se eleva desproporcionadamente incluso con consumo mínimo.</p>
        
        <h3>¿La exposición pasiva al humo realmente afecta la salud cardiovascular?</h3>
        <p>Sí, significativamente. La exposición pasiva al humo de tabaco aumenta 25-30% el riesgo de enfermedad cardiovascular en no fumadores. El humo de segunda mano contiene >7,000 químicos y produce efectos cardiovasculares agudos medibles: solo 30 minutos de exposición deterioran la vasodilatación coronaria en no fumadores. Por esto, Life's Essential 8™ penaliza 20 puntos vivir con fumadores indoor. Las políticas de espacios públicos libres de humo han demostrado reducciones 10-20% en hospitalizaciones por infarto.</p>
        
        <h3>¿Cuál es la mejor terapia farmacológica para dejar de fumar?</h3>
        <p>La vareniclina (Champix) es la farmacoterapia individual más efectiva con OR 2.3 vs placebo (abstinencia ~18% vs 7% placebo a 12 meses). Sin embargo, la combinación de terapias puede ser aún más efectiva: TRN parche + forma corta acción (chicle/pastilla) alcanza OR 1.9, y bupropión + TRN parche logra OR 2.5. La "mejor" terapia depende del paciente individual: contraindicaciones, preferencias, intentos previos, efectos secundarios tolerables. Lo más importante es usar ALGUNA farmacoterapia - todas duplican como mínimo las tasas de éxito vs placebo.</p>
        
        <h3>¿Voy a aumentar de peso si dejo de fumar?</h3>
        <p>Típicamente sí, pero moderadamente. El promedio es 2-3 kg en el primer año post-cesación. Esto ocurre porque: (1) la nicotina suprime apetito y aumenta metabolismo ~200 kcal/día, y (2) muchas personas sustituyen el hábito oral de fumar con snacking. Sin embargo, este incremento de peso es MUCHO menor riesgo cardiovascular que continuar fumando. Estrategias para minimizar ganancia peso: actividad física regular, TRN (retrasa ganancia peso), bupropión (reduce ganancia peso), atención a calidad dietética, manejo stress alternativo (no comer emocional).</p>
        
        <h3>¿Cuántos intentos toma típicamente dejar de fumar exitosamente?</h3>
        <p>El promedio es 7-10 intentos antes de lograr cesación permanente. Sin tratamiento, 85-95% de intentos resultan en recaída dentro de 12 meses. Con farmacoterapia + apoyo conductual, las tasas de éxito mejoran sustancialmente a 20-30% abstinencia a 12 meses (aún así, 70-80% recaída). Esto NO es fracaso personal - la nicotina es una de las sustancias más adictivas conocidas. Cada intento es aprendizaje sobre triggers y estrategias. El mensaje clave: persistencia es crítica. Nunca darse por vencido intentando.</p>
        
        <h3>¿Es seguro usar terapia de reemplazo de nicotina si tengo enfermedad cardiovascular?</h3>
        <p>Generalmente SÍ, la TRN es segura incluso en pacientes con enfermedad cardiovascular establecida. Estudios en pacientes post-IAM demostraron que TRN no aumenta eventos cardiovasculares vs placebo. La nicotina pura de TRN es MUY menos nociva que fumar (que contiene nicotina + miles de otros tóxicos). Precauciones: iniciar dosis menores en enfermedad CV inestable reciente (<2 semanas post-IAM), monitorear síntomas, considerar formas corta acción sobre parches inicialmente. Consultar con cardiólogo si arritmias significativas. El beneficio de cesación con TRN supera ampliamente cualquier riesgo potencial.</p>
        
        <h3>¿La reducción gradual de cigarrillos es mejor que cesación abrupta?</h3>
        <p>La evidencia favorece cesación abrupta ("cold turkey") ligeramente sobre reducción gradual para tasas de abstinencia a largo plazo. Sin embargo, reducción gradual puede ser apropiada para: (1) fumadores muy pesados (>30 cig/día) que sienten que abrupto es imposible, (2) personas con intentos previos fallidos de cesación abrupta, (3) pacientes con condiciones psiquiátricas que necesitan transición más suave. Si se elige reducción gradual: establecer cronograma claro (ej. reducir 25%/semana), fijar fecha definitiva cesación (no indefinida), combinar con TRN para facilitar proceso, transicionar eventualmente a cesación completa (la reducción sola rara vez resulta en abstinencia total).</p>
        
