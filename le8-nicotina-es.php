<h3>🏥 Pacientes con Enfermedad Cardiovascular Establecida</h3>

<h4>Urgencia de Cesación</h4>
<ul>
<li><strong>Post-IAM:</strong> Continuar fumar → 2× riesgo re-infarto a 5 años</li>
<li><strong>Revascularización (PCI/CABG):</strong> Fumar ↓ permeabilidad injertos, ↑ re-estenosis</li>
<li><strong>Insuficiencia cardíaca:</strong> Fumar empeora clase funcional, ↑ hospitalizaciones</li>
<li><strong>Arritmias:</strong> Nicotina precipita FA, taquiarritmias ventriculares</li>
</ul>

<h4>Ventana de Oportunidad</h4>
<p><strong>"Teachable moment":</strong> Hospitalización por evento CV = momento óptimo intervención</p>
<ul>
<li>Motivación intrínseca alta (confrontación mortalidad)</li>
<li>Captive audience (ambiente controlado sin acceso tabaco)</li>
<li>Inicio farmacoterapia inmediato (durante hospitalización)</li>
<li>Seguimiento estructurado post-alta</li>
<li>Tasas abstinencia: 40-50% a 1 año si intervención intensiva hospitalaria</li>
</ul>

