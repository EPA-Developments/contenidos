<h3>💪 Estrategias para Fumadores "No Listos" para Dejar</h3>

<div class="motivational-strategies">
<h4>Intervención Motivacional Breve (5 R's)</h4>

<h5>1. RELEVANCE (Relevancia)</h5>
<p>Personalizar por qué es relevante para ESA persona dejar de fumar</p>
<ul>
<li>"Mencionó que quiere ver crecer a sus nietos - fumar reduce dramáticamente sus posibilidades"</li>
<li>"Su diabetes será mucho más difícil de controlar mientras fume"</li>
<li>"Como atleta, está perdiendo capacidad pulmonar significativa"</li>
</ul>

<h5>2. RISKS (Riesgos)</h5>
<p>Educación sobre riesgos específicos del tabaquismo</p>
<ul>
<li>Riesgos agudos: IAM, stroke, complicaciones quirúrgicas</li>
<li>Riesgos a largo plazo: EPOC, cáncer, demencia</li>
<li>Riesgos ambientales: Exposición familia (hijos, pareja)</li>
<li>Presentar en términos personalmente relevantes</li>
</ul>

<h5>3. REWARDS (Recompensas)</h5>
<p>Enfatizar beneficios de cesación</p>
<ul>
<li><strong>Inmediatos:</strong> Ahorro económico, mejor aliento, sabor comida</li>
<li><strong>Corto plazo:</strong> Mejor condición física, piel más saludable</li>
<li><strong>Largo plazo:</strong> Reducción dramática riesgo enfermedades, mayor longevidad</li>
<li><strong>Familiares:</strong> Modelar comportamiento saludable para hijos, proteger seres queridos</li>
</ul>

<h5>4. ROADBLOCKS (Obstáculos)</h5>
<p>Identificar y abordar barreras percibidas</p>
<ul>
<li><strong>Miedo síntomas abstinencia:</strong> "Medicación reduce síntomas 50-70%"</li>
<li><strong>Preocupación ganancia peso:</strong> "Promedio 2-3 kg, manejable con plan; beneficio CV supera ampliamente este riesgo"</li>
<li><strong>Intentos previos fallidos:</strong> "Promedio 7-10 intentos antes de éxito permanente - cada intento es aprendizaje"</li>
<li><strong>Entorno fumadores:</strong> "Puedo conectarle con recursos de cesación para su pareja también"</li>
</ul>

<h5>5. REPETITION (Repetición)</h5>
<p>Mensaje motivacional en CADA encuentro clínico</p>
<ul>
<li>Consistencia refuerza importancia</li>
<li>Disponibilidad expresada aumenta probabilidad de intento cuando paciente esté listo</li>
<li>"Mi puerta está abierta cuando esté listo/a para dar este paso hacia mejor salud"</li>
</ul>
