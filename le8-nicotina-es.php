</ul>

<h3>🧓 Adultos Mayores (≥65 años)</h3>

<h4>Beneficios Cesación en Edad Avanzada</h4>
<ul>
<li><strong>Mito "ya es muy tarde":</strong> FALSO - beneficio a cualquier edad</li>
<li><strong>Cesación a 65 años:</strong> Recupera 2-4 años expectativa vida</li>
<li><strong>Beneficios inmediatos:</strong> Mejora función pulmonar, circulación, energía</li>
