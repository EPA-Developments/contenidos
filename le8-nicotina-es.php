<h3>🔄 Manejo de Recaída</h3>

<div class="relapse-management">
<h4>Estadísticas de Recaída</h4>
<ul>
<li><strong>Sin tratamiento:</strong> 85-95% recaída en 12 meses</li>
<li><strong>Con tratamiento (farmacológico + conductual):</strong> 50-70% recaída en 12 meses</li>
<li><strong>Tiempo mayor riesgo:</strong> Primeras 2 semanas post-cesación</li>
<li><strong>Promedio intentos hasta éxito:</strong> 7-10 intentos</li>
</ul>

<h4>Distinguir: Lapso vs Recaída</h4>
<ul>
<li><strong>Lapso:</strong> Fumar aislado (1-2 cigarrillos) → No es fracaso, oportunidad aprendizaje</li>
<li><strong>Recaída:</strong> Retorno patrón regular de fumar</li>
<li><strong>Mensaje clave:</strong> Lapso no predice inevitablemente recaída completa</li>
</ul>

<h4>Estrategias Post-Lapso</h4>
<ol>
<li><strong>No auto-culpabilización:</strong> Normalizar experiencia, enfocarse en aprendizaje</li>
<li><strong>Identificar trigger específico:</strong> ¿Qué precipitó el lapso? (estrés, alcohol, entorno social)</li>
<li><strong>Desarrollar plan alternativo:</strong> ¿Cómo manejar ese trigger diferentemente?</li>
<li><strong>Recomprometerse inmediatamente:</strong> No esperar a "día perfecto" para reiniciar</li>
<li><strong>Intensificar apoyo:</strong> Mayor contacto con consejero, considerar ajuste farmacoterapia</li>
</ol>

<h4>Prevención Recaída a Largo Plazo</h4>
<ul>
<li><strong>Evitar alcohol primeros meses:</strong> Alcohol deteriora control inhibitorio</li>
<li><strong>Manejo estrés:</strong> Desarrollar alternativas saludables (ejercicio, meditación, hobbies)</li>
<li><strong>Evitar situaciones alto riesgo:</strong> Pausas con colegas fumadores, bares/clubs (inicialmente)</li>
<li><strong>Terapia farmacológica extendida:</strong> Considerar 6-12 meses (vs estándar 12 semanas) para fumadores severos</li>
<li><strong>Recordatorios beneficios:</strong> Tracking ahorro económico, mejoras físicas tangibles</li>
</ul>
</div>

<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>Framingham Heart Study - Impacto Multigeneracional Tabaquismo</h4>
<p><strong>Diseño:</strong> Cohorte prospectiva, >10,000 participantes, 3 generaciones, seguimiento 60+ años</p>
<p><strong>Hallazgos Clave:</strong></p>
<ul>
<li>Fumadores: 2-4× riesgo enfermedad cardiovascular vs nunca fumadores</li>
<li>Riesgo dosis-dependiente: 1-14 cig/día → RR 2.0; ≥25 cig/día → RR 4.0</li>
<li>Cesación: Reducción riesgo detectable en 1 año, normalización casi completa en 15 años</li>
<li>Exposición pasiva (no fumadores con cónyuge fumador): 30% ↑ riesgo enfermedad coronaria</li>
<li>Transmisión intergeneracional: Padres fumadores → hijos 2× probabilidad convertirse fumadores</li>
</ul>
</div>

<div class="evidence-box">
<h4>Million Women Study (UK) - Impacto en Mujeres</h4>
<p><strong>Diseño:</strong> Cohorte prospectiva, 1.2 millones mujeres, seguimiento 12 años</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li>Fumadoras actuales: 3× mortalidad vs nunca fumadoras</li>
<li>Pérdida expectativa vida: 11 años (fumadoras vs nunca fumadoras)</li>
<li><strong>Cesación por edad:</strong>
  <ul>
    <li>Antes de 30 años: Recupera casi toda expectativa vida perdida</li>
    <li>Antes de 40 años: Recupera 10 años expectativa vida</li>
    <li>50-60 años: Recupera 4-6 años expectativa vida</li>
  </ul>
</li>
<li>Interacción anticonceptivos orales + tabaco: 20× ↑ riesgo IAM en mujeres >35 años</li>
</ul>
</div>

<div class="evidence-box">
<h4>Cochrane Review - Terapias Farmacológicas para Cesación (2021)</h4>
<p><strong>Análisis:</strong> 267 RCTs, >100,000 participantes</p>
<p><strong>Eficacia Relativa (vs Placebo) - Abstinencia a 12 meses:</strong></p>
<table class="efficacy-table">
<tr>
<td><strong>Vareniclina:</strong></td>
<td>OR 2.3 (IC95% 2.1-2.5)</td>
<td>~18% abstinencia vs 7% placebo</td>
</tr>
<tr>
<td><strong>Combinación TRN:</strong></td>
<td>OR 1.9 (IC95% 1.5-2.4)</td>
<td>~14% abstinencia</td>
</tr>
<tr>
<td><strong>TRN Monoterapia:</strong></td>
<td>OR 1.6 (IC95% 1.5-1.7)</td>
<td>~12% abstinencia</td>
</tr>
<tr>
<td><strong>Bupropión:</strong></td>
<td>OR 1.6 (IC95% 1.5-1.8)</td>
<td>~12% abstinencia</td>
</tr>
<tr>
<td><strong>Nortriptilina:</strong></td>
<td>OR 1.6 (IC95% 1.3-2.0)</td>
<td>~12% abstinencia (segunda línea)</td>
</tr>
<tr>
<td><strong>Sin farmacoterapia:</strong></td>
<td>-</td>
<td>~5% abstinencia</td>
</tr>
</table>
<p><strong>Conclusión:</strong> Todas farmacoterapias significativamente superiores a placebo. Vareniclina + combinación TRN más efectivas.</p>
</div>

<div class="evidence-box">
<h4>Meta-análisis E-cigarrillos para Cesación (NEJM 2019)</h4>
<p><strong>Análisis:</strong> RCT comparando e-cigarrillos vs TRN para cesación tabáquica</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li>Abstinencia 1 año: 18.0% (e-cig) vs 9.9% (TRN), RR 1.83</li>
<li>E-cigarrillos superiores a TRN en este estudio específico</li>
<li><strong>PERO:</strong> 80% usuarios e-cig continuaron usando e-cigarrillos a 1 año (vs 9% TRN)</li>
<li><strong>Implicancia:</strong> Riesgo sustitución una adicción por otra</li>
<li><strong>Posición AHA:</strong> E-cigarrillos NO tratamiento primera línea; preferir terapias aprobadas FDA</li>
</ul>
</div>

<h3>Mecanismos Fisiopatológicos del Daño Cardiovascular por Tabaco</h3>

<div class="mechanisms-grid">
<div class="mechanism">
<h4>🔬 Disfunción Endotelial</h4>
<ul>
<li>↓ Óxido nítrico (NO) biodisponibilidad</li>
<li>↑ Especies reactivas oxígeno (ROS)</li>
<li>Deterioro vasodilatación dependiente endotelio</li>
<li>↑ Permeabilidad endotelial</li>
<li>Expresión moléculas adhesión (VCAM-1, ICAM-1)</li>
<li><strong>Reversibilidad:</strong> Mejora detectable en 2-4 semanas post-cesación</li>
</ul>
</div>

<div class="mechanism">
<h4>🩸 Efectos Hematológicos</h4>
<ul>
<li>↑ Agregación plaquetaria (factor von Willebrand)</li>
<li>↑ Fibrinógeno y viscosidad sanguínea</li>
<li>↓ Actividad fibrinolítica</li>
<li>↑ Leucocitos (respuesta inflamatoria crónica)</li>
<li>↑ Hematocrito (respuesta hipoxia crónica CO)</li>
<li><strong>Estado protrombótico:</strong> Riesgo IAM y stroke</li>
</ul>
</div>

<div class="mechanism">
<h4>💥 Inflamación Vascular</h4>
<ul>
<li>↑ PCR (proteína C-reactiva) 50-100%</li>
<li>↑ IL-6, IL-1β, TNF-α</li>
<li>Infiltración leucocitos en pared arterial</li>
<li>Activación macrófagos → células espumosas</li>
<li>Progresión aterosclerosis acelerada</li>
</ul>
</div>

<div class="mechanism">
<h4>⚡ Efectos Sistema Nervioso Simpático</h4>
<ul>
<li>Activación adrenérgica aguda (nicotina)</li>
<li>↑ Frecuencia cardíaca 10-15 lpm</li>
<li>↑ Presión arterial 5-10 mmHg</li>
<li>↑ Contractilidad miocárdica</li>
<li>↑ Demanda oxígeno miocárdico</li>
<li>Vasoconstricción periférica</li>
</ul>
</div>

<div class="mechanism">
<h4>🧬 Estrés Oxidativo</h4>
<ul>
<li>↓ Capacidad antioxidante plasmática</li>
<li>Oxidación LDL → LDL-ox (altamente aterogénico)</li>
<li>Daño oxidativo DNA endotelial</li>
<li>Disfunción mitocondrial</li>
<li>Senescencia celular acelerada (telómeros)</li>
</ul>
</div>

<div class="mechanism">
<h4>📊 Efectos Metabólicos</h4>
<ul>
<li>↑ LDL-colesterol</li>
<li>↓ HDL-colesterol (10-15%)</li>
<li>↑ Triglicéridos</li>
<li>↓ Sensibilidad insulina</li>
<li>↑ Riesgo diabetes tipo 2 (30-40%)</li>
<li>Distribución grasa central (↑ grasa visceral)</li>
</ul>
</div>

<div class="mechanism">
<h4>💀 Monóxido de Carbono (CO)</h4>
<ul>
<li>Afinidad Hb 200× mayor que O2</li>
<li>Carboxihemoglobina: Hipoxia tisular crónica</li>
<li>↓ Entrega oxígeno al miocardio</li>
<li>Desviación curva disociación O2 (↓ liberación O2)</li>
<li>Niveles fumadores: 5-10% COHb (vs <2% no fumadores)</li>
</ul>
</div>

<div class="mechanism">
<h4>🧱 Remodelado Vascular</h4>
<ul>
<li>↑ Rigidez arterial (velocidad onda pulso)</li>
<li>Engrosamiento íntima-media carotídea</li>
<li>Calcificación arterial acelerada</li>
<li>Degradación elastina pared arterial</li>
<li>Envejecimiento vascular prematuro</li>
</ul>
</div>
