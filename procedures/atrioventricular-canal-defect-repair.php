              <p>Atrioventricular canal defect repair surgery typically involves several key steps to address the defect and restore normal heart function. The procedure is performed under general anesthesia, and the patient is closely monitored throughout the surgery to ensure safety and effectiveness.</p>



              <ul>
                <li>Steps involved in atrioventricular canal defect repair surgery include:</li>
                <li>Opening the chest to access the heart</li>
                <li>Repairing the hole in the atrioventricular canal</li>
                <li>Reconstructing the valves and chambers of the heart</li>
                <li>Closing the chest incision</li>
                <li>Monitoring the patient in the recovery room</li>
              </ul>

              <p>Surgeons work meticulously to repair the defect and optimize heart function during the procedure. The goal is to provide a successful outcome that improves the patient's overall health and well-being.</p>



              <p>Following surgery, patients will be closely monitored to ensure a smooth recovery process.</p>



