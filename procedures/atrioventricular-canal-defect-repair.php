              <p>Atrioventricular canal defect repair surgery is typically performed by a cardiothoracic surgeon who specializes in heart surgery.</p>



              <p>These highly skilled and experienced surgeons have extensive training in repairing congenital heart defects and are equipped to handle complex procedures like atrioventricular canal defect repair.</p>



              <p>Cardiothoracic surgeons work closely with a multidisciplinary team of healthcare professionals, including cardiologists, anesthesiologists, and nurses, to ensure the best possible outcome for patients undergoing atrioventricular canal defect repair surgery.</p>



              <p>Their expertise and dedication play a crucial role in the success of the procedure and the overall well-being of the patient.</p>



