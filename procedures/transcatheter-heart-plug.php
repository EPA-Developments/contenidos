        <h3>What is a transcatheter heart plug?</h3>
          <p>A transcatheter heart plug is a small device inserted through a thin tube into the heart to seal off a hole or close off abnormal blood flow.</p>





          <h3>How does a transcatheter heart plug prevent embolism?</h3>
