          <h2 class="title" id="faqs">Frequently Asked Questions</h2>
        </div>
        <h3>What is a heart transplant?</h3>
          <p>A heart transplant is a surgery where a diseased heart is replaced with a healthy donor heart to improve heart function and quality of life.</p>





          <h3>When is a heart transplant needed?</h3>
            <p>A heart transplant is needed when other treatments for heart failure are no longer effective, and the heart is severely damaged, causing symptoms that significantly affect quality of life and survival.</p>





            <h3>How do you qualify for a heart transplant?</h3>
              <p>To qualify for a heart transplant, you typically need to have advanced heart failure that has not responded to other treatments and meet certain medical, psychological, and social criteria.</p>





              <h3>How long is the wait for a heart transplant?</h3>
                <p>The wait for a heart transplant can vary depending on factors like your blood type, severity of illness, and availability of donor organs. It can range from days to months.</p>





                <h3>What are the risks of heart transplant surgery?</h3>
                  <p>The risks of heart transplant surgery include bleeding, infection, organ rejection, and side effects from immunosuppressant medications.</p>





                  <h3>How long does recovery take after a heart transplant?</h3>
                    <p>Recovery after a heart transplant can vary, but most patients spend about 1-3 weeks in the hospital and 3-6 months in a supervised cardiac rehabilitation program. Full recovery may take up to a year.</p>





                    <h3>Can heart transplant surgery cure heart disease?</h3>
                      <p>Heart transplant surgery can be a treatment for severe heart disease, but it is not a cure. It can help improve quality of life and increase life expectancy in some cases.</p>





                      <h3>What are the chances of rejection after a heart transplant?</h3>
                        <p>The rejection rate after a heart transplant can vary, but with current medications and monitoring, many patients do not experience rejection. Regular follow-up with your healthcare team is essential to monitor and manage any signs of rejection.</p>





                        <h3>What lifestyle changes are needed after a heart transplant?</h3>
                          <p>After a heart transplant, it's important to follow a healthy lifestyle, including regular exercise, a heart-healthy diet, taking medications as prescribed, avoiding smoking and excessive alcohol, managing stress, and attending follow-up appointments with your healthcare team.</p>





                          <h3>How successful are heart transplants?</h3>
                            <p>Heart transplants are generally successful, with about 85-90% of patients surviving the first year post-transplant, and 70-75% surviving for at least five years.</p>
