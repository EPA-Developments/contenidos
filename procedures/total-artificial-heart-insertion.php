            <h3>What are the risks of total artificial heart insertion?</h3>
              <p>The risks of total artificial heart insertion include bleeding, infection, blood clots, stroke, and device malfunction. Your healthcare team will closely monitor you for any complications.</p>





              <h3>Who is a candidate for total artificial heart insertion?</h3>
