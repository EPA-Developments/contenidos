                <li>Before SVT ablation surgery, discuss any concerns or questions with your healthcare team.</li>
                <li>After SVT ablation surgery, follow your doctor's post-operative instructions carefully for a speedy recovery.</li>
                <li>Before the procedure, arrange for someone to drive you home from the hospital.</li>
                <li>After the procedure, avoid strenuous activities and heavy lifting for a few days.</li>
                <li>Before SVT ablation surgery, make sure to have someone available to assist you at home during the initial recovery period.</li>
              </ul>

