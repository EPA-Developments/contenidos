          <h3>Why is endarterectomy performed?</h3>
            <p>Endarterectomy is performed to remove plaque buildup in the arteries, improving blood flow and reducing the risk of stroke or heart attack.</p>





            <h3>How is endarterectomy performed?</h3>
              <p>During an endarterectomy, the surgeon makes an incision in the affected artery, removes the plaque causing the blockage, and then closes the artery with stitches or a patch to restore proper blood flow.</p>





              <h3>What are the risks of endarterectomy?</h3>
                <p>Risks of endarterectomy include bleeding, infection, stroke, nerve injury, and heart attack, but these complications are rare and vary depending on the patient's overall health and the location of the surgery.</p>





                <h3>How long does it take to recover from endarterectomy?</h3>
