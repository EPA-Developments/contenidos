                <li>Preoperative evaluation to assess the patient's overall health and determine the best course of action</li>
                <li>Anesthesia administration to ensure the patient is comfortable and pain-free during the surgery</li>
                <li>Opening the chest to access the heart and locate the tumor</li>
                <li>Careful removal of the tumor while preserving the surrounding healthy tissue</li>
                <li>Closing the chest and monitoring the patient closely during the recovery process</li>
              </ul>

              <p>These steps are carried out with precision and care by a team of skilled surgeons and healthcare professionals to ensure the best possible outcome for the patient undergoing Heart Tumor Removal Surgery surgery.</p>



