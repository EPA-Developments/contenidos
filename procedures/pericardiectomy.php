                    <h3>What are the benefits of pericardiectomy?</h3>
                      <p>Pericardiectomy can help relieve symptoms such as chest pain, shortness of breath, and swelling due to the removal of the pericardium, the membrane around the heart.</p>





                      <h3>What is the success rate of pericardiectomy?</h3>
