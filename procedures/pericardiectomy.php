          <h3>Why is pericardiectomy needed?</h3>
            <p>Pericardiectomy is needed to remove part or all of the pericardium (the sac around the heart) to relieve pressure on the heart caused by conditions like constrictive pericarditis or cardiac tamponade.</p>





            <h3>How is pericardiectomy performed?</h3>
              <p>Pericardiectomy is a surgical procedure where a surgeon removes part or all of the pericardium, the sac around the heart. This can be done through a small incision or with the help of a camera and instruments using minimally invasive techniques.</p>





              <h3>What are the risks of pericardiectomy?</h3>
                <p>Risks of pericardiectomy may include bleeding, infection, damage to nearby structures, irregular heart rhythms, and in rare cases, death. Your healthcare team will discuss these risks with you before the procedure.</p>





                <h3>How long is the recovery after pericardiectomy?</h3>
