            <h3>Who needs a defibrillator?</h3>
              <p>A defibrillator is needed for people who have a history of irregular heartbeats (arrhythmias) or those at risk of sudden cardiac arrest.</p>





              <h3>What are the different types of defibrillators?</h3>
                <p>There are mainly two types of defibrillators: automated external defibrillators (AEDs) used in public settings and implantable cardioverter-defibrillators (ICDs) placed inside the body for long-term management of heart rhythm problems.</p>





