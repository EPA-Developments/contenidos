        <h3>What is a trans-oesophageal echocardiogram (TOE)?</h3>
          <p>A trans-oesophageal echocardiogram (TOE) is a test that uses sound waves to create detailed pictures of the heart. It involves a small probe inserted into the esophagus to obtain close-up images of the heart.</p>





          <h3>Why is TOE performed?</h3>
            <p>A transesophageal echocardiogram (TOE) is performed to get detailed images of the heart and its blood vessels, providing more information than a regular echocardiogram.</p>





            <h3>How does a TOE differ from a traditional echocardiogram?</h3>
              <p>A Transesophageal echocardiogram (TOE) is similar to a traditional echocardiogram, but the ultrasound probe is passed into the esophagus to get closer images of the heart from different angles.</p>





              <h3>What conditions can TOE diagnose?</h3>
                <p>Transesophageal echocardiogram (TOE) can diagnose conditions such as heart valve problems, blood clots, infections around the heart, and abnormalities in the structure of the heart.</p>





                <h3>How is a TOE procedure performed?</h3>
                  <p>During a transesophageal echocardiogram (TOE) procedure, a small ultrasound probe is passed through your mouth and into your esophagus to get detailed images of your heart. It is done while you are sedated and typically takes about 30 minutes.</p>





                  <h3>What are the risks of TOE?</h3>
                    <p>The risks of transesophageal echocardiogram (TOE) include sore throat, minor bleeding at the site of tube insertion, and very rarely, more serious complications like esophageal perforation.</p>





                    <h3>How long does the TOE procedure take?</h3>
                      <p>A transesophageal echocardiogram (TOE) typically takes about 30-60 minutes to complete.</p>





                      <h3>Is TOE painful?</h3>
                        <p>During a transesophageal echocardiogram (TOE), you will be sedated, so you should not feel any pain during the procedure.</p>





                        <h3>How effective is TOE in detecting heart problems?</h3>
                          <p>A transesophageal echocardiogram (TOE) is very effective in detecting heart problems that may not be visible on a regular echocardiogram. It provides detailed images of the heart's structure and function.</p>





                          <h3>What should be done before and after a TOE procedure?</h3>
                            <p>Before a TOE (transesophageal echocardiogram) procedure, you should not eat or drink for a few hours. After the procedure, you may have a sore throat, so it's advisable to rest and avoid eating or drinking until the numbness wears off.</p>
