            <h3>Who is a candidate for pulmonary embolectomy?</h3>
              <p>A patient with a massive pulmonary embolism or a clot in the lungs that is causing severe symptoms and is at high risk of death may be a candidate for pulmonary embolectomy.</p>





              <h3>What are the risks of pulmonary embolectomy?</h3>
                <p>The risks of pulmonary embolectomy include bleeding, infection, blood clots, and damage to nearby structures like blood vessels. Your healthcare team will discuss these risks with you before the procedure.</p>





                <h3>How is pulmonary embolectomy performed?</h3>
