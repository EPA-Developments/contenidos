              <p>Before undergoing aortic fenestration for type B dissection surgery, patients will need to undergo a series of pre-operative tests and evaluations to assess their overall health and fitness for the procedure.</p>



              <p>These may include blood tests, imaging studies, and consultations with various healthcare professionals.</p>



