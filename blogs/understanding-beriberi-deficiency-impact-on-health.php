              <p>In addition to the heart, thiamine deficiency can also affect the nervous system, leading to symptoms such as tingling, numbness, and muscle weakness.</p>



              <p>Thiamine is essential for the proper functioning of nerve cells, so a deficiency can have a significant impact on nerve function.</p>



              <p>Furthermore, thiamine deficiency can affect the digestive system, leading to symptoms such as constipation, loss of appetite, and weight loss.</p>



              <p>Thiamine is crucial for the proper digestion of food and the absorption of nutrients, so a deficiency can lead to malnutrition and other health issues.</p>



