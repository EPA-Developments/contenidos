        <h3>How does aortic coarctation lead to high blood pressure?</h3>
        <p>Aortic coarctation narrows the aorta, increasing pressure in the arteries. This forces the heart to work harder, leading to high blood pressure.</p>



        <h3>What are the longterm complications of untreated aortic coarctation?</h3>
        <p>Untreated aortic coarctation can lead to high blood pressure, heart failure, stroke, and aortic aneurysm, impacting long-term heart health.</p>



        <h3>How is aortic coarctation diagnosed?</h3>
        <p>Aortic coarctation is diagnosed through physical exams, imaging tests like echocardiograms and MRIs, and monitoring blood pressure differences in the arms and legs.</p>



        <h3>What are the treatment options for aortic coarctation?</h3>
        <p>Treatment options for aortic coarctation include surgery to repair the narrowed section of the aorta, balloon angioplasty, or stent placement.</p>



        <h3>How does aortic coarctation affect the function of the heart over time?</h3>
