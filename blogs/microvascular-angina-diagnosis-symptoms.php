        <h3>Is surgery necessary for treating microvascular angina?</h3>
        <p>Surgery is typically not necessary for treating microvascular angina. Medications, lifestyle changes, and cardiac rehabilitation are often recommended instead.</p>



        <h3>What are the risks of untreated microvascular angina?</h3>
