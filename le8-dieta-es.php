<h2 id="estrategias">Estrategias para Mejorar Calidad Dietética</h2>

<h3>🥗 Enfoque por Componente MEPA</h3>

<div class="strategy-grid">

<div class="strategy-card">
<h4>1. Aumentar Frutas y Vegetales</h4>
<p><strong>Objetivo:</strong> 9 porciones combinadas/día</p>
<p><strong>Estrategias prácticas:</strong></p>
<ul>
<li>Llenar 50% del plato con vegetales en almuerzo/cena</li>
<li>Frutas como snack entre comidas principales</li>
<li>Smoothies con vegetales de hoja verde + frutas</li>
<li>Variedad de colores (arcoíris nutricional)</li>
<li>"Meal prep" dominical: cortar vegetales para semana</li>
</ul>
<p><strong>1 porción =</strong> 1 taza vegetales crudos, ½ taza cocidos, 1 fruta mediana</p>
</div>

<div class="strategy-card">
<h4>2. Transición a Granos Integrales</h4>
<p><strong>Objetivo:</strong> 3+ porciones/día</p>
<p><strong>Sustituciones simples:</strong></p>
<ul>
<li>Pan blanco → Pan integral 100%</li>
<li>Arroz blanco → Arroz integral, quinoa, bulgur</li>
<li>Pasta regular → Pasta integral</li>
<li>Cereales azucarados → Avena, granola sin azúcar</li>
<li>Snacks procesados → Palomitas de maíz, galletas integrales</li>
</ul>
<p><strong>Tip:</strong> Leer etiquetas - primer ingrediente debe ser "integral"</p>
</div>

<div class="strategy-card">
<h4>3. Optimizar Proteínas</h4>
<p><strong>Objetivo:</strong> Diversificar fuentes proteicas</p>
<p><strong>Plan semanal:</strong></p>
<ul>
<li><strong>2-3 días:</strong> Pescado graso (salmón, sardinas, atún)</li>
<li><strong>2-3 días:</strong> Legumbres (lentejas, garbanzos, frijoles)</li>
<li><strong>1-2 días:</strong> Aves sin piel</li>
<li><strong>1 día:</strong> Tofu, tempeh (proteínas vegetales)</li>
<li><strong>Diario:</strong> 1 puñado nueces/almendras (30g)</li>
<li><strong>Limitar:</strong> Carnes rojas a <1 vez/semana</li>
</ul>
</div>

<div class="strategy-card">
<h4>4. Reducir Sodio</h4>
<p><strong>Objetivo:</strong> <1500 mg/día (óptimo) o <2300 mg/día</p>
<p><strong>Fuentes principales a reducir:</strong></p>
<ul>
<li>Alimentos procesados y empacados (70% sodio dietético)</li>
<li>Comida de restaurantes</li>
<li>Pan y productos de panadería</li>
<li>Embutidos y carnes procesadas</li>
<li>Quesos (preferir bajos en sodio)</li>
</ul>
<p><strong>Estrategias:</strong></p>
<ul>
<li>Cocinar en casa con ingredientes frescos</li>
<li>Usar hierbas, especias, limón en lugar de sal</li>
<li>Leer etiquetas: <140mg sodio/porción = "bajo en sodio"</li>
<li>Enjuagar alimentos enlatados</li>
</ul>
</div>

<div class="strategy-card">
<h4>5. Eliminar Azúcares Añadidos</h4>
<p><strong>Objetivo:</strong> <10% calorías totales (~50g/día en dieta 2000 cal)</p>
<p><strong>Fuentes principales ocultas:</strong></p>
<ul>
<li>Bebidas azucaradas (gaseosas, jugos, bebidas deportivas)</li>
<li>Cereales de desayuno</li>
<li>Yogures saborizados</li>
<li>Salsas y aderezos comerciales</li>
<li>Postres y productos de panadería</li>
</ul>
<p><strong>Alternativas saludables:</strong></p>
<ul>
<li>Agua, agua con gas, té sin azúcar</li>
<li>Frutas enteras para postre</li>
<li>Yogur griego natural + frutas</li>
<li>Chocolate oscuro ≥70% cacao (pequeñas cantidades)</li>
</ul>
</div>

<div class="strategy-card">
<h4>6. Priorizar Grasas Saludables</h4>
<p><strong>Objetivo:</strong> Aceite de oliva como grasa principal</p>
<p><strong>Grasas a INCLUIR:</strong></p>
<ul>
<li>Aceite de oliva extra virgen (AOVE)</li>
<li>Aguacate</li>
<li>Nueces, almendras, nueces de nogal</li>
<li>Semillas de chía, lino, calabaza</li>
<li>Pescados grasos (omega-3)</li>
</ul>
<p><strong>Grasas a LIMITAR:</strong></p>
<ul>
<li>Mantequilla, margarina</li>
<li>Aceite de palma, coco</li>
<li>Grasas trans (alimentos procesados)</li>
<li>Carnes grasas, piel de aves</li>
</ul>
</div>

</div>

<h3>📋 Plan de Implementación Gradual (12 semanas)</h3>

<div class="implementation-plan">
<h4>Semanas 1-2: Evaluación Baseline</h4>
<ul>
<li>Completar cuestionario MEPA</li>
<li>Registro dietético de 3 días (2 días hábiles + 1 fin de semana)</li>
<li>Identificar componentes MEPA con puntuación más baja</li>
<li>Establecer metas SMART específicas</li>
</ul>

<h4>Semanas 3-4: Primer Componente (usualmente vegetales/frutas)</h4>
<ul>
<li>Incrementar 1 porción/día de vegetales</li>
<li>Agregar 1 fruta como snack</li>
<li>Experimentar con 3 vegetales nuevos</li>
<li>Re-evaluar y ajustar</li>
</ul>

<h4>Semanas 5-6: Segundo Componente (granos integrales)</h4>
<ul>
<li>Sustituir 1 grano refinado por integral</li>
<li>Probar 2 granos integrales nuevos</li>
<li>Mantener mejoras de semanas 3-4</li>
</ul>

<h4>Semanas 7-8: Tercer Componente (proteínas)</h4>
<ul>
<li>Añadir 1 comida de pescado/semana</li>
<li>Sustituir 1 carne roja por legumbres</li>
<li>Incorporar nueces como snack diario</li>
</ul>

<h4>Semanas 9-10: Cuarto Componente (sodio/azúcares)</h4>
<ul>
<li>Eliminar 1 fuente principal de azúcares añadidos</li>
<li>Reducir sal en cocina 25%</li>
<li>Leer etiquetas activamente</li>
</ul>

<h4>Semanas 11-12: Consolidación y Re-evaluación</h4>
<ul>
<li>Repetir cuestionario MEPA</li>
<li>Calcular mejora en puntuación</li>
<li>Identificar áreas persistentes de oportunidad</li>
<li>Planificar mantenimiento a largo plazo</li>
</ul>
</div>

<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>PREDIMED Trial (2013)</h4>
<p><strong>Diseño:</strong> RCT con 7,447 participantes alto riesgo CV, seguimiento 4.8 años</p>
<p><strong>Intervención:</strong> Dieta mediterránea + AOVE o nueces vs dieta baja en grasa</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>30% reducción eventos cardiovasculares mayores (P=0.004)</li>
<li>49% reducción stroke (P=0.03)</li>
<li>Beneficio sin restricción calórica o aumento actividad física</li>
</ul>
</div>

<div class="evidence-box">
<h4>DASH Trial (1997)</h4>
<p><strong>Diseño:</strong> Ensayo controlado alimentación, 459 adultos</p>
<p><strong>Intervención:</strong> Dieta rica en frutas, vegetales, lácteos bajos en grasa</p>
<p><strong>Resultados:</strong></p>
<ul>
<li>Reducción presión arterial sistólica: 11.4 mmHg (hipertensos)</li>
<li>Reducción presión arterial diastólica: 5.5 mmHg</li>
<li>Efecto comparable a monoterapia farmacológica</li>
</ul>
</div>

<div class="evidence-box">
<h4>Meta-análisis Calidad Dietética y Mortalidad CV (2020)</h4>
<p><strong>Análisis:</strong> 24 estudios prospectivos, 1.9 millones participantes</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li>31% reducción riesgo enfermedad cardiovascular (adherencia alta vs baja)</li>
<li>25% reducción mortalidad por todas las causas</li>
<li>22% reducción mortalidad cardiovascular específica</li>
<li>Beneficio consistente en múltiples patrones dietéticos saludables</li>
</ul>
</div>

<h3>Mecanismos Fisiopatológicos</h3>

<p>La dieta de alta calidad protege contra enfermedad cardiovascular mediante múltiples vías:</p>

<ul>
<li><strong>Perfil lipídico:</strong> Reducción LDL-colesterol 10-15%, aumento HDL 5-10%</li>
<li><strong>Presión arterial:</strong> Disminución 5-10 mmHg sistólica, efecto DASH</li>
<li><strong>Inflamación:</strong> Reducción PCR, IL-6, marcadores proinflamatorios</li>
<li><strong>Función endotelial:</strong> Mejora vasodilatación mediada por flujo</li>
<li><strong>Estrés oxidativo:</strong> Aumento capacidad antioxidante plasmática</li>
<li><strong>Microbioma:</strong> Promoción de bacterias productoras de SCFA (butirato)</li>
<li><strong>Control glucémico:</strong> Mejora sensibilidad insulina, reducción HbA1c 0.3-0.5%</li>
<li><strong>Peso corporal:</strong> Facilitación de balance energético negativo sin hambre</li>
</ul>

<h2>Consideraciones Especiales por Población</h2>

<h3>👩 Mujeres</h3>
<ul>
