          <h2 class="title" id="faqs">Preguntas Frecuentes - Calidad de la Dieta</h2>
        </div>
        
        <h3>¿Por qué la dieta es la métrica con peor puntaje poblacional?</h3>
        <p>El puntaje promedio de 36.0/100 refleja el predominio de patrones alimentarios occidentales ricos en alimentos ultraprocesados, bebidas azucaradas, y bajos en frutas, vegetales y granos integrales. Factores contribuyentes incluyen disponibilidad de alimentos procesados, marketing agresivo, costo percibido de alimentos saludables, y barreras de tiempo para preparación.</p>
        
        <h3>¿Necesito contar calorías para mejorar mi puntuación MEPA?</h3>
        <p>No. El enfoque MEPA es en calidad dietética, no cantidad. Estudios como PREDIMED demuestran beneficios cardiovasculares significativos sin restricción calórica explícita. Al mejorar calidad (más alimentos enteros, menos procesados), la regulación natural de apetito típicamente resulta en balance energético apropiado.</p>
        
        <h3>¿Qué tan rápido puedo mejorar mi puntuación dietética?</h3>
        <p>Cambios mensurables ocurren en semanas. Un plan de implementación gradual de 12 semanas puede mejorar el MEPA score 4-8 puntos, equivalente a 25-50 puntos en Life's Essential 8™. Beneficios cardiovasculares (reducción presión arterial, mejora perfil lipídico) son detectables en 2-4 semanas de adherencia al patrón MEPA.</p>
        
        <h3>¿La dieta mediterránea es la única opción saludable?</h3>
        <p>No. MEPA es una adaptación americana del patrón mediterráneo, pero otros patrones demuestran beneficios cardiovasculares: DASH, nórdica, vegetariana/vegana bien planificada, y patrones tradicionales asiáticos. El principio común: énfasis en alimentos enteros vegetales, proteínas de calidad, grasas saludables, y limitación de ultraprocesados.</p>
        
