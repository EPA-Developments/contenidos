<h1>Calidad de la Dieta: La Métrica #1 de Life's Essential 8™</h1>

<p>La <strong>calidad de la dieta</strong> es la primera de las 8 métricas esenciales para salud cardiovascular y, paradójicamente, es la que presenta el <strong>puntaje promedio más bajo en la población: 36.0/100 puntos</strong>. Esta métrica evalúa el patrón alimentario general mediante el <strong>Mediterranean Eating Pattern for Americans (MEPA)</strong>, un sistema de puntuación validado científicamente que captura la adherencia a patrones dietéticos cardiovascularmente protectores.</p>

<p>La evidencia es clara: <strong>una dieta de alta calidad reduce hasta 31% el riesgo de enfermedad cardiovascular</strong> y 25% la mortalidad por todas las causas. La transición del enfoque en nutrientes individuales hacia patrones dietéticos completos refleja el entendimiento moderno de que los alimentos interactúan sinérgicamente para producir efectos sobre la salud.</p>

<h2 id="puntuacion">Sistema de Puntuación Dietética</h2>

<h3>Métodos de Evaluación</h3>

<p>Life's Essential 8™ permite dos aproximaciones para evaluar calidad dietética:</p>

<h4>1. Evaluación Basada en Población</h4>
<ul>
<li><strong>100 puntos:</strong> ≥Percentil 95 en distribución poblacional</li>
<li><strong>Descenso gradual:</strong> Según posición en distribución</li>
<li><strong>0 puntos:</strong> ≤Percentil 5</li>
<li><strong>Ventaja:</strong> No requiere recordatorio dietético detallado</li>
<li><strong>Limitación:</strong> Depende de datos poblacionales de referencia</li>
</ul>

<h4>2. MEPA Score Individual (Recomendado)</h4>
<ul>
<li><strong>100 puntos:</strong> 15-16 puntos MEPA</li>
<li><strong>Descenso proporcional:</strong> Hasta 0 puntos MEPA = 0 puntos LE8</li>
<li><strong>Ventaja:</strong> Medición precisa y personalizada</li>
<li><strong>Componentes:</strong> 8 categorías de alimentos</li>
</ul>

