<h3>🏠 Monitoreo Ambulatorio Presión Arterial (MAPA)</h3>

<div class="ambulatory-monitoring">
<h4>Monitoreo Ambulatorio 24 Horas (MAPA 24h)</h4>

<p><strong>Método:</strong></p>
<ul>
<li>Dispositivo automático oscilométrico portátil</li>
<li>Mediciones cada 15-30 min día, 30-60 min noche</li>
<li>Paciente mantiene actividades normales, diario actividades/síntomas</li>
<li>Análisis: Promedios 24h, diurno, nocturno, variabilidad, patrón dipping</li>
</ul>

<p><strong>Indicaciones MAPA:</strong></p>
<ul>
<li>Sospecha <strong>hipertensión bata blanca</strong> (PA elevada consultorio, normal habitual)</li>
<li>Sospecha <strong>hipertensión enmascarada</strong> (PA normal consultorio, sospecha elevada fuera)</li>
<li><strong>PA lábil/variable</strong> consultorio</li>
<li>Evaluación <strong>eficacia tratamiento</strong> (especialmente cobertura 24h)</li>
<li>Evaluación <strong>resistencia tratamiento</strong></li>
<li>Síntomas <strong>hipotensión</strong> (evaluar nadires PA, correlación síntomas)</li>
<li>Disfunción <strong>autonómica</strong> (neuropatía diabética, Parkinson)</li>
<li>Evaluación <strong>patrón dipping</strong> (no-dippers ↑ riesgo CV)</li>
</ul>

<p><strong>Umbrales diagnóstico MAPA (adultos):</strong></p>
