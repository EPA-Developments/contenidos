<li><strong>Intensificar estilo vida:</strong> Pérdida peso si obesidad, restricción Na+ estricta (<1,500 mg/día), DASH rigurosa</li>

<li><strong>Si aún refractaria (5+ fármacos):</strong> Referencia especialista hipertensión, considerar denervación renal (terapia invasiva emergente)</li>
</ol>
