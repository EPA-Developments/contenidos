<h2 id="fisiologia">Fisiología de Presión Arterial</h2>

<h3>🔬 Determinantes Presión Arterial</h3>

<div class="bp-physiology">
<h4>Ecuación Fundamental</h4>

<div class="fundamental-equation">
<p><strong>Presión Arterial Media (PAM) = Gasto Cardíaco (GC) × Resistencia Vascular Periférica (RVP)</strong></p>

<p><strong>Desglose:</strong></p>
<ul>
<li><strong>Gasto Cardíaco (GC) = Volumen Sistólico (VS) × Frecuencia Cardíaca (FC)</strong></li>
<li><strong>Volumen Sistólico</strong> depende de: Precarga, Contractilidad, Postcarga</li>
<li><strong>Resistencia Vascular Periférica</strong> determinada principalmente por: Diámetro arteriolas (vasomoción), Viscosidad sangre</li>
</ul>

<p><strong>Relación PA Sistólica/Diastólica:</strong></p>
<ul>
<li><strong>PA Sistólica:</strong> Presión pico durante eyección ventricular (sístole) - refleja GC, distensibilidad arterial</li>
<li><strong>PA Diastólica:</strong> Presión mínima entre latidos (diástole) - refleja RVP</li>
<li><strong>Presión Pulso:</strong> PAS - PAD - aumenta con rigidez arterial (envejecimiento, aterosclerosis)</li>
<li><strong>PAM (aprox):</strong> PAD + (Presión Pulso / 3) ≈ (2×PAD + PAS) / 3</li>
</ul>
</div>

