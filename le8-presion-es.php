<h2 id="evidencia">Evidencia Científica</h2>

<h3>Estudios Clave de Validación</h3>

<div class="evidence-box">
<h4>SPRINT (Systolic Blood Pressure Intervention Trial) - Estudio Índice Metas PA</h4>
<p><strong>Diseño:</strong> RCT, 9,361 adultos ≥50 años alto riesgo CV (sin diabetes), seguimiento 3.26 años (detenido temprano por beneficio)</p>
<p><strong>Intervención:</strong> Tratamiento intensivo (meta PAS <120 mmHg) vs estándar (meta PAS <140 mmHg)</p>
<p><strong>PA alcanzada:</strong> 121.4 mmHg (intensivo) vs 136.2 mmHg (estándar)</p>
<p><strong>Resultados (FAVORECE INTENSIVO):</strong></p>
<ul>
<li><strong>↓ 25% eventos CV mayores</strong> (IAM, síndrome coronario agudo, stroke, IC, muerte CV) - HR 0.75, P<0.001</li>
<li><strong>↓ 27% mortalidad total</strong> (HR 0.73, P=0.003) - ÚNICO estudio hipertensión mostrar ↓ mortalidad total</li>
<li>↓ 43% muerte CV</li>
<li>↓ 38% IC</li>
<li>NNT=61 (3.26 años) prevenir 1 evento CV</li>
</ul>
<p><strong>Eventos adversos serios:</strong></p>
<ul>
<li>Hipotensión: 2.4% (intensivo) vs 1.4% (estándar)</li>
<li>Síncope: 2.3% vs 1.7%</li>
<li>Alteraciones electrolíticas: 3.1% vs 2.3%</li>
<li>Lesión renal aguda: 4.1% vs 2.5%</li>
<li>Eventos serios totales: 38.3% vs 37.1% (diferencia modesta)</li>
</ul>
<p><strong>Subgrupo ≥75 años:</strong> Beneficio similar (↓ eventos CV, mortalidad), sin ↑ caídas/lesiones</p>
<p><strong>Controversia/Limitaciones:</strong></p>
<ul>
<li>Medición PA automatizada sin presencia personal (PA "real" posiblemente 5-10 mmHg más alta → meta efectiva ~130 mmHg)</li>
<li>Excluidos diabéticos, post-stroke reciente, IC sintomática, ERC avanzada</li>
<li>Intensivo requirió promedio 2.8 fármacos vs 1.8 estándar</li>
</ul>
<p><strong>Impacto:</strong> Catalizó cambio guías ACC/AHA 2017 → umbral 130/80 mmHg</p>
</div>

<div class="evidence-box">
<h4>ALLHAT (Antihypertensive and Lipid-Lowering Treatment to Prevent Heart Attack Trial)</h4>
<p><strong>Diseño:</strong> RCT, 33,357 hipertensos ≥55 años + ≥1 factor riesgo CV, seguimiento 4.9 años</p>
<p><strong>Comparación:</strong> Clortalidona (tiazida) vs amlodipino (CCB) vs lisinopril (IECA) vs doxazosina (bloqueador α - brazo detenido temprano)</p>
<p><strong>Outcome primario:</strong> Enfermedad coronaria fatal/IAM no-fatal</p>
<p><strong>Resultados:</strong></p>
<ul>
<li><strong>Sin diferencia outcome primario</strong> entre clortalidona, amlodipino, lisinopril (todos ~11-12% incidencia)</li>
<li>Clortalidona superior prevención IC vs amlodipino (10.2% vs 7.7%, P<0.001)</li>
<li>Lisinopril inferior control PA vs clortalidona en negros</li>
<li>Doxazosina detenida temprano: ↑ IC vs clortalidona (HR 2.04)</li>
</ul>
<p><strong>Conclusión:</strong> Tiazidas (clortalidona) son opción costo-efectiva, apropiadas primera línea mayoría hipertensos. Sin embargo, IECA y CCB igualmente efectivos prevención eventos coronarios.</p>
<p><strong>Impacto:</strong> Estableció tiazidas/CCB/IECA como clases equivalentes primera línea (relegó bloqueadores α líneas posteriores)</p>
</div>

<div class="evidence-box">
<h4>HOPE (Heart Outcomes Prevention Evaluation) - Beneficio IECA Alto Riesgo</h4>
<p><strong>Diseño:</strong> RCT, 9,297 pacientes ≥55 años alto riesgo CV (enfermedad vascular O diabetes + factor riesgo), seguimiento 5 años</p>
<p><strong>Intervención:</strong> Ramipril 10 mg/día vs placebo (muchos pacientes NO hipertensos basalmente)</p>
<p><strong>PA basal:</strong> 139/79 mmHg promedio (1/2 normotensos)</p>
<p><strong>↓ PA:</strong> 3/2 mmHg (ramipril vs placebo) - PEQUEÑA</p>
<p><strong>Resultados (beneficio MAYOR que esperado por ↓ PA sola):</strong></p>
<ul>
<li><strong>↓ 22% eventos CV mayores</strong> (IAM, stroke, muerte CV) - P<0.001</li>
<li>↓ 20% IAM</li>
<li>↓ 32% stroke</li>
<li>↓ 16% mortalidad total</li>
<li>↓ 24% mortalidad CV</li>
</ul>
<p><strong>Interpretación:</strong> IECA tienen beneficios MÁS ALLÁ reducción PA (efectos pleiotrópicos: ↓ remodelado vascular, estabilización placa, efectos antiinflamatorios, antiarrítmicos)</p>
<p><strong>Impacto:</strong> Estableció IECA indicación fuerte post-IAM, diabetes alto riesgo, enfermedad vascular, independiente PA basal</p>
</div>

<div class="evidence-box">
<h4>Meta-análisis Reducción PA y Outcomes CV (Ettehad et al., Lancet 2016)</h4>
<p><strong>Análisis:</strong> 123 RCTs, 613,815 participantes</p>
<p><strong>Hallazgos:</strong></p>
<ul>
<li><strong>Cada 10 mmHg ↓ PA sistólica:</strong>
  <ul>
    <li>↓ 20% eventos coronarios mayores</li>
    <li>↓ 27% stroke</li>
    <li>↓ 28% insuficiencia cardíaca</li>
    <li>↓ 13% mortalidad total</li>
  </ul>
</li>
<li>Beneficio proporcional similar independiente PA basal (incluso <130 mmHg)</li>
<li>Sin evidencia umbral inferior beneficio ("lower is better" dentro rango razonable)</li>
<li>Beneficio consistente todas clases antihipertensivas principales</li>
</ul>
<p><strong>Conclusión:</strong> Reducción PA per se (independiente agente) confiere beneficio CV; magnitud beneficio proporcional magnitud reducción PA</p>
</div>

