<p><strong>Ventajas MAPA:</strong></p>
<ul>
<li>Múltiples mediciones (30-80) → promedio más representativo</li>
<li>Elimina efecto bata blanca</li>
<li>Identifica HTA enmascarada</li>
<li>Evalúa PA nocturna (no evaluable consultorio)</li>
<li>Mejor predictor outcomes CV que PA consultorio (múltiples estudios)</li>
<li>Evalúa variabilidad PA</li>
</ul>

<p><strong>Limitaciones:</strong></p>
<ul>
<li>Costo ($150-300 estudio)</li>
<li>Disponibilidad limitada (no todos centros)</li>
<li>Incomodidad (interferencia sueño, actividades)</li>
<li>Mediciones ocasionales fallan (movimiento, arritmias)</li>
</ul>

<h4>Monitoreo Domiciliario Presión Arterial (MDPA / HBPM)</h4>

<p><strong>Método:</strong></p>
<ul>
<li>Dispositivo validado automático (oscilométrico) brazo superior</li>
<li>Paciente mide en casa siguiendo protocolo</li>
</ul>

<p><strong>Protocolo recomendado:</strong></p>
<ul>
<li><strong>Frecuencia:</strong> 2 mediciones AM (pre-medicación, pre-desayuno) + 2 mediciones PM (pre-cena), 7 días consecutivos</li>
<li><strong>Técnica:</strong> Mismos principios medición consultorio (reposo 5 min, etc.)</li>
<li><strong>Registro:</strong> Todas mediciones en diario/app</li>
<li><strong>Reporte:</strong> Promedio todas mediciones (descartar día 1)</li>
</ul>

<p><strong>Umbral hipertensión MDPA:</strong> ≥135/85 mmHg (promedio)</p>

<p><strong>Ventajas MDPA:</strong></p>
<ul>
<li>Bajo costo (~$30-100 dispositivo validado)</li>
<li>Conveniente, repetible</li>
<li>Elimina bata blanca</li>
<li>↑ Adherencia tratamiento (engagement paciente)</li>
<li>Mejor predictor outcomes vs consultorio</li>
<li>Útil monitoreo largo plazo</li>
</ul>

<p><strong>Limitaciones:</strong></p>
<ul>
<li>Requiere educación/entrenamiento paciente</li>
<li>Dispositivos no validados comunes (↑ error)</li>
<li>No evalúa PA nocturna</li>
<li>Potencial ansiedad/obsesión mediciones</li>
</ul>

<p><strong>Validación dispositivos:</strong> Verificar lista dispositivos validados:</p>
<ul>
<li>dabl Educational Trust: <a href="https://www.dableducational.org" target="_blank">dableducational.org</a></li>
<li>Stride BP: <a href="https://www.stridebp.org" target="_blank">stridebp.org</a></li>
<li>Evitar: Monitores muñeca (menos precisos), dedo (muy imprecisos)</li>
</ul>
