<h3>¿Puedo suspender medicación si mi PA está controlada?</h3>
    <p>NO sin supervisión médica. PA controlada = éxito tratamiento (estilo vida + medicación), NO curación hipertensión. Hipertensión esencial es condición crónica, generalmente requiere tratamiento indefinido. Suspensión medicación → PA típicamente ↑ semanas-meses regresando niveles pre-tratamiento. Excepciones posibles (discutir médico): (1) Pérdida peso sustancial (15-20 kg) con estilo vida ejemplar sostenido → algunos pacientes logran suspender/reducir, (2) HTA secundaria corregida (ej: hiperaldosteronismo resecado), (3) HTA "reactiva" situacional (estrés laboral resuelto), (4) Ancianos frágiles donde riesgo/beneficio cambia. Si desea intentar reducir medicación: (1) NUNCA suspender abruptamente (algunos fármacos - clonidina, β-bloqueadores - causan efecto rebote peligroso), (2) Solo bajo supervisión médica, (3) Después período prolongado (≥1 año) control excelente PA + estilo vida óptimo, (4) Reducción gradual UN fármaco a vez, (5) Monitoreo estrecho MDPA durante/post-reducción.</p>
    
    <h3>¿Es normal que mi PA sea más baja en casa que en el consultorio médico?</h3>
    <p>SÍ - muy común. PA consultorio típicamente 5-10 mmHg MÁS ALTA vs domiciliaria (estrés, ansiedad, prisa - "efecto bata blanca"). Si diferencia >20/10 mmHg: "Hipertensión bata blanca" - PA elevada consultorio (≥140/90) PERO normal ambulatoria/domiciliaria (<135/85 promedio MDPA o <130/80 MAPA 24h). Prevalencia: 15-30% PA elevada consultorio. Riesgo CV: Intermedio (entre normotensos y HTA sostenida), NO benigno. Manejo: (1) Confirmar con MAPA 24h o MDPA rigurosa antes iniciar farmacoterapia (evitar sobretratamiento), (2) Modificaciones estilo vida (HTA bata blanca frecuentemente progresa HTA sostenida), (3) Seguimiento anual (monitorear progresión), (4) Farmacoterapia SI riesgo CV alto (ASCVD, diabetes, daño órgano blanco) O progresión HTA sostenida. Opuesto también existe: "Hipertensión enmascarada" - PA normal consultorio PERO elevada fuera (10-15% prevalencia, riesgo CV similar HTA sostenida, frecuentemente no diagnosticada). Sospecha: Daño órgano blanco sin HTA consultorio, historia familiar fuerte.</p>
    
    <h3>¿Qué tan bajo es "demasiado bajo" para presión arterial?</h3>
    <p>Controversia - no hay consenso absoluto, pero guía: PA <90/60 mmHg = hipotensión (por definición). PERO: Muchas personas sanas (especialmente jóvenes, atléticas, mujeres) tienen PA 100-110/60-70 mmHg sin síntomas - NORMAL para ellos. Preocupa hipotensión si: (1) Síntomas: Mareos, lipotimia, síncope, visión borrosa, fatiga extrema, náusea, confusión, (2) Hipotensión ortostática: ↓ ≥20 sistólica o ≥10 diastólica al ponerse de pie (↑ riesgo caídas, especialmente ancianos), (3) Shock: PA críticamente baja + hipoperfusión órganos (emergencia médica). En tratamiento hipertensión: Meta PA <130/80 segura mayoría pacientes SPRINT (meta <120) sin ↑ eventos adversos mayores excepto: (1) Hipotensión sintomática: 2.4% vs 1.4%, (2) Síncope: 2.3% vs 1.7%, (3) Ancianos ≥75: Beneficio similar, sin ↑ caídas. Límite práctico: Evitar PA <110/70 si síntomas, o <100/60 ancianos frágiles. Individualizar - algunos toleran PA más bajas sin problemas, otros síntomas con PA "normal". Guiarse por síntomas + función, NO número aislado.</p>
    
    <h3>¿Necesito realmente cambiar dieta si tomo medicación para PA?</h3>
    <p>SÍ - estilo vida NO es opcional incluso con medicación. Razones: (1) Efectos aditivos: Dieta DASH + medicación = ↓ PA mayor que cualquiera solo (15-20 mmHg combinados), (2) Menor dosis medicación necesaria: Estilo vida óptimo puede reducir requerimiento 1-2 fármacos, (3) Otros beneficios CV: DASH mejora lípidos, resistencia insulina, peso - beneficia más allá PA, (4) Algunos logran suspender medicación: Pérdida peso + DASH rigurosa → 30-50% hipertensos estadio 1 alcanzan control sin fármacos, (5) Medicación trata síntoma (↓ PA) NO causa raíz (obesidad, exceso Na+, sedentarismo) - estilo vida ataca causa, (6) Sostenibilidad: Estilo vida sin efectos adversos farmacológicos, costo, adherencia largo plazo. Datos: Ensayo ENCORE - hipertensos medicados: Adición programa estilo vida intensivo (DASH + ejercicio + pérdida peso) → ↓ adicional 16/10 mmHg vs medicación sola, 50% redujeron medicación. Mensaje: Medicación + estilo vida = óptimo; solo medicación = subóptimo; solo estilo vida = posible HTA leve, insuficiente HTA moderada-severa.</p>
    
    <h3>¿Los monitores de PA domiciliarios son confiables?</h3>
    <p>SI dispositivo VALIDADO y usado CORRECTAMENTE - sí, confiables. Problema: Mayoría dispositivos mercado (especialmente económicos, muñeca, dedo) NO validados - precisión variable/pobre. Cómo asegurar confiabilidad: (1) Comprar dispositivo VALIDADO - verificar listas: stridebp.org, dableducational.org, (2) Brazo superior (NO muñeca/dedo), (3) Método oscilométrico automático (NO auscultatorio casero - requiere entrenamiento), (4) Manguito apropiado tamaño brazo (crítico - verificar rango brazo dispositivo), (5) Validar contra medición clínica: Llevar monitor primera visita médica, comparar lecturas simultáneas (diferencia <10 mmHg aceptable), (6) Seguir técnica correcta rigurosamente (reposo 5 min, brazo apoyado nivel corazón, espalda apoyada, pies planos, sin hablar), (7) Re-calibración: Validar anualmente contra clínico, reemplazar dispositivo cada 2-3 años. Estudios: Dispositivos validados precisión ±5 mmHg vs auscultatorio/MAPA. MDPA con dispositivo validado predice outcomes CV MEJOR que PA consultorio. Costo dispositivo validado: $30-100 (inversión pequeña vs beneficio).</p>
    
    <h3>¿Cuánta sal (sodio) puedo consumir con hipertensión?</h3>
    <p>Recomendación AHA/ACC: <strong><2,300 mg sodio/día</strong> (todos adultos, hipertensos o no). Meta IDEAL hipertensos/alto riesgo: <strong><1,500 mg/día</strong>. Contexto: Americano promedio consume 3,400 mg/día (mucho exceso). Reducción 2,300→1,500 mg: ↓ 5-6 mmHg PA promedio (equivalente 1 fármaco). Sensibilidad sal: 40-60% hipertensos "sal-sensibles" (PA responde marcadamente ingesta Na+) - frecuente en: negros, ancianos, diabéticos, ERC. Ellos benefician MÁS restricción. Equivalencias prácticas: 2,300 mg Na+ = 1 cucharadita sal (5.8 g), 1,500 mg = 2/3 cucharadita. Pero ATENCIÓN: 75% sodio proviene alimentos procesados/restaurantes (NO salero). Fuentes ocultas alto Na+: Pan (230 mg/rebanada promedio), quesos, embutidos/carnes procesadas (salami 1,000+ mg), sopas enlatadas (800+ mg/taza), pizzas, sandwiches, salsas. Estrategia: (1) Evitar ultra-procesados, (2) Cocinar fresco controlando sal, (3) Leer etiquetas (<5% VD/porción = bajo Na+), (4) Sustituir sal por especias/hierbas, (5) Enjuagar enlatados, (6) Restaurantes: Sin sal/salsa aparte. Balance: Restricción <1,000 mg/día NO recomendada (puede activar SRAA contraproductivamente); 1,500-2,300 mg = zona óptima riesgo/beneficio hipertensos.</p>
    
    <h3>¿Cuánto tiempo toma ver resultados del tratamiento?</h3>
    <p>Variable según intervención: <strong>Medicación:</strong> Efecto completo 2-4 semanas mayoría fármacos (algunos - CCB, tiazidas - semanas máximo efecto; IECA/ARA-II - días-semanas). Monitoreo: Reevaluar 2-4 semanas post-inicio/cambio dosis. <strong>Pérdida peso:</strong> ↓ PA proporcional pérdida: 1 kg → ~1 mmHg. Pérdida 5-10 kg (alcanzable 3-6 meses) → ↓ 5-10 mmHg. Efecto máximo cuando peso estabiliza. <strong>Dieta DASH:</strong> Efecto detectable 2 semanas, máximo 4-8 semanas adherencia rigurosa. DASH Trial: ↓ 11.4 mmHg a 8 semanas. <strong>Reducción sodio:</strong> Efecto 1-2 semanas (rápido), máximo 4 semanas. <strong>Ejercicio:</strong> Efecto agudo 24h post-ejercicio (↓ 5-7 mmHg), efecto crónico acumula 4-12 semanas ejercicio regular. <strong>Combinación estilo vida:</strong> Pérdida peso + DASH + ejercicio: ↓ sustancial (15-20 mmHg) visible 8-12 semanas, máximo 6 meses. Mensaje clave: Paciencia - cambios significativos requieren semanas-meses adherencia sostenida. NO esperar resultados inmediatos (excepto medicación rápida). Monitoreo frecuente (MDPA) mantiene motivación mostrando progreso gradual.</p>
    
