<h4>Manejo Hipertensión Resistente</h4>

<ol>
<li><strong>Confirmar verdadera resistencia:</strong> MAPA 24h (excluir bata blanca)</li>

<li><strong>Verificar adherencia:</strong> Conversación empática, simplificar régimen (combinaciones fijas), estrategias mejorar adherencia</li>

<li><strong>Optimizar terapia actual:</strong>
  <ul>
    <li>Asegurar diurético tiazida/tiazida-like (considerar cambiar HCTZ → clortalidona si subóptimo)</li>
    <li>Dosis máximas toleradas 3 fármacos base</li>
    <li>Combinación ideal: IECA/ARA-II + CCB (DHP) + Tiazida</li>
  </ul>
</li>

<li><strong>Añadir 4º agente:</strong>
  <ul>
    <li><strong>Espironolactona 25-50 mg/día</strong> - MÁS EFECTIVO (↓ PA adicional 20-25/10-12 mmHg promedio)
