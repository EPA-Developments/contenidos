<h1>Presión Arterial: La Métrica #8 de Life's Essential 8™</h1>

<p>La <strong>presión arterial (PA)</strong> es la octava y final métrica esencial para salud cardiovascular, completando el framework integral de Life's Essential 8™. La hipertensión arterial afecta a <strong>1.28 mil millones adultos globalmente (46% población adulta)</strong>, siendo el <strong>factor de riesgo cardiovascular modificable más prevalente</strong> y el <strong>contribuyente líder de mortalidad global</strong> (10.8 millones muertes/año).</p>

<p>La evidencia es inequívoca: <strong>cada incremento de 20 mmHg presión sistólica o 10 mmHg diastólica duplica el riesgo de muerte cardiovascular</strong>. La relación PA ↔ riesgo CV es <strong>continua, log-lineal, sin umbral</strong> desde 115/75 mmHg. Sin embargo, la hipertensión es <strong>altamente modificable</strong>: reducción 10 mmHg PA sistólica disminuye 20% eventos coronarios, 27% stroke, 28% insuficiencia cardíaca, y 13% mortalidad total.</p>

