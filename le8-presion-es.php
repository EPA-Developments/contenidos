<h4>🚨 Hipertensión Pediátrica - Problema Creciente</h4>

<p><strong>Epidemiología:</strong></p>
<ul>
<li>Prevalencia hipertensión pediátrica: 3.5% (↑ desde 2.5% década 1990)</li>
<li>Hipertensión Estadio 2: 1.3%</li>
<li><strong>Obesidad infantil:</strong> Factor impulsor principal (50-60% hipertensión pediátrica asociada obesidad)</li>
<li>Disparidades: Afroamericanos e Hispanos > prevalencia</li>
</ul>

<p><strong>Consecuencias:</strong></p>
<ul>
<li>Tracking: 40% niños hipertensos → adultos hipertensos</li>
<li>Daño órgano blanco temprano: Hipertrofia VI (20-40% niños HTA severa), engrosamiento carotídeo</li>
<li>Riesgo CV adulto aumentado</li>
</ul>

<p><strong>Causas hipertensión pediátrica:</strong></p>
<ul>
<li><strong>Primaria (esencial):</strong> 85-95% (especialmente adolescentes obesos)</li>
<li><strong>Secundaria:</strong> 5-15% (más frecuente <6 años)
  <ul>
    <li>Renal: Enfermedad parenquimatosa, renovascular (estenosis arteria renal)</li>
    <li>Cardiovascular: Coartación aorta</li>
    <li>Endocrina: Feocromocitoma, hiperaldosteronismo, Cushing, hipertiroidismo</li>
    <li>Medicaciones: Corticosteroides, simpaticomiméticos, anticonceptivos orales</li>
  </ul>
</li>
</ul>

<p><strong>Screening recomendado:</strong></p>
<ul>
<li><strong>Anual ≥3 años</strong> todas visitas atención primaria</li>
<li>Método auscultatorio (gold standard pediátrico)</li>
<li>Manguito apropiado (ancho 40% circunferencia brazo)</li>
<li>Confirmación 3 visitas separadas antes diagnóstico</li>
</ul>
