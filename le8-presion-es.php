      </ul>
    </li>
    <li><strong>Alternativas:</strong> Bloqueador β (bisoprolol, carvedilol), bloqueador α (doxazosina), vasodilatador directo (hidralazina), bloqueador α-2 central (clonidina)</li>
  </ul>
</li>

