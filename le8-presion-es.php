<h2 id="manejo">Manejo Hipertensión</h2>

<h3>🎯 Estratificación Riesgo Cardiovascular</h3>

<div class="cv-risk-stratification">
<p><strong>Tratamiento NO basado solo nivel PA, sino riesgo CV global</strong></p>

<h4>Calculadora Riesgo ACC/AHA (ASCVD Risk Estimator)</h4>

<p><strong>Incorpora:</strong> Edad, sexo, raza, PA sistólica, tratamiento HTA, colesterol total, HDL-C, diabetes, tabaquismo</p>

<p><strong>Output:</strong> Riesgo 10 años evento ASCVD (IAM, muerte coronaria, stroke)</p>

<p><strong>Categorías riesgo:</strong></p>
<ul>
<li><strong>Bajo:</strong> <5%</li>
<li><strong>Limítrofe:</strong> 5-7.4%</li>
<li><strong>Intermedio:</strong> 7.5-19.9%</li>
<li><strong>Alto:</strong> ≥20%</li>
</ul>

<h4>Enhancers Riesgo (Considerar si decisión límite)</h4>

<ul>
<li>Historia familiar enfermedad CV prematura</li>
<li>Enfermedad renal crónica (eGFR <60)</li>
<li>Síndrome metabólico</li>
<li>Condiciones inflamatorias crónicas</li>
<li>Menopausia prematura, preeclampsia</li>
<li>Etnias alto riesgo (surasiáticos)</li>
<li>Marcadores: hsCRP ≥2 mg/L, ApoB ≥130, Lp(a) ≥50, tobillo-braquial <0.9</li>
<li><strong>CAC score >0</strong> (especialmente >100)</li>
</ul>

<h4>Daño Órgano Blanco (Indica Alto Riesgo)</h4>

<ul>
<li>Hipertrofia ventricular izquierda (ECG o ecocardiograma)</li>
<li>Retinopatía hipertensiva</li>
<li>Proteinuria/albuminuria</li>
<li>eGFR <60 mL/min/1.73m²</li>
<li>Placas carotídeas (ultrasonido)</li>
<li>↑ Velocidad onda pulso (PWV >10 m/s)</li>
</ul>
</div>

