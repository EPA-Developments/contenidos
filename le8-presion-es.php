<h4>Procedimiento Medición</h4>

<ol>
<li><strong>Colocar manguito:</strong>
  <ul>
    <li>Borde inferior 2-3 cm sobre fosa antecubital</li>
    <li>Centrar vejiga sobre arteria braquial (línea media cara interna brazo)</li>
    <li>Ajustado firme pero no apretado (cabe 1-2 dedos bajo manguito)</li>
  </ul>
</li>

<li><strong>Palpar pulso radial, inflar manguito rápidamente</strong> hasta desaparición pulso + 20-30 mmHg adicionales</li>

<li><strong>Colocar estetoscopio</strong> sobre arteria braquial (fosa antecubital), sin presión excesiva</li>

<li><strong>Desinflar manguito lentamente</strong> 2-3 mmHg/segundo</li>

<li><strong>Auscultar tonos Korotkoff:</strong>
  <ul>
    <li><strong>Fase I:</strong> Primer tono audible = <strong>PRESIÓN SISTÓLICA</strong></li>
    <li><strong>Fase V:</strong> Desaparición tonos = <strong>PRESIÓN DIASTÓLICA</strong></li>
    <li>(Fase IV: Amortiguamiento tonos - raramente usado; usar Fase V)</li>
  </ul>
</li>

<li><strong>Registrar:</strong> Redondear 2 mmHg más cercano</li>

<li><strong>Repetir:</strong> Esperar 1-2 minutos, medir nuevamente</li>

<li><strong>Promedio:</strong> Reportar promedio 2-3 mediciones (descartar primera si discrepancia >10 mmHg)</li>
</ol>

