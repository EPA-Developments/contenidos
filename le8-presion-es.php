<h4>Variabilidad Presión Arterial</h4>

<p><strong>PA NO es constante - varía significativamente:</strong></p>

<div class="bp-variability">
<h5>Variación Circadiana (Patrón 24h)</h5>
<ul>
<li><strong>Patrón "Dipper" (normal):</strong>
  <ul>
    <li>PA ↑ durante día (actividad, estrés)</li>
    <li>PA ↓ 10-20% durante sueño nocturno ("dipping")</li>
    <li>Elevación matutina pronunciada (pico 6-10am) - "morning surge"</li>
  </ul>
</li>
<li><strong>Patrón "Non-Dipper" (anormal):</strong>
  <ul>
    <li>PA NO ↓ adecuadamente durante sueño (<10% reducción)</li>
    <li>Asociado: ↑ Riesgo stroke, HVI, proteinuria, eventos CV</li>
    <li>Causas: Apnea sueño, diabetes, ERC, edad avanzada, alto consumo sal, disfunción autonómica</li>
  </ul>
</li>
<li><strong>Patrón "Reverse Dipper":</strong> PA nocturna > diurna (muy anormal - ↑↑ riesgo CV)</li>
<li><strong>Patrón "Extreme Dipper":</strong> ↓ >20% nocturna (riesgo stroke isquémico nocturno/matutino)</li>
</ul>

<h5>Variación Latido-a-Latido</h5>
<ul>
<li>Respiración: ↓ PA inspiración (10-20 mmHg variación respiratoria normal)</li>
<li>Arritmias: Fibrilación atrial → PA muy variable</li>
</ul>

<h5>Variación Visita-a-Visita (Largo Plazo)</h5>
<ul>
<li>↑ Variabilidad visita-a-visita (independiente PA promedio) asociada ↑ riesgo CV</li>
<li>Posible marcador rigidez arterial, disfunción autonómica</li>
</ul>

<h5>Hipertensión "Bata Blanca"</h5>
<ul>
<li>PA elevada consultorio PERO normal ambulatoria/domiciliaria</li>
<li>Prevalencia: 15-30% pacientes PA elevada consultorio</li>
<li>Riesgo CV: Intermedio (entre normotensos y HTA sostenida)</li>
<li>Requiere monitoreo ambulatorio confirmación antes tratamiento</li>
</ul>

<h5>Hipertensión "Enmascarada"</h5>
<ul>
<li>PA normal consultorio PERO elevada ambulatoria/domiciliaria</li>
<li>Prevalencia: 10-15% población general</li>
<li>Riesgo CV: Similar HTA sostenida (frecuentemente no diagnosticada/tratada)</li>
<li>Sospecha: Daño órgano blanco sin HTA consultorio, historia familiar fuerte, diabetes, ERC</li>
</ul>
</div>
