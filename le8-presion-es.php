<h3>💔 Consecuencias Cardiovasculares Hipertensión</h3>

<div class="cv-consequences-htn">
<h4>Hipertensión = "Asesino Silencioso"</h4>

<p><strong>Por qué "silencioso":</strong> Mayoría pacientes HTA asintomáticos durante años/décadas mientras daño vascular acumula.</p>

<p><strong>Magnitud problema global:</strong></p>
<ul>
<li>1.28 mil millones adultos con HTA (46% población adulta mundial)</li>
<li>2/3 países ingresos bajos-medios</li>
<li>Solo 42% diagnosticados, tratados, y controlados (países altos ingresos)</li>
<li><15% controlados países bajos ingresos</li>
<li><strong>10.8 millones muertes/año atribuibles HTA</strong> (contribuyente #1 mortalidad global)</li>
</ul>

<h4>Daño Órgano Blanco - Mecanismos y Manifestaciones</h4>

<div class="organ-damage">
<h5>🫀 Corazón</h5>

<p><strong>Hipertrofia Ventricular Izquierda (HVI)</strong></p>
<ul>
<li><strong>Mecanismo:</strong> Sobrecarga presión crónica (↑ postcarga) → hipertrofia compensatoria miocitos</li>
<li><strong>Prevalencia:</strong> 15-60% hipertensos (según método detección, severidad HTA)</li>
<li><strong>Tipos:</strong>
  <ul>
    <li>Concéntrica (grosor pared ↑, cavidad normal) - HTA sostenida</li>
    <li>Excéntrica (grosor Y dilatación) - sobrecarga volumen agregada</li>
  </ul>
</li>
<li><strong>Consecuencias:</strong>
  <ul>
    <li>Disfunción diastólica (rigidez miocárdica, ↓ compliance)</li>
    <li>Isquemia subendocárdica (hipertrofia supera vascularización)</li>
    <li>Arritmias (FA, arritmias ventriculares)</li>
<li>Progresión insuficiencia cardíaca (HFpEF >> HFrEF)</li>
  </ul>
</li>
<li><strong>Regresión:</strong> Tratamiento PA agresivo → ↓ masa VI (pero normalización completa rara)</li>
</ul>

<p><strong>Enfermedad Coronaria</strong></p>
<ul>
<li>HTA acelera aterosclerosis coronaria (estrés hemodinámico, disfunción endotelial, inflamación)</li>
<li>↑ 2-3× riesgo IAM</li>
<li>Cada 20 mmHg ↑ PAS → ↑ 50% mortalidad enfermedad coronaria</li>
</ul>

<p><strong>Insuficiencia Cardíaca</strong></p>
<ul>
<li>HTA = causa #1 IC globalmente (especialmente HFpEF)</li>
<li>↑ 2-3× riesgo IC vs normotensos</li>
<li>HVI + disfunción diastólica → IC sintomática</li>
</ul>

<h5>🧠 Cerebro</h5>

<p><strong>Stroke Isquémico</strong></p>
<ul>
<li>HTA = factor riesgo modificable MÁS IMPORTANTE stroke</li>
<li>↑ 3-5× riesgo stroke</li>
<li>Mecanismos:
  <ul>
    <li>Aterosclerosis acelerada arterias cerebrales grandes</li>
    <li>Lipohialinosis arterias pequeñas penetrantes</li>
    <li>Embolia cardiogénica (FA frecuentemente coexiste)</li>
  </ul>
</li>
<li>Cada 10 mmHg ↓ PAS → ↓ 27% stroke (meta-análisis)</li>
</ul>

<p><strong>Stroke Hemorrágico (Intracerebral, Subaracnoideo)</strong></p>
<ul>
<li>HTA = factor riesgo DOMINANTE hemorragia intracerebral</li>
<li>↑ 5-10× riesgo vs normotensos</li>
<li>Sitios típicos: Ganglios basales, tálamo, protuberancia, cerebelo (arterias penetrantes)</li>
</ul>

<p><strong>Enfermedad Pequeños Vasos Cerebrales</strong></p>
<ul>
<li>Infartos lacunares múltiples (silentes frecuentemente)</li>
<li>Leucoaraiosis (lesiones substancia blanca)</li>
<li>Microhemorragias</li>
<li>Contribuye deterioro cognitivo vascular, demencia</li>
</ul>

<p><strong>Encefalopatía Hipertensiva</strong></p>
<ul>
<li>Complicación aguda HTA severa (usualmente PAS >180, PAD >120)</li>
<li>Ruptura autorregulación cerebrovascular → edema cerebral</li>
<li>Clínica: Cefalea, confusión, convulsiones, déficits focales, coma</li>
<li>Emergencia médica - reducción PA IV gradual necesaria</li>
</ul>

<h5>🫘 Riñón - Nefroesclerosis Hipertensiva</h5>

<p><strong>Mecanismos daño:</strong></p>
<ul>
<li>Presión elevada transmitida glomérulo → daño podocitos, mesangio</li>
<li>Arterioloesclerosis aferente/eferente</li>
<li>Isquemia glomerular → esclerosis</li>
<li>Fibrosis túbulo-intersticial</li>
</ul>

<p><strong>Manifestaciones:</strong></p>
<ul>
<li>Proteinuria (inicialmente microalbuminuria <300 mg/día, progresa proteinuria franca)</li>
<li>↓ eGFR progresivo (pérdida 1-5 mL/min/1.73m²/año si no controlada)</li>
<li>Enfermedad Renal Crónica (ERC) - HTA causa #2 ERC (después diabetes)</li>
<li>Enfermedad Renal Terminal (ERT) - 30% pacientes diálisis por HTA</li>
</ul>

<p><strong>Círculo vicioso:</strong> HTA → daño renal → ↑ HTA (retención sal/agua, ↑ SRAA) → más daño renal</p>

<h5>👁️ Ojos - Retinopatía Hipertensiva</h5>

<p><strong>Clasificación Keith-Wagener-Barker (modificada):</strong></p>
<ul>
<li><strong>Grado I:</strong> Estrechamiento arteriolar leve</li>
<li><strong>Grado II:</strong> Estrechamiento arteriolar focal, cruces arteriovenosos patológicos</li>
<li><strong>Grado III:</strong> Hemorragias retinianas, exudados algodonosos, edema</li>
<li><strong>Grado IV:</strong> Grado III + papiledema (emergencia - encefalopatía hipertensiva frecuentemente)</li>
</ul>

<p><strong>Consecuencias:</strong></p>
<ul>
<li>Pérdida visión (generalmente grados III-IV)</li>
<li>Marcador daño sistémico (retinopatía severa correlaciona daño cerebral, renal, cardíaco)</li>
</ul>

<h5>🩸 Vasos Sanguíneos - Enfermedad Vascular</h5>

<p><strong>Aterosclerosis Acelerada</strong></p>
<ul>
<li>HTA factor riesgo aterosclerosis (estrés hemodinámico, disfunción endotelial, inflamación)</li>
<li>Afecta todos lechos vasculares: coronario, cerebral, periférico, renal, mesentérico</li>
</ul>

<p><strong>Rigidez Arterial</strong></p>
<ul>
<li>HTA crónica → remodelado vascular (hipertrofia media, fibrosis, calcificación)</li>
<li>↑ Velocidad onda pulso (PWV) - marcador rigidez arterial, predictor CV independiente</li>
<li>↑ Presión pulso (PAS-PAD) - refleja rigidez aorta</li>
</ul>

<p><strong>Aneurismas</strong></p>
<ul>
<li>Aorta abdominal: ↑ 2-3× riesgo</li>
<li>Aneurismas cerebrales: HTA principal factor riesgo ruptura</li>
</ul>

<p><strong>Disección Aórtica</strong></p>
<ul>
<li>HTA presente 70-90% casos</li>
<li>Emergencia médica - mortalidad 1-2%/hora sin tratamiento</li>
</ul>

<p><strong>Enfermedad Arterial Periférica</strong></p>
<ul>
<li>↑ 2-3× riesgo claudicación intermitente</li>
<li>HTA + tabaco = sinergia particularmente deletérea</li>
</ul>
</div>
</div>

<h2 id="medicion">Medición Correcta Presión Arterial</h2>

<h3>📏 Técnica Auscultatorio (Gold Standard Clínico)</h3>

<div class="bp-measurement">
<h4>Preparación Paciente</h4>

<ol>
<li><strong>Reposo 5 minutos:</strong> Sentado tranquilamente, espalda apoyada, pies planos en piso</li>
<li><strong>Evitar 30 min previos:</strong> Cafeína, ejercicio, tabaco</li>
<li><strong>Vejiga vacía:</strong> Vejiga llena ↑ PA 10-15 mmHg</li>
<li><strong>No hablar</strong> durante medición</li>
<li><strong>Brazo descubierto:</strong> Sin ropa apretada</li>
<li><strong>Brazo apoyado:</strong> Nivel corazón (ángulo esternal, 4º espacio intercostal)</li>
</ol>

