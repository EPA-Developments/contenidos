<h2 id="faqs">Preguntas Frecuentes - Residentes</h2>

<div class="faq-section">
<h3>¿Es realista mantener Life's Essential 8™ durante residencia, o debo esperar post-residencia?</h3>
<p><strong>Realista - pero con expectativas ajustadas.</strong> Puntuación perfecta (100 todas métricas) NO realista mayoría residentes dadas demandas. PERO puntuación compuesta 75-85 (salud CV "Buena") es alcanzable con estrategias descritas. Importancia comenzar AHORA: (1) Patrones residencia tienden persistir - esperar post-residencia frecuentemente = nunca cambiar, (2) Daño acumulativo - 3-4 años hábitos deletéreos tienen consecuencias largo plazo, (3) Modelado - tu salud afecta cuidado pacientes. Post-residencia, podrás expandir/optimizar, pero fundación establecida durante residencia crítica.</p>

<h3>¿Cómo balanceo estudio (Boards) con autocuidado sin sentir culpa?</h3>
<p><strong>Reframe mental:</strong> Autocuidado NO es "tiempo perdido" vs estudio - es <strong>optimización rendimiento</strong>. Evidencia: Privación sueño ↓ consolidación memoria 40%, ejercicio mejora función cognitiva/memoria, nutrición adecuada estabiliza energía/concentración. Médico agotado, mal alimentado, sedentario estudia MENOS eficientemente. Estrategia práctica: (1) <strong>Schedule autocuidado como "cita médica"</strong> - bloquea calendario (ej. ejercicio 7-7:30am lunes/miércoles/viernes), (2) <strong>Técnica Pomodoro estudio:</strong> 50 min estudio intenso + 10 min break activo (caminar, estiramientos) = mejor retención que 5h continuas, (3) <strong>Sueño no negociable:</strong> 7h mínimo noche pre-examen (estudiar trasnochado = contraproducente), (4) <strong>Ejercicio = "study break productivo"</strong> - 20-30 min ejercicio mejora concentración subsiguiente 2-3h. Boards importante, pero carrera es maratón - sostenibilidad require cuidarte.</p>

<h3>¿Qué hago si mi programa/cultura no apoya autocuidado?</h3>
<p><strong>Desafortunadamente común.</strong> Estrategias: (1) <strong>Buscar aliados:</strong> Co-residentes con mentalidad similar - apoyo mutuo, accountability, normalizar autocuidado entre pares, (2) <strong>Discreto inicialmente:</strong> No necesitas "anunciar" - simplemente integra hábitos sin justificar excesivamente, (3) <strong>Modelar silenciosamente:</strong> Tu ejemplo (energía sostenida, menor burnout, mejor desempeño clínico) eventualmente notado/valorado, (4) <strong>Comunicar límites apropiadamente:</strong> Defender razonablemente (ej. "necesito salir 5pm este día específico para compromiso personal importante") - establecer precedente aut

ocuidado razonable, (5) <strong>Escalar si tóxico:</strong> Violaciones ACGME work hours, presión explícita ignorar salud, cultura bullying → reportar program director, GME office, ACGME si necesario. Tu bienestar NO es sacrificable. (6) <strong>Post-residencia elección:</strong> Recordar - seleccionarás futura práctica/empleador. Priorizar lugares valoran bienestar médicos.</p>

<h3>¿Debo tomar vitaminas/suplementos dados mi dieta/sueño subóptimos residencia?</h3>
<p><strong>Generalmente NO necesarios si dieta razonablemente variada.</strong> Excepciones considerar: (1) <strong>Vitamina D:</strong> Si exposición solar limitada (mayormente indoors hospital), especialmente invierno, latitudes altas. Lab medir 25-OH vitamina D, suplementar si <30 ng/mL (típico 1,000-2,000 IU/día), (2) <strong>Omega-3 (EPA/DHA):</strong> Si consumo pescado <2×/semana. Suplemento 500-1,000 mg/día o aumentar pescado graso dietético, (3) <strong>Multivitamínico básico:</strong> "Seguro" si preocupación deficiencias, pero evidencia beneficio CV población saludable limitada. NO sustituye dieta adecuada. <strong>EVITAR:</strong> Megadosis vitaminas (A, E - posible daño), suplementos "energía" no regulados (frecuentemente cafeína disfrazada +/- ingredientes cuestionables), "fat burners" (inefectivos, riesgosos). <strong>Mensaje:</strong> Suplementos pueden llenar brechas, pero enfoque primario debe ser optimizar dieta real máximo posible.</p>

<h3>¿Cómo manejo guardias 24h sin destruir completamente mi salud?</h3>
<p><strong>Guardias 24h inevitables cardiología - estrategias minimizar daño:</strong> <strong>Pre-Guardia (24h antes):</strong> (1) Dormir 8-9h noche previa (banco sueño), (2) Comida balanceada, hidratación óptima, (3) Evitar alcohol. <strong>Durante Guardia:</strong> (1) Siesta estratégica si oportunidad (20-30 min 2-4am), set alarm, (2) Comidas pequeñas frecuentes (cada 3-4h) vs 1-2 grandes (evita crash glucémico), proteína + carbohidrato complejo (energía sostenida), (3) Hidratación continua (agua, evitar exceso cafeína/azúcar), (4) Movimiento intermitente (caminar, estiramientos cada 1-2h - combate fatiga, mejora alerta), (5) Exposición luz brillante si disponible (mantiene alerta), (6) Cafeína táctica: 200 mg (2 cafés) cuando necesites alerta peak (ej. 3am), NO continuamente. <strong>Post-Guardia:</strong> (1) Evita conducir inmediatamente si severamente fatigado (riesgo accidente ≈ 0.10% alcohol), (2) Opción A: Siesta corta 2-3h al llegar casa → mantenerse despierto resto día → dormir normal noche (recomendado - re-sincroniza circadiano), (3) Opción B: Dormir largo inmediato 6-8h si fatiga extrema, (4) Exposición luz natural día ayuda re-sincronización, (5) Comida ligera, hidratación, evita alcohol "para dormir", (6) Día post-guardia: actividad ligera OK (caminata), evita ejercicio vigoroso/decisiones importantes. <strong>Recuperación requiere 48-72h completa.</strong></p>

<h3>Tengo historia familiar enfermedad CV prematura - ¿debo hacer algo adicional durante residencia?</h3>
<p><strong>SÍ - historia familiar = factor riesgo significativo, justifica vigilancia/intervención más agresiva.</strong> Acciones: (1) <strong>Screening más frecuente:</strong> Lípidos, glucosa, PA anual (vs cada 3-5 años población general), (2) <strong>Calcular riesgo CV:</strong> ASCVD Risk Estimator incluyendo historia familiar - puede reclasificar riesgo intermedio → alto, (3) <strong>Considerar biomarcadores avanzados:</strong> ApoB, Lp(a) (si historia familiar muy fuerte/temprana), hsCRP, CAC score si riesgo intermedio ambiguo (discutir cardiólogo preventivo), (4) <strong>Intervención estilo vida MÁS agresiva:</strong> Historia familiar NO modificable, pero otros factores SÍ - enfoque compensar riesgo genético con optimización máxima factores modificables, (5) <strong>Umbral más bajo farmacoterapia:</strong> Estatina considerar si LDL persistentemente >160 (vs >190 población general sin historia familiar), (6) <strong>Consejo genético:</strong> Si historia familiar muy fuerte (múltiples familiares 1º grado IAM/muerte súbita <50 años), considerar evaluación genética (hipercolesterolemia familiar, cardiomiopatías hereditarias). <strong>Ventaja residencia cardiología:</strong> Acceso fácil consultas cardiólogos preventivos - aprovechar para establecer plan preventivo personalizado.</p>

