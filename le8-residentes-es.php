<h1 id="intro">Life's Essential 8™ para Residentes de Cardiología</h1>

<div class="highlight-box">
<p><strong>"Médico, cúrate a ti mismo"</strong> - Lucas 4:23</p>
<p>Como residentes de cardiología, dedicamos nuestras vidas a prevenir y tratar enfermedades cardiovasculares en nuestros pacientes. Paradójicamente, <strong>los médicos residentes tienen mayor prevalencia de factores de riesgo cardiovascular</strong> que la población general de su edad: 44% obesidad/sobrepeso, 23% hipertensión, 40% dislipidemia, 58% sedentarismo, y <strong>78% reportan sueño insuficiente crónico</strong>.</p>

<p>La residencia de cardiología es un período de transformación profesional intenso - típicamente 3-4 años de jornadas extendidas (60-80 horas/semana), guardias nocturnas frecuentes, estrés emocional sostenido, y frecuentemente descuido sistemático del autocuidado. Este programa adapta <strong>Life's Essential 8™</strong> a la realidad única de la residencia, proporcionando estrategias prácticas, basadas en evidencia, para mantener tu salud cardiovascular óptima mientras formas a la próxima generación de cardiólogos.</p>
</div>
<br />
<h2>¿Por Qué Life's Essential 8™ para Residentes?</h2>

<div class="why-residents">
<h3>La Paradoja del Médico</h3>

<p><strong>Conocemos la ciencia, pero no siempre la aplicamos a nosotros mismos.</strong></p>

<p>Estudios demuestran que médicos residentes:</p>
<ul>
<li>Tienen <strong>conocimiento superior</strong> sobre prevención cardiovascular vs público general</li>
<li>Pero <strong>tasas similares o peores</strong> de factores de riesgo CV modificables</li>
<li>Frecuentemente <strong>posponen autocuidado</strong> ("cuando termine la guardia", "cuando termine la residencia")</li>
<li>Desarrollan <strong>cultura normalización</strong> comportamientos no saludables (dormir 4h = "suficiente", saltear comidas = "parte del trabajo")</li>
<li>Experimentan <strong>burnout</strong> significativo (50-60% residentes) - asociado con peor autocuidado</li>
</ul>

<h3>Consecuencias Largo Plazo</h3>

<p><strong>Patrones establecidos durante residencia tienden a persistir:</strong></p>

<ul>
<li>Estudio longitudinal médicos: Hábitos salud residencia predicen fuertemente hábitos 10-20 años post-residencia</li>
<li>Médicos con sobrepeso en residencia: 85% continúan sobrepeso/obesidad como attending</li>
<li>Residentes sedentarios: 70% permanecen sedentarios práctica establecida</li>
<li>Burnout residencia: Factor riesgo significativo burnout carrera temprana</li>
</ul>

<p><strong>Pero también ventana de oportunidad:</strong> Intervenciones autocuidado durante residencia pueden establecer patrones saludables duraderos.</p>

<h3>Impacto en Cuidado Pacientes</h3>

<p><strong>Tu salud afecta directamente la calidad del cuidado que proporcionas:</strong></p>

<ul>
<li><strong>Modelado comportamiento:</strong> Médicos con hábitos saludables más efectivos consejería estilo vida (pacientes perciben autenticidad/credibilidad)</li>
<li><strong>Decisiones clínicas:</strong> Privación sueño (común residencia) deteriora juicio clínico, aumenta errores médicos 36% post-guardias extendidas</li>
<li><strong>Empatía/conexión:</strong> Burnout asociado con ↓ empatía, ↑ despersonalización, menor satisfacción paciente</li>
<li><strong>Sostenibilidad carrera:</strong> Médicos saludables tienen carreras más largas, productivas, satisfactorias</li>
</ul>

<div class="quote-box">
<p><em>"No puedes verter de una copa vacía. Cuidarte a ti mismo no es egoísta - es fundamental para cuidar a otros."</em></p>
</div>
</div>

<h2 id="desafios">Desafíos Únicos de la Residencia de Cardiología</h2>

<div class="challenges-section">
<h3>1. Jornadas Extendidas y Horarios Impredecibles</h3>

<div class="challenge-detail">
<p><strong>Realidad:</strong></p>
<ul>
<li>Promedio 60-80 horas/semana (ACGME límite 80h/semana promediado 4 semanas)</li>
<li>Guardias 24+4 horas (permitidas post-PGY1)</li>
<li>Rotaciones exigentes: UCI, hemodinamia, electrofisiología</li>
<li>Horarios variables rotan mensualmente</li>
<li>Emergencias impredecibles (códigos, IAM, inestabilidad hemodinámica)</li>
</ul>

<p><strong>Impacto Life's Essential 8™:</strong></p>
<ul>
<li><strong>Actividad física:</strong> Difícil programar ejercicio cuando jornadas variables/impredecibles</li>
<li><strong>Sueño:</strong> Privación crónica (<6h promedio noches guardia, fragmentación post-guardia)</li>
<li><strong>Dieta:</strong> Horarios comida irregulares, dependencia cafetería hospital/vending machines</li>
<li><strong>Estrés:</strong> Sostenido sin períodos recuperación adecuados</li>
</ul>
</div>

<h3>2. Cultura "Hustle" y Normalización Autocuidado Deficiente</h3>

<div class="challenge-detail">
<p><strong>Realidad:</strong></p>
<ul>
<li>Cultura implícita: "Trabajar duro = dormir poco, saltear comidas, posponer necesidades personales"</li>
<li>Presión pares: Temor parecer "débil" o "no comprometido" si priorizas autocuidado</li>
<li>Competitividad: Comparación con co-residentes (¿quién duerme menos? ¿quién trabaja más horas?)</li>
<li>"Síndrome Superman/Superwoman": Expectativa médicos "aguantan todo"</li>
<li>Minimización síntomas propios: "No es para tanto", "puedo manejarlo"</li>
</ul>

<p><strong>Consecuencia:</strong> Autocuidado percibido como "lujo" o "debilidad" en lugar de necesidad fundamental.</p>
</div>

<h3>3. Acceso Limitado Opciones Alimentación Saludable</h3>

<div class="challenge-detail">
<p><strong>Realidad:</strong>
<ul>
<li>Cafetería hospital: Opciones limitadas horarios nocturnos/fines de semana</li>
<li>Vending machines: Dominados snacks ultra-procesados, alto sodio/azúcar</li>
<li>Tiempo escaso: "Comer rápido" prioridad sobre "comer saludable"</li>
<li>Reuniones médicas: Pizza, donuts, comida rápida frecuente</li>
<li>Costo: Opciones más saludables frecuentemente más caras con salario residente limitado</li>
</ul>
</div>

<h3>4. Estrés y Carga Emocional</h3>

<div class="challenge-detail">
<p><strong>Fuentes estrés residencia:</strong></p>
<ul>
<li><strong>Responsabilidad clínica:</strong> Tomar decisiones vida/muerte bajo supervisión variable</li>
<li><strong>Volumen trabajo:</strong> Listas pacientes extensas, documentación masiva</li>
<li><strong>Exposición sufrimiento:</strong> Muertes, malas noticias, pacientes jóvenes IAM</li>
<li><strong>Relaciones interpersonales:</strong> Dinámicas equipo, conflictos ocasionales, feedback negativo</li>
<li><strong>Exámenes:</strong> Boards, presentaciones, evaluaciones continuas</li>
<li><strong>Vida personal:</strong> Relaciones tensionadas, tiempo familia limitado, aislamiento social</li>
<li><strong>Financiero:</strong> Deuda estudiantil, salario modesto, costo vida</li>
</ul>

<p><strong>Manifestaciones:</strong></p>
<ul>
<li>Ansiedad (33% residentes)</li>
<li>Depresión (28%)</li>
<li>Burnout (50-60%) - agotamiento emocional, despersonalización, sentimiento ineficacia</li>
<li>Ideación suicida (6% anualmente - tasa superior población general)</li>
</ul>
</div>

<h3>5. Falta Tiempo y Energía Ejercicio</h3>

<div class="challenge-detail">
<p><strong>Barreras ejercicio residentes:</strong></p>
<ul>
<li>58% residentes no cumplen recomendaciones mínimas actividad física (150 min/semana)</li>
<li>Post-guardia: Fatiga extrema, solo deseo dormir</li>
<li>Días laborales: Salir hospital 7-8pm → oscuro, cansado, sin motivación</li>
<li>Costo: Membresías gym $30-100/mes (gasto "no esencial" presupuesto residente)</li>
<li>Sentimiento culpa: "Debería estar estudiando" en lugar de ejercitando</li>
</ul>
</div>

<h3>6. Interrupción Ritmos Circadianos</h3>

<div class="challenge-detail">
<p><strong>Impacto guardias nocturnas:</strong></p>
<ul>
<li>Desincronización circadiana (reloj interno vs horario externo)</li>
<li>Consecuencias metabólicas: ↑ Resistencia insulina, ↑ apetito hormonal (ghrelin ↑, leptina ↓), ↑ riesgo obesidad/diabetes</li>
<li>Cardiovasculares: ↑ PA, ↑ FC, disfunción endotelial, ↑ inflamación (PCR)</li>
<li>Cognitivas: ↓ Atención, ↓ memoria, ↓ función ejecutiva, ↑ errores</li>
<li>Psicológicas: ↑ Irritabilidad, ↑ depresión, ↓ bienestar</li>
</ul>

<p><strong>Recuperación:</strong> Requiere 2-3 días normalizar ritmos post-guardia nocturna - frecuentemente no permitido antes próxima guardia.</p>
</div>
</div>

<h2 id="estrategias">Estrategias Prácticas Life's Essential 8™ para Residentes</h2>

<div class="strategies-intro">
<p><strong>Filosofía clave:</strong> <em>Perfección es enemigo de lo bueno.</em> Durante residencia, el objetivo NO es salud cardiovascular "perfecta" (100 puntos todas métricas) - objetivo REALISTA es <strong>prevenir deterioro significativo</strong> y <strong>mantener prácticas mínimas protectoras</strong> que puedas sostener y expandir post-residencia.</p>

<p><strong>Principio 80/20:</strong> Enfócate en el 20% intervenciones que proporcionan 80% beneficio - alta eficiencia, bajo tiempo/esfuerzo.</p>
</div>

<h3>🥗 Métrica 1: Calidad de la Dieta</h3>

<div class="metric-strategies">
<h4>Desafío Residente</h4>
<p>Tiempo limitado preparación comida, acceso opciones saludables hospital variable, fatiga → cravings comida chatarra, comidas irregulares/saltadas.</p>

<h4>Estrategias Realistas</h4>

<div class="strategy-card">
<h5>🔹 Meal Prep Simplificado (Domingos 2-3h)</h5>
<p><strong>Concepto:</strong> Preparar componentes base (no comidas completas complejas) que ensamblas rápidamente.</p>

<p><strong>Componentes preparar domingo:</strong></p>
<ul>
<li><strong>Proteína:</strong> 1-1.5 kg pollo/pavo/pescado horneado con especias → porcionar recipientes</li>
<li><strong>Granos:</strong> 3-4 tazas arroz integral/quinoa/farro cocidos</li>
<li><strong>Verduras asadas:</strong> Bandejas brócoli, coliflor, zanahorias, pimientos (aceite oliva + sal)</li>
<li><strong>Snacks:</strong> Bolsitas nueces/almendras (30g), frutas lavadas/cortadas, hummus porciones</li>
</ul>

<p><strong>Ensamblaje rápido:</strong> Proteína + grano + verduras = comida balanceada 5 minutos</p>

<p><strong>Tiempo:</strong> 2-3h domingo = 10-15 comidas saludables semana</p>

<p><strong>Almacenamiento:</strong> Refrigerador 3-4 días, congelador porciones 2-3 meses</p>
</div>

<div class="strategy-card">
<h5>🔹 Navegación Cafetería Hospital</h5>
<p><strong>Opciones mejores (usualmente disponibles):</strong></p>
<ul>
<li><strong>Desayuno:</strong> Avena (añadir fruta fresca, nueces propias) > cereales azucarados/donuts</li>
<li><strong>Almuerzo/Cena:</strong> Bar ensaladas (base verduras, proteína grilled, aderezo vinagreta lado) > opciones fritas</li>
<li><strong>Proteínas:</strong> Pollo/pescado grilled/horneado > frito/rebozado</li>
<li><strong>Acompañamientos:</strong> Verduras al vapor, ensalada > papas fritas, mac & cheese</li>
<li><strong>Bebidas:</strong> Agua, agua saborizada, té no azucarado > sodas, jugos</li>
</ul>

<p><strong>Regla práctica:</strong> "50% plato verduras, 25% proteína magra, 25% granos integrales"</p>
</div>

<div class="strategy-card">
<h5>🔹 Snacks Estratégicos Call Room/Bolsillo</h5>
<p><strong>Stock personal saludable (evita vending machines):</strong></p>
<ul>
<li>Nueces mixtas (almendras, nueces, pistachos) - porciones 30g</li>
<li>Barras proteína/granola (verificar <10g azúcar, >5g proteína)</li>
<li>Mantequilla maní individual packets + manzana/banana</li>
<li>Hummus individual + vegetales baby carrots</li>
<li>Yogurt griego individual (refrigerador call room)</li>
<li>Jerky (carne seca) bajo sodio</li>
</ul>

<p><strong>Evitar:</strong> Galletas, chips, candy bars, bebidas energéticas azucaradas</p>
</div>

<div class="strategy-card">
<h5>🔹 Hidratación Intencional</h5>
<ul>
<li>Botella agua reutilizable 1L (llenar 2-3× diario) - meta 2-3L</li>
<li>Agua + limón/lima/pepino si necesitas sabor</li>
<li>Café: Máximo 2-3 tazas/día (última dosis <6h pre-sleep intentado)</li>
<li>Evitar: Bebidas energéticas regulares (ocasional emergencia OK, no rutina)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Regla "No Saltear Comidas"</h5>
<p><strong>Incluso si ocupado:</strong></p>
<ul>
<li>Mínimo: 3 "puntos contacto" alimentación/día (puede ser snack sustancial si no comida completa)</li>
<li>Saltear comidas → hipoglucemia → cravings intensos → elecciones impulsivas no saludables</li>
<li>Si emergencia impide comida: Snack proteína (bar, nueces + fruta) mejor que nada</li>
</ul>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> 50-60 puntos dieta LE8™ (vs 100 óptimo)</li>
<li><strong>Traducción:</strong> 3-4 días/semana comida balanceada predominantemente, limitación alimentos ultra-procesados, hidratación adecuada</li>
<li><strong>Expansión post-residencia:</strong> Cocina más elaborada, mayor variedad, consistencia</li>
</ul>
</div>

<h3>🏃 Métrica 2: Actividad Física</h3>

<div class="metric-strategies">
<h4>Desafío Residente</h4>
<p>Jornadas largas eliminan tiempo gym tradicional, fatiga post-trabajo/guardia, sentimiento culpa "debería estudiar".</p>

<h4>Estrategias Realistas</h4>

<div class="strategy-card">
<h5>🔹 Micro-Ejercicios Integrados Jornada</h5>
<p><strong>Actividades incrementales (no requieren cambio ropa/ducha):</strong></p>
<ul>
<li><strong>Escaleras vs elevador:</strong> Siempre escaleras (si <5 pisos). 10 min escaleras/día = 70 min/semana actividad vigorosa</li>
<li><strong>Rondas caminando rápido:</strong> Paso enérgico entre pacientes (vs caminar lento)</li>
<li><strong>Llamadas caminando:</strong> Llamadas teléfono familia/amigos = caminata (15-20 min)</li>
<li><strong>Parking remoto:</strong> Estacionar lejos entrada (5-10 min caminata adicional ida/vuelta)</li>
<li><strong>Break activo:</strong> 5 min cada 2h - caminar piso, estiramientos, sentadillas</li>
</ul>

<p><strong>Acumulación:</strong> 5-10 min × 6-8 veces/día = 30-80 min actividad total</p>
</div>

<div class="strategy-card">
<h5>🔹 Entrenamientos Cortos Alta Intensidad (HIIT)</h5>
<p><strong>Eficiencia temporal - beneficio CV similar ejercicio continuo moderado con MENOS tiempo:</strong></p>

<p><strong>Protocolo 15-20 minutos:</strong></p>
<ul>
<li>Calentamiento: 3 min (jumping jacks, marcha lugar)</li>
<li>Intervalos: 30 seg máxima intensidad (burpees, mountain climbers, sprints lugar, jump squats) + 30 seg recuperación activa (marcha). Repetir 8-10 ciclos (8-10 min)</li>
<li>Enfriamiento: 3 min estiramientos</li>
</ul>

<p><strong>Frecuencia:</strong> 3×/semana suficiente beneficio CV significativo</p>

<p><strong>Ubicación:</strong> Call room, casa, parque - no requiere gym</p>

<p><strong>Apps guía:</strong> Nike Training Club (gratuita), Seven (7 min workouts), Freeletics</p>
</div>

<div class="strategy-card">
<h5>🔹 Rutina Mañana Pre-Hospital (20-30 min)</h5>
<p><strong>Ventaja:</strong> Ejercicio matutino = mayor adherencia (antes demandas día interfieran)</p>

<p><strong>Opciones:</strong></p>
<ul>
<li>Correr/trotar 20-30 min (2-3 km)</li>
<li>Ciclismo estacionario mientras revisa labs/estudios en tablet</li>
<li>Video yoga/Pilates YouTube (Yoga with Adriene - rutinas 20-30 min)</li>
<li>Rutina fuerza peso corporal (push-ups, squats, lunges, planks)</li>
</ul>

<p><strong>Preparación noche anterior:</strong> Ropa gym lista, alarma 30 min antes → reduce fricción</p>
</div>

<div class="strategy-card">
<h5>🔹 Gym Hospital (Si Disponible)</h5>
<p>Muchos hospitales tienen gym empleados (frecuentemente subutilizado)</p>
<ul>
<li><strong>Ventaja:</strong> Cercanía (5 min desplazamiento), bajo/sin costo</li>
<li><strong>Timing:</strong> Pre-shift (6-7am), lunch break (30 min), post-shift inmediato (antes ir casa = sin excusas)</li>
<li><strong>Rutina eficiente:</strong> 30-40 min circuito (fuerza + cardio)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Ejercicio Social</h5>
<ul>
<li>Organizar co-residentes: Running group, clases grupales, basketball/soccer</li>
<li>Ventaja dual: Ejercicio + conexión social (combate aislamiento)</li>
<li>Accountability mutuo (más difícil cancelar si otros dependen)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Adaptación Post-Guardia</h5>
<p><strong>Realidad:</strong> Post-guardia 24h = agotamiento extremo</p>
<ul>
<li><strong>No forzar:</strong> Ejercicio vigoroso post-guardia sin dormir = contraproducente, riesgo lesión</li>
<li><strong>Alternativa:</strong> Caminata suave 15-20 min (ayuda transición sueño, exposición luz natural), O siesta primero → ejercicio ligero después si recuperado</li>
<li><strong>Compensación:</strong> Días no-guardia = prioridad ejercicio</li>
</ul>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> 90-120 min actividad moderada/semana (vs 150 óptimo) = 60-80 puntos LE8™</li>
<li><strong>Traducción:</strong> 3-4 sesiones 20-30 min + actividad incremental diaria</li>
<li><strong>Mantenimiento:</strong> ALGO > NADA. Semana mala (0-60 min) > semana sedentaria completa</li>
</ul>
</div>

<h3>🚭 Métrica 3: Exposición a Nicotina</h3>

<div class="metric-strategies">
<h4>Contexto Residente</h4>
<p>Prevalencia tabaquismo residentes (<5%) menor que población general (~14%), PERO:</p>
<ul>
<li>Estrés residencia puede → iniciar/reiniciar tabaco en susceptibles</li>
<li>Exposición segunda mano ocasional (pacientes, áreas fumadores externas hospital)</li>
<li>Vaping emergente (~8-10% residentes jóvenes)</li>
</ul>

<h4>Estrategias</h4>

<div class="strategy-card">
<h5>🔹 Si No Fumador: Mantener Abstinencia Total</h5>
<ul>
<li><strong>Evitar "cigarrillo ocasional estrés"</strong> - NO existe uso ocasional seguro</li>
<li>Alternativas manejo estrés: Caminata, respiración profunda, llamar amigo, ejercicio</li>
<li>Si exposición segunda mano laboral: Minimizar (evitar áreas fumadores)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Si Fumador Actual: Cesación Prioritaria</h5>
<p>Residencia es momento desafiante pero CRÍTICO cesar - beneficios inmediatos y largo plazo</p>
<ul>
<li><strong>Apoyo farmacológico:</strong> NRT (parches, goma nicotina), varenicline, bupropion - considerar consultar medicina adicción institucional</li>
<li><strong>Terapia conductual:</strong> Apps (QuitGuide CDC, Smoke Free), líneas quitline gratuitas</li>
<li><strong>Fecha cesación:</strong> Establecer día específico, informar co-residentes (apoyo social)</li>
<li><strong>Identificar triggers:</strong> Post-guardia, break, estrés caso difícil → plan alternativas</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Vaping: NO es Alternativa Segura</h5>
<ul>
<li>EVAPI (lesión pulmonar asociada vaping) - casos severos descritos</li>
<li>Contenido nicotina frecuentemente ALTO (Juul 1 pod = 20 cigarrillos)</li>
<li>Efectos CV largo plazo aún investigándose pero evidencia preliminar preocupante</li>
<li>Si usas vaping: Mismo consejo que tabaco - cesar completamente</li>
</ul>
</div>

<h4>Meta Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> 100 puntos LE8™ - abstinencia completa nicotina</li>
<li><strong>Si fumador:</strong> Iniciar proceso cesación durante residencia (puede requerir múltiples intentos - persistir)</li>
</ul>
</div>

<h3>💤 Métrica 4: Duración del Sueño</h3>

<div class="metric-strategies">
<h4>Desafío Residente - EL MÁS DIFÍCIL</h4>
<p>78% residentes reportan sueño insuficiente crónico (<6h promedio). Guardias 24h, días largos, estudio nocturno → privación inevitable parcialmente.</p>

<h4>Estrategias Realistas (Minimizar Daño)</h4>

<div class="strategy-card">
<h5>🔹 Priorización Radical Sueño Días No-Guardia</h5>
<p><strong>Filosofía:</strong> "Recuperar" déficit guardia en días previos/posteriores</p>

<ul>
<li><strong>Meta:</strong> 7-8h sueño días no-guardia (NO negociable)</li>
<li><strong>Bedtime protegido:</strong> Si necesitas despertar 6am → cama 10-10:30pm (incluir 30 min dormirse)</li>
<li><strong>Estudio:</strong> Completar antes bedtime o despertar temprano (vs trasnochar)</li>
<li><strong>Socialización:</strong> Limitar eventos nocturnos días pre-guardia</li>
</ul>

<p><strong>Evidencia:</strong> Sueño 7-8h días no-guardia mitiga parcialmente efectos adversos CV privación guardia</p>
</div>

<div class="strategy-card">
<h5>🔹 Siestas Estratégicas Guardia</h5>
<ul>
<li><strong>Timing:</strong> Siesta 20-30 min (siesta "power nap") si oportunidad 2-4am (nadir circadiano)</li>
<li><strong>Beneficio:</strong> Mejora vigilancia 34%, reduce errores, ↓ PA post-guardia</li>
<li><strong>Set alarm:</strong> 30 min máximo (evita inercia sueño profundo)</li>
<li><strong>No culpa:</strong> Siesta guardia = intervención seguridad paciente</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Higiene Sueño Rigurosa</h5>
<p><strong>Especialmente importante cuando sueño limitado - optimizar calidad:</strong></p>

<ul>
<li><strong>Ambiente:</strong> Cuarto oscuro (blackout curtains si turnos nocturnos), fresco (18-20°C), silencioso (earplugs, white noise machine si necesario)</li>
<li><strong>Pre-sleep ritual:</strong> 30-60 min wind-down (luz tenue, lectura, stretching suave), NO screens última hora</li>
<li><strong>Evitar:</strong> Cafeína post-2pm (vida media 5-6h), alcohol como "sleep aid" (fragmenta sueño segunda mitad noche)</li>
<li><strong>Consistencia:</strong> Misma hora acostarse/despertar (incluso fines semana) máximo posible</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Manejo Post-Guardia</h5>
<p><strong>Opciones recuperación:</strong></p>

<p><strong>Opción A - Siesta corta + sueño nocturno normal:</strong></p>
<ul>
<li>Llegar casa post-guardia → siesta 2-3h (NO más - despertador)</li>
<li>Despertar tarde tarde/tarde (1-3pm)</li>
<li>Mantenerse despierto resto día (exposición luz natural, actividad ligera)</li>
<li>Dormir noche normal (10-11pm)</li>
<li><strong>Ventaja:</strong> Re-sincroniza ritmo circadiano rápido</li>
</ul>

<p><strong>Opción B - Sueño largo inmediato:</strong></p>
<ul>
<li>Llegar casa → dormir inmediatamente 6-8h</li>
<li>Despertar tarde (3-5pm)</li>
<li>Riesgo: Dificultad dormir noche siguiente, perpetúa desincronización</li>
<li><strong>Usar si:</strong> Fatiga extrema, múltiples guardias próximas</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Cafeína Táctica (No Exceso)</h5>
<ul>
<li><strong>Uso estratégico:</strong> 200 mg cafeína (2 cafés) mejora vigilancia 3-4h guardia</li>
<li><strong>Timing:</strong> Consumir cuando necesites estar alerta (ej. 2-4am nadir), NO automático todo el día</li>
<li><strong>Límite:</strong> <400 mg/día total (equiv. 4 cafés)</li>
<li><strong>Cutoff:</strong> Última dosis ≥6h antes dormir intentado</li>
<li><strong>Evitar:</strong> Bebidas energéticas alto azúcar (crash post-pico)</li>
</ul>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> 50-60 puntos LE8™ (vs 100 óptimo)</li>
<li><strong>Traducción:</strong> Promedio 6-6.5h/noche (incluyendo guardias), con 7-8h días no-guardia</li>
<li><strong>Aceptación:</strong> Durante residencia, sueño SERÁ subóptimo - enfoque minimizar daño</li>
<li><strong>Promesa post-residencia:</strong> Priorizar recuperación déficit crónico (puede tomar 6-12 meses normalizar patrones)</li>
</ul>
</div>

<h3>⚖️ Métrica 5: IMC (Índice Masa Corporal)</h3>

<div class="metric-strategies">
<h4>Desafío Residente</h4>
<p>Ganancia peso común residencia (promedio 2-5 kg durante 3 años) - causas multifactoriales: sedentarismo, dieta subóptima, privación sueño (↑ ghrelin, ↓ leptina), estrés (↑ cortisol).</p>

<h4>Estrategias Realistas</h4>

<div class="strategy-card">
<h5>🔹 Meta Mantenimiento (No Pérdida Activa)</h5>
<p><strong>Filosofía:</strong> Durante residencia, objetivo es <strong>prevenir ganancia</strong>, NO necesariamente perder peso activamente (salvo sobrepeso/obesidad establecidos pre-residencia)</p>

<ul>
<li><strong>Monitoreo:</strong> Pesarse semanalmente (misma balanza, misma hora, ej. domingo mañana)</li>
<li><strong>Rango aceptable:</strong> ±2 kg peso inicial residencia</li>
<li><strong>Alarma:</strong> Ganancia >3 kg sostenida → intensificar dieta/ejercicio</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Si Sobrepeso/Obesidad Pre-Residencia</h5>
<p><strong>Meta realista:</strong> Pérdida gradual 0.25-0.5 kg/semana (vs 0.5-1 kg población general) - más lento pero sostenible</p>

<p><strong>Déficit calórico moderado:</strong> 250-500 kcal/día (vs 500-750 estándar)</p>

<ul>
<li>Combinación: Dieta (-300 kcal) + Ejercicio (-200 kcal) = -500 kcal total</li>
<li>Evitar déficits agresivos (>750 kcal) - no sostenibles con demandas residencia</li>
</ul>

<p><strong>Enfoque:</strong> Estrategias dieta (meal prep, cafetería navegación) + ejercicio (micro-ejercicios, HIIT) descritas arriba</p>
</div>

<div class="strategy-card">
<h5>🔹 Prevención "Comfort Eating"</h5>
<p><strong>Patrón común:</strong> Estrés/fatiga → cravings comida alta calórico/azúcares (dopamina ↑ temporal)</p>

<p><strong>Estrategias:</strong></p>
<ul>
<li><strong>Identificar triggers:</strong> Post-caso difícil, post-guardia, feedback negativo</li>
<li><strong>Alternativas no-alimentarias:</strong> Llamar amigo/familia, caminata corta, música, ducha, breathing exercises</li>
<li><strong>Permitir ocasional:</strong> Regla 80/20 - 80% comida saludable, 20% "disfrutar" (previene sentimiento privación)</li>
<li><strong>Snacks plan B:</strong> Si craving inevitable, opción "menos mala" disponible (dark chocolate 1-2 cuadros vs caja entera donuts)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Evitar "Dietas" Extremas</h5>
<ul>
<li>Keto, ayuno prolongado, dietas muy bajas calorías - NO sostenibles residencia</li>
<li>Riesgo rebound weight gain, pérdida masa muscular, fatiga extrema</li>
<li>Enfoque: Cambios moderados sostenibles largo plazo</li>
</ul>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Si IMC normal (18.5-24.9) inicio residencia:</strong> Mantener (±2 kg) = 100 puntos LE8™</li>
<li><strong>Si sobrepeso (25-29.9):</strong> Mantener O pérdida gradual → 80-99 puntos</li>
<li><strong>Si obesidad (≥30):</strong> Pérdida 5-10% peso (mejoras metabólicas significativas incluso sin "normalizar" IMC) → 50-79 puntos</li>
</ul>
</div>

<h3>🩸 Métrica 6: Colesterol (Lípidos)</h3>

<div class="metric-strategies">
<h4>Contexto Residente</h4>
<p>Dislipidemia prevalencia 30-40% residentes (mayoría límite alto, no severamente elevado). Factores: Dieta subóptima, sedentarismo, estrés crónico, predisposición genética.</p>

<h4>Estrategias</h4>

<div class="strategy-card">
<h5>🔹 Screening Apropiado</h5>
<ul>
<li><strong>Frecuencia:</strong> Perfil lipídico completo (colesterol total, LDL-C, HDL-C, triglicéridos) cada 4-6 años si normal, anual si límite/alto</li>
<li><strong>Aprovechar:</strong> Ferias salud institucionales, screening empleados (frecuentemente gratuitos)</li>
<li><strong>No auto-prescripción:</strong> Consultar PCP (Primary Care Physician) para interpretación/manejo</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Intervención Estilo Vida Primera Línea</h5>
<p><strong>Si colesterol elevado sin indicación inmediata estatina (ej. LDL 130-159, sin ASCVD/diabetes):</strong></p>

<ul>
<li><strong>Dieta Portfolio:</strong> Enfoque fibra soluble (avena, psyllium), esteroles vegetales (margarinas fortificadas), proteína soja, nueces - puede ↓ LDL 20-30%</li>
<li><strong>↓ Grasas saturadas:</strong> <7% calorías (limitar carnes rojas, lácteos enteros, aceite coco/palma)</li>
<li><strong>Eliminar grasas trans:</strong> Comidas fritas, productos horneados comerciales</li>
<li><strong>Ejercicio aeróbico:</strong> ↑ HDL-C 5-10%, ↓ triglicéridos 20-30%</li>
<li><strong>Pérdida peso:</strong> Si sobrepeso, 5-10% peso → ↓ LDL 5-8%</li>
</ul>

<p><strong>Re-evaluar:</strong> 3-6 meses post-cambios estilo vida</p>
</div>

<div class="strategy-card">
<h5>🔹 Farmacoterapia Si Indicada</h5>
<p><strong>Indicaciones estatina incluso jóvenes residentes:</strong></p>
<ul>
<li>LDL ≥190 mg/dL (hipercolesterolemia familiar probable)</li>
<li>Diabetes + edad >40 (O <40 si otros factores riesgo)</li>
<li>Riesgo ASCVD 10 años ≥7.5% (raro residentes jóvenes salvo múltiples factores riesgo)</li>
<li>Historia familiar ASCVD prematura + LDL persistentemente ≥160</li>
</ul>

<p><strong>Estatinas:</strong> Considerar si indicación clara - beneficio CV >> efectos adversos (mialgias <10%, generalmente tolerables)</p>

<p><strong>Adherencia:</strong> Establecer rutina (ej. bedtime diario), apps recordatorio</p>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> No-HDL <130 mg/dL (LDL <100 mg/dL) = 100 puntos LE8™</li>
<li><strong>Si límite alto:</strong> Intervención estilo vida agresiva 3-6 meses antes considerar estatina (salvo indicaciones absolutas)</li>
<li><strong>Monitoreo:</strong> No ignorar - "soy joven" NO es escudo (aterosclerosis inicia temprano)</li>
</ul>
</div>

<h3>📊 Métrica 7: Glucosa (Hemoglobina Glucosilada)</h3>

<div class="metric-strategies">
<h4>Contexto Residente</h4>
<p>Prediabetes prevalencia 10-15% residentes (frecuentemente no diagnosticada). Factores riesgo: Sobrepeso/obesidad, sedentarismo, dieta alta carbohidratos refinados, privación sueño (↑ resistencia insulina), estrés crónico.</p>

<h4>Estrategias</h4>

<div class="strategy-card">
<h5>🔹 Screening Apropiado</h5>
<ul>
<li><strong>Indicaciones screening:</strong> IMC ≥25 (≥23 asiáticos) + ≥1 factor riesgo adicional (sedentarismo, historia familiar diabetes, hipertensión, dislipidemia)</li>
<li><strong>Prueba:</strong> HbA1c (no requiere ayuno - conveniente residentes) O glucosa ayunas</li>
<li><strong>Frecuencia:</strong> Cada 3 años si normal, anual si prediabetes</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Prevención Prediabetes/Diabetes</h5>
<p><strong>Diabetes Prevention Program adaptado residentes:</strong></p>

<p><strong>Si prediabetes (HbA1c 5.7-6.4%):</strong></p>
<ul>
<li><strong>Pérdida peso:</strong> 5-7% peso corporal (ej. 5 kg si pesas 70 kg) - evidencia clase A reduce progresión diabetes 58%</li>
<li><strong>Ejercicio:</strong> 150 min/semana moderado (DPP protocolo) - puede ser desafiante residencia, meta mínima 90-120 min</li>
<li><strong>Dieta bajo índice glucémico:</strong> ↓ Carbohidratos refinados (pan blanco, dulces, sodas), ↑ granos integrales, verduras, proteína, fibra</li>
<li><strong>Metformina:</strong> Considerar si IMC ≥35, <60 años, historia diabetes gestacional - reduce progresión 31% (discutir PCP)</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Manejo Estrés/Sueño → Glucosa</h5>
<ul>
<li>Privación sueño aguda (1 noche) → ↓ sensibilidad insulina 30-40% (reversible con recuperación)</li>
<li>Estrés crónico → ↑ cortisol → hiperglucemia, resistencia insulina</li>
<li><strong>Implicación:</strong> Priorizar sueño/manejo estrés NO solo "bienestar" sino prevención metabólica concreta</li>
</ul>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> HbA1c <5.7% = 100 puntos LE8™</li>
<li><strong>Si prediabetes:</strong> Intervención estilo vida intensiva - posible revertir (40-50% regresan normoglucemia DPP)</li>
<li><strong>Monitoreo:</strong> No asumir "no me pasará" - prevención temprana crítica</li>
</ul>
</div>

<h3>🩺 Métrica 8: Presión Arterial</h3>

<div class="metric-strategies">
<h4>Contexto Residente</h4>
<p>Hipertensión/prehipertensión prevalencia 20-25% residentes. Factores: Exceso sodio (comida hospital), sobrepeso, sedentarismo, estrés, privación sueño, ocasional genética.</p>

<h4>Estrategias</h4>

<div class="strategy-card">
<h5>🔹 Monitoreo Regular</h5>
<ul>
<li><strong>Frecuencia:</strong> Anual mínimo si normal, cada 3-6 meses si elevada/estadio 1</li>
<li><strong>Técnica correcta:</strong> Reposo 5 min, manguito apropiado, brazo nivel corazón, promedio 2-3 mediciones</li>
<li><strong>Monitoreo domiciliario:</strong> Considerar si PA límite consultorio (descartar bata blanca) - dispositivo validado <$50</li>
<li><strong>Evitar auto-diagnóstico:</strong> PA elevada ocasional (estrés agudo, post-cafeína) NO = hipertensión. Requiere confirmación múltiples visitas/MAPA</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Modificaciones Estilo Vida - PA</h5>
<p><strong>Efectivas incluso PA normal-alta (prevención progresión):</strong></p>

<ul>
<li><strong>Reducción sodio:</strong> <2,300 mg/día (ideal <1,500 mg/día) - ↓ PA 5-6 mmHg promedio
  <ul>
    <li>Evitar comidas alta sodio cafetería (sopas, sandwiches, pizzas)</li>
    <li>No añadir sal alimentos</li>
    <li>Leer etiquetas, elegir opciones bajas sodio</li>
  </ul>
</li>
<li><strong>Dieta DASH:</strong> ↑ Frutas, verduras, lácteos bajos grasa, ↓ grasas saturadas - ↓ PA 8-14 mmHg</li>
<li><strong>Pérdida peso:</strong> Cada kg pérdida → ~1 mmHg ↓ PA</li>
<li><strong>Ejercicio:</strong> 150 min/semana aeróbico → ↓ PA 5-8 mmHg</li>
<li><strong>Alcohol moderación:</strong> ≤2 bebidas/día hombres, ≤1 mujeres (exceso ↑ PA)</li>
<li><strong>Manejo estrés:</strong> Meditación, yoga, ejercicio - ↓ PA 4-5 mmHg</li>
</ul>
</div>

<div class="strategy-card">
<h5>🔹 Farmacoterapia Si Necesaria</h5>
<p><strong>Indicaciones tratamiento jóvenes:</strong></p>
<ul>
<li>PA ≥140/90 mmHg sostenida (confirmada múltiples visitas/MAPA)</li>
<li>PA ≥130/80 + riesgo CV alto (diabetes, ERC, ASCVD, riesgo 10 años ≥10%)</li>
<li>Daño órgano blanco (HVI, proteinuria, retinopatía)</li>
</ul>

<p><strong>Primera línea:</strong> IECA, ARA-II, tiazida, CCB - elección según perfil individual (discutir PCP/cardiólogo)</p>

<p><strong>Adherencia:</strong> Dosis única diaria preferible, apps recordatorio, monitoreo PA domiciliario feedback</p>
</div>

<h4>Meta Realista Residencia</h4>
<ul>
<li><strong>Objetivo:</strong> PA <120/80 mmHg = 100 puntos LE8™</li>
<li><strong>Si elevada (120-129/<80):</strong> Intervención estilo vida agresiva 3-6 meses</li>
<li><strong>Si estadio 1 (130-139/80-89):</strong> Estilo vida + considerar farmacoterapia según riesgo global</li>
<li><strong>Monitoreo:</strong> No normalizar HTA joven - requiere intervención</li>
</ul>
</div>

