                        <h3>Is lethargy related to chronic fatigue syndrome?</h3>
                          <p>Yes, lethargy is a common symptom of chronic fatigue syndrome. People with chronic fatigue syndrome often experience extreme tiredness or fatigue that is not relieved by rest.</p>





