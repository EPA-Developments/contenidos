            <h3>What is the reason for poor blood circulation?</h3>
              <p>Poor blood circulation can be caused by conditions like peripheral artery disease, diabetes, obesity, smoking, and a sedentary lifestyle.</p>





              <h3>How to test for circulation?</h3>
