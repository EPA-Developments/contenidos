<li>Applying a cold compress to the chest or arm to reduce inflammation and numb the pain</li>
<li>Practicing relaxation techniques such as meditation or yoga to reduce stress and tension in the body</li>
<li>Avoiding activities that may worsen the symptoms, such as strenuous exercise or heavy lifting</li>
</ul>
<p>It is important to note that home remedies should not delay or replace seeking medical evaluation for crushing chest pain spreading to the arm, especially if the symptoms are severe or concerning.</p>
